def translate_text(text: str, language: str) -> str:
    if language != "ar":
        return text
    if text in AR_TRANSLATIONS:
        return AR_TRANSLATIONS[text]
    for source in sorted(AR_TRANSLATIONS, key=len, reverse=True):
        if source in {"File", "URL"}:
            continue
        text = text.replace(source, AR_TRANSLATIONS[source])
    return text


def shape_arabic_text(text: str) -> str:
    if not any("\u0600" <= character <= "\u06FF" for character in text):
        return text
    return get_display(arabic_reshaper.reshape(text))

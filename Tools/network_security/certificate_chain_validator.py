def _load_bundle(x509, data):
    """Load a CA bundle one certificate at a time, skipping any the library rejects (e.g. non-positive serials)."""
    import warnings

    roots = []
    for block in data.split(b"-----END CERTIFICATE-----"):
        if b"-----BEGIN CERTIFICATE-----" not in block:
            continue
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            try:
                roots.append(x509.load_pem_x509_certificate(block + b"-----END CERTIFICATE-----\n"))
            except ValueError:
                continue
    return roots


def _name(cert):
    try:
        return cert.subject.rfc4514_string()[:200]
    except Exception:  # noqa: BLE001
        return "(unparseable subject)"


def _analyze(ctx, data):
    try:
        from cryptography import x509
        from cryptography.hazmat.primitives import hashes
        from cryptography.hazmat.primitives.asymmetric import dsa, ec, rsa
        from cryptography.x509 import verification
    except ImportError as exc:
        raise Unavailable("cryptography>=42 is required for chain validation.") from exc

    if data.get("pem_chain"):
        ctx.input_kind = "pem"
        ctx.execution_mode = "local"
        try:
            chain = x509.load_pem_x509_certificates(data["pem_chain"].encode())
        except ValueError as exc:
            raise ToolInputError("pem_chain contains no parseable PEM certificates.") from exc
    elif data.get("host"):
        ctx.input_kind = "tls-handshake"
        port = int(data.get("port") or 443)
        if not 1 <= port <= 65535:
            raise ToolInputError("port must be 1-65535.")
        try:
            ders = httputil.fetch_tls_chain(data["host"], port, min(10.0, ctx.deadline.remaining()))
        except (OSError, ssl.SSLError) as exc:
            raise Unavailable(f"TLS handshake with {data['host']}:{port} failed ({type(exc).__name__}).") from exc
        chain = [x509.load_der_x509_certificate(d) for d in ders if d]
        if len(chain) == 1:
            ctx.limit("This Python runtime returned only the leaf certificate; intermediate checks need Python 3.13+ or pem_chain.")
    else:
        raise ToolInputError("Provide pem_chain, or host (and optionally port) for a live handshake.")
    if not chain:
        raise ToolInputError("No certificates found.")
    hostname = (data.get("hostname") or data.get("host") or "").strip().lower() or None
    now = dt.datetime.fromtimestamp(data["now"], dt.timezone.utc) if data.get("now") else dt.datetime.now(dt.timezone.utc)
    warn_days = int(data.get("expiry_warning_days") or 30)
    leaf = chain[0]
    ctx.artifacts["chain"] = [{"subject": _name(c), "issuer": c.issuer.rfc4514_string()[:200],
                               "not_after": c.not_valid_after_utc.isoformat(), "serial": format(c.serial_number, "x")[:64],
                               "sha256": c.fingerprint(hashes.SHA256()).hex()} for c in chain[:10]]

    for index, cert in enumerate(chain):
        where = f"certificate {index} ({_name(cert)})"
        if cert.not_valid_after_utc < now:
            ctx.finding(f"cert.expired.{index}", "Certificate has expired", "high",
                        f"{where} expired on {cert.not_valid_after_utc:%Y-%m-%d}.", assurance="verified_condition", location=where)
        elif cert.not_valid_after_utc - now < dt.timedelta(days=warn_days):
            days = (cert.not_valid_after_utc - now).days
            ctx.finding(f"cert.expiring.{index}", f"Certificate expires in {days} day(s)", "medium",
                        f"{where} expires on {cert.not_valid_after_utc:%Y-%m-%d}.", assurance="verified_condition", location=where)
        if cert.not_valid_before_utc > now:
            ctx.finding(f"cert.not-yet-valid.{index}", "Certificate is not yet valid", "high",
                        f"{where} becomes valid on {cert.not_valid_before_utc:%Y-%m-%d}.", assurance="verified_condition", location=where)
        algorithm = cert.signature_hash_algorithm
        if index < len(chain) - 1 or cert.issuer != cert.subject:  # self-signed roots' own signatures do not matter
            if algorithm is not None and algorithm.name in ("sha1", "md5"):
                ctx.finding(f"cert.weak-signature.{index}", f"Signed with {algorithm.name.upper()}", "high",
                            f"{where} uses a collision-prone signature hash; browsers reject it.", assurance="verified_condition", location=where)
        key = cert.public_key()
        if isinstance(key, rsa.RSAPublicKey) and key.key_size < 2048:
            ctx.finding(f"cert.weak-rsa.{index}", f"RSA key is only {key.key_size} bits", "high",
                        f"{where} has an RSA key below 2048 bits.", assurance="verified_condition", location=where)
        elif isinstance(key, ec.EllipticCurvePublicKey) and key.curve.key_size < 256:
            ctx.finding(f"cert.weak-ec.{index}", f"EC key on {key.curve.name}", "medium",
                        f"{where} uses a curve below 256 bits.", assurance="verified_condition", location=where)
        elif isinstance(key, dsa.DSAPublicKey):
            ctx.finding(f"cert.dsa.{index}", "DSA key", "medium", f"{where} uses DSA, which TLS clients no longer accept.",
                        assurance="verified_condition", location=where)
        if index > 0:
            try:
                constraints = cert.extensions.get_extension_for_class(x509.BasicConstraints).value
                is_ca = constraints.ca
            except x509.ExtensionNotFound:
                is_ca = False
            if not is_ca:
                ctx.finding(f"cert.issuer-not-ca.{index}", "Issuing certificate is not a CA", "high",
                            f"{where} signs another certificate but lacks basicConstraints CA:TRUE.", assurance="verified_condition", location=where)
            child = chain[index - 1]
            try:
                child.verify_directly_issued_by(cert)
            except (ValueError, TypeError, Exception) as exc:  # noqa: BLE001 - InvalidSignature or name mismatch
                ctx.finding(f"chain.broken-link.{index}", "Chain is out of order or a signature does not verify", "high",
                            f"Certificate {index - 1} was not issued by certificate {index} ({type(exc).__name__}).",
                            assurance="verified_condition", location=where,
                            recommendation="Serve leaf first, then each issuer in order.")

    if leaf.issuer == leaf.subject and len(chain) == 1:
        ctx.finding("cert.self-signed", "Self-signed leaf certificate", "high",
                    "The server presents a self-signed certificate; clients cannot authenticate it without pinning.",
                    assurance="verified_condition", location="certificate 0")

    try:
        if data.get("trusted_roots_pem"):
            roots = x509.load_pem_x509_certificates(data["trusted_roots_pem"].encode())
            store_label = "supplied roots"
        else:
            import certifi

            roots = _load_bundle(x509, Path(certifi.where()).read_bytes())
            store_label = "Mozilla trust store (certifi)"
        store = verification.Store(roots)
        builder = verification.PolicyBuilder().store(store).time(now)
        if hostname:
            verifier = builder.build_server_verifier(x509.DNSName(hostname))
            built = verifier.verify(leaf, chain[1:])
        else:
            verifier = builder.build_client_verifier()
            built = verifier.verify(leaf, chain[1:]).chain
            ctx.limit("No hostname was given: the chain was validated without a host-name check.")
        ctx.artifacts["trusted_path"] = [_name(c) for c in built]
        ctx.artifacts["trust_store"] = store_label
    except ImportError:
        ctx.limit("certifi is not installed and no trusted_roots_pem was given: trust was not evaluated.", partial=True)
    except verification.VerificationError as exc:
        message = re.sub(r"\s*\(encountered processing .*$", "", str(exc), flags=re.S)[:400]
        lowered = message.lower()
        if hostname and re.search(r"subjectaltname|no matching|hostname|dns ?name|does not match", lowered):
            fid, title = "chain.hostname-mismatch", f"Certificate does not match {hostname}"
        elif "missing required extension" in lowered or "invalid extension" in lowered:
            fid, title = "chain.profile-violation", "Certificate violates the RFC 5280 / CA-Browser Forum profile"
        else:
            fid, title = "chain.untrusted", "Chain does not validate to a trusted root"
        ctx.finding(fid, title, "high", f"Path validation failed: {message}", assurance="verified_condition", location="chain")



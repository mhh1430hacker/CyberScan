DEPRECATED_ALGORITHMS = {1: "RSAMD5", 3: "DSA", 5: "RSASHA1", 6: "DSA-NSEC3-SHA1", 7: "RSASHA1-NSEC3-SHA1", 12: "ECC-GOST"}
ALGORITHM_NAMES = {8: "RSASHA256", 10: "RSASHA512", 13: "ECDSAP256SHA256", 14: "ECDSAP384SHA384", 15: "ED25519", 16: "ED448",
                   **DEPRECATED_ALGORITHMS}


def _from_zone_text(zone_name, text):
    import dns.exception
    import dns.rdatatype
    import dns.zone

    try:
        zone = dns.zone.from_text(text, origin=zone_name, relativize=False, check_origin=False)
    except (dns.exception.DNSException, ValueError) as exc:
        raise ToolInputError(f"zone_text could not be parsed ({type(exc).__name__}).") from exc
    rrsets, sigs = {}, {}
    for name, node in zone.nodes.items():
        for rdataset in node.rdatasets:
            if rdataset.rdtype == dns.rdatatype.RRSIG:
                sigs[(name, rdataset.covers)] = rdataset
            else:
                rrsets[(name, rdataset.rdtype)] = rdataset
    return rrsets, sigs


def _analyze(ctx, data):
    try:
        import dns.dnssec
        import dns.name
        import dns.rdata
        import dns.rdataclass
        import dns.rdatatype
        import dns.rrset
    except ImportError as exc:
        raise Unavailable("dnspython with cryptography is required for DNSSEC validation.") from exc
    zone_label = normalize_domain(data["zone"])
    zone = dns.name.from_text(zone_label)
    now = float(data.get("now") or time.time())
    ctx.artifacts["zone"] = zone_label
    failed = set()

    if data.get("zone_text"):
        ctx.input_kind = "zone-text"
        rrsets, sigs = _from_zone_text(zone, data["zone_text"])
    elif data.get("resolve"):
        ctx.input_kind = "live-dns"
        rrsets, sigs = {}, {}
        for rtype in ("DNSKEY", "SOA"):
            ctx.check()
            try:
                rrset, sig = dnsutil.fetch_rrsets(zone_label, rtype, nameserver=data.get("nameserver"), timeout=min(5.0, ctx.deadline.remaining()))
            except Exception as exc:  # noqa: BLE001 - any resolver failure makes this check incomplete
                ctx.limit(f"Live query for {rtype} failed ({type(exc).__name__}).", partial=True)
                failed.add(rtype)
                continue
            if rrset is not None:
                rrsets[(zone, rrset.rdtype)] = rrset
            if sig is not None:
                sigs[(zone, dns.rdatatype.from_text(rtype))] = sig
    else:
        raise ToolInputError("Provide zone_text (presentation format) or set resolve=true.")

    keyset = rrsets.get((zone, dns.rdatatype.DNSKEY))
    if keyset is None and "DNSKEY" in failed:
        ctx.summary = "The DNSKEY lookup failed, so whether the zone is signed is unknown."
        return
    if keyset is None:
        ctx.finding("dnssec.unsigned", "No DNSKEY records: the zone is not signed", "medium",
                    "Resolvers cannot authenticate answers for this zone; forged responses go undetected.",
                    assurance="verified_condition", location=zone_label,
                    recommendation="Sign the zone and publish a DS record at the parent.")
        return
    keys = list(keyset)
    ctx.artifacts["keys"] = [{"key_tag": dns.dnssec.key_id(k), "algorithm": ALGORITHM_NAMES.get(int(k.algorithm), str(int(k.algorithm))),
                              "flags": k.flags, "sep": bool(k.flags & 1)} for k in keys]
    for key in keys:
        algorithm = int(key.algorithm)
        tag = dns.dnssec.key_id(key)
        if algorithm in DEPRECATED_ALGORITHMS:
            ctx.finding(f"dnssec.weak-algorithm.{tag}", f"Key {tag} uses deprecated {DEPRECATED_ALGORITHMS[algorithm]}", "medium",
                        "RFC 8624 says this algorithm must not be used for signing; validators may treat the zone as insecure.",
                        assurance="verified_condition", location=f"DNSKEY {tag}", recommendation="Roll to ECDSAP256SHA256 (13) or ED25519 (15).")
        if algorithm in (5, 7, 8, 10):
            bits = _rsa_bits(key.key)
            is_zsk = (key.flags & 1) == 0
            if bits and bits < 2048 and not (is_zsk and bits >= 1024):  # 1024-bit ZSKs are still common practice
                ctx.finding(f"dnssec.short-rsa.{tag}", f"Key {tag} is RSA-{bits}", "low",
                            "RSA keys below 2048 bits are considered weak for key-signing keys.",
                            assurance="verified_condition", location=f"DNSKEY {tag}")

    validated_types = []
    for (owner, rdtype), rrset in rrsets.items():
        ctx.check()
        sig = sigs.get((owner, rdtype))
        type_name = dns.rdatatype.to_text(rdtype)
        if rdtype in (dns.rdatatype.NSEC, dns.rdatatype.NSEC3) and sig is None:
            continue
        if sig is None:
            if owner == zone and rdtype in (dns.rdatatype.DNSKEY, dns.rdatatype.SOA):
                ctx.finding(f"dnssec.unsigned-rrset.{type_name}", f"{type_name} RRset has no signature", "high",
                            f"The zone publishes keys but {owner} {type_name} carries no RRSIG, so validating resolvers return SERVFAIL.",
                            assurance="verified_condition", location=f"{owner} {type_name}")
            continue
        named = dns.rrset.from_rdata_list(owner, rrset.ttl, list(rrset))
        named_sig = dns.rrset.from_rdata_list(owner, sig.ttl, list(sig))
        try:
            dns.dnssec.validate(named, named_sig, {zone: keyset}, now=now)
            validated_types.append(type_name)
        except dns.dnssec.ValidationFailure as exc:
            ctx.finding(f"dnssec.bogus.{type_name}", f"{type_name} signature does not validate", "high",
                        f"No RRSIG over {owner} {type_name} verifies with the zone's keys ({exc}). Validating resolvers will reject these answers.",
                        assurance="verified_condition", location=f"{owner} {type_name}")
        for rrsig in sig:
            remaining = rrsig.expiration - now
            if 0 < remaining < 7 * 86400:
                ctx.finding(f"dnssec.expiring.{type_name}", f"{type_name} signature expires in {remaining / 86400:.1f} days", "medium",
                            "If the zone is not re-signed before expiry, validation fails for everyone.",
                            assurance="verified_condition", location=f"{owner} {type_name}")
            elif remaining <= 0:
                ctx.finding(f"dnssec.expired.{type_name}", f"{type_name} signature has expired", "high",
                            "An expired RRSIG makes answers bogus for validating resolvers.",
                            assurance="verified_condition", location=f"{owner} {type_name}")
    ctx.artifacts["validated_rrsets"] = sorted(set(validated_types))

    ds_texts = list(data.get("ds_records") or [])
    for (owner, rdtype), rrset in rrsets.items():
        if owner == zone and rdtype == dns.rdatatype.DS:
            ds_texts.extend(r.to_text() for r in rrset)
    if not ds_texts:
        ctx.limit("No DS records were supplied, so the chain of trust to the parent zone was not checked.")
        return
    matched = False
    for text in ds_texts:
        try:
            ds = dns.rdata.from_text(dns.rdataclass.IN, dns.rdatatype.DS, text)
        except Exception as exc:  # noqa: BLE001 - malformed DS text
            raise ToolInputError("A DS record could not be parsed.") from exc
        if ds.digest_type == 1:
            ctx.finding(f"dnssec.ds-sha1.{ds.key_tag}", f"DS {ds.key_tag} uses a SHA-1 digest", "low",
                        "SHA-1 DS digests are deprecated (RFC 8624); publish a SHA-256 (type 2) DS.",
                        assurance="verified_condition", location=f"DS {ds.key_tag}")
        for key in keys:
            if dns.dnssec.key_id(key) != ds.key_tag:
                continue
            try:
                candidate = dns.dnssec.make_ds(zone, key, ds.digest_type, policy=dns.dnssec.allow_all_policy)
            except Exception:  # noqa: BLE001 - unsupported digest type
                continue
            if candidate.digest == ds.digest:
                matched = True
    if not matched:
        ctx.finding("dnssec.ds-mismatch", "No DS record matches a DNSKEY", "high",
                    "The parent's DS does not correspond to any key in the zone: the chain of trust is broken and the zone is bogus.",
                    assurance="verified_condition", location=zone_label)


def _rsa_bits(key_bytes: bytes) -> int | None:
    # RFC 3110: exponent length (1 or 3 bytes), exponent, modulus
    if not key_bytes:
        return None
    if key_bytes[0] == 0:
        if len(key_bytes) < 3:
            return None
        exp_len = int.from_bytes(key_bytes[1:3], "big")
        offset = 3
    else:
        exp_len, offset = key_bytes[0], 1
    modulus = key_bytes[offset + exp_len:]
    return len(modulus) * 8 if modulus else None



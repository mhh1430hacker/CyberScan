def _txt_fields(record):
    return {k.strip().lower(): v.strip() for k, _, v in (p.partition("=") for p in record.split(";")) if k.strip()}


def matches(pattern, host):
    """RFC 8461 3.2: a leading '*.' matches exactly one left-most label."""
    pattern, host = pattern.lower().rstrip("."), host.lower().rstrip(".")
    if pattern.startswith("*."):
        suffix = pattern[1:]
        return host.endswith(suffix) and "." not in host[: -len(suffix)] and len(host) > len(suffix)
    return pattern == host


def parse_policy(text):
    fields, errors = {"mx": []}, []
    for number, line in enumerate(text.replace("\r\n", "\n").split("\n"), start=1):
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            errors.append(f"line {number}: not 'key: value'")
            continue
        key, value = key.strip().lower(), value.strip()
        if key == "mx":
            fields["mx"].append(value)
        elif key in fields:
            errors.append(f"line {number}: duplicate {key}")
        else:
            fields[key] = value
    return fields, errors


def _analyze(ctx, data):
    domain = normalize_domain(data["domain"])
    live = bool(data.get("resolve"))
    src = RecordSource(ctx, data.get("records"), live=live, nameserver=data.get("nameserver")) if (data.get("records") or live) else None
    ctx.input_kind = "live" if live else "records"

    if src is not None:
        txt = src.get(f"_mta-sts.{domain}", "TXT")
        if txt is not None:
            sts = [t for t in txt if t.replace(" ", "").lower().startswith("v=stsv1")]
            if not sts:
                ctx.finding("mtasts.no-record", "No MTA-STS TXT record", "medium",
                            "Sending servers will not look for an MTA-STS policy, so SMTP TLS to this domain can be downgraded.",
                            assurance="verified_condition", location=f"TXT _mta-sts.{domain}",
                            recommendation="Publish 'v=STSv1; id=<changing id>' and the policy file.")
            elif len(sts) > 1:
                ctx.finding("mtasts.multiple-records", "Multiple MTA-STS TXT records", "medium",
                            "RFC 8461 3.1: senders must treat multiple records as no policy.", assurance="verified_condition",
                            location=f"TXT _mta-sts.{domain}")
            else:
                fields = _txt_fields(sts[0])
                if not re.fullmatch(r"[A-Za-z0-9]{1,32}", fields.get("id", "")):
                    ctx.finding("mtasts.bad-id", "MTA-STS id is missing or invalid", "medium",
                                "id must be 1-32 alphanumeric characters; senders use it to detect policy changes.",
                                assurance="verified_condition", location=f"TXT _mta-sts.{domain}")
        rpt = src.get(f"_smtp._tls.{domain}", "TXT")
        if rpt is not None:
            records = [t for t in rpt if t.replace(" ", "").lower().startswith("v=tlsrptv1")]
            if not records:
                ctx.finding("tlsrpt.missing", "No TLS-RPT record", "low",
                            "Without _smtp._tls reporting you will not learn when senders fail TLS to your servers (RFC 8460).",
                            assurance="verified_condition", location=f"TXT _smtp._tls.{domain}")
            elif "rua" not in _txt_fields(records[0]):
                ctx.finding("tlsrpt.no-rua", "TLS-RPT record has no rua", "low", "The record names no report destination.",
                            assurance="verified_condition", location=f"TXT _smtp._tls.{domain}")

    policy_text = data.get("policy_text")
    policy_url = f"https://mta-sts.{domain}/.well-known/mta-sts.txt"
    if policy_text is None and data.get("fetch_policy"):
        try:
            response = httputil.fetch(policy_url, timeout=min(10.0, ctx.deadline.remaining()), max_body=65536)
        except httputil.FetchFailed as exc:
            ctx.finding("mtasts.policy-unreachable", "Policy file could not be fetched", "high",
                        f"{policy_url} failed ({exc}). Senders that cached the TXT record cannot load the policy.",
                        assurance="verified_condition", location=policy_url)
            return
        if response.status != 200:
            ctx.finding("mtasts.policy-http-error", f"Policy file returned HTTP {response.status}", "high",
                        "RFC 8461 3.3: only a 200 response is a valid policy.", assurance="verified_condition", location=policy_url)
            return
        content_type = (response.header_values("Content-Type") or [""])[0].lower()
        if not content_type.startswith("text/plain"):
            ctx.finding("mtasts.content-type", "Policy is not served as text/plain", "medium",
                        f"Content-Type is '{content_type or 'missing'}'; RFC 8461 requires text/plain.", assurance="verified_condition",
                        location=policy_url)
        policy_text = response.body.decode("utf-8", errors="replace")
    if policy_text is None:
        ctx.limit("No policy file was supplied or fetched; only DNS records were checked.")
        return

    fields, errors = parse_policy(policy_text)
    for error in errors[:10]:
        ctx.finding("mtasts.policy-syntax", "Policy file syntax error", "medium", error, assurance="verified_condition", location=policy_url)
    if fields.get("version") != "STSv1":
        ctx.finding("mtasts.bad-version", "Policy version is not STSv1", "high", "Senders discard policies without 'version: STSv1'.",
                    assurance="verified_condition", location=policy_url)
    mode = fields.get("mode", "").lower()
    if mode not in ("enforce", "testing", "none"):
        ctx.finding("mtasts.bad-mode", "Policy mode is missing or invalid", "high", "mode must be enforce, testing or none.",
                    assurance="verified_condition", location=policy_url)
    elif mode == "testing":
        ctx.finding("mtasts.testing", "Policy is in testing mode", "low",
                    "Testing mode only reports failures; delivery still proceeds over unauthenticated or plaintext connections.",
                    assurance="verified_condition", location=policy_url)
    elif mode == "none":
        ctx.finding("mtasts.none", "Policy mode is none", "medium", "mode: none withdraws protection.", assurance="verified_condition",
                    location=policy_url)
    age = fields.get("max_age", "")
    if not age.isdigit():
        ctx.finding("mtasts.bad-max-age", "max_age missing or invalid", "medium", "max_age is required (seconds).",
                    assurance="verified_condition", location=policy_url)
    elif int(age) > 31557600:
        ctx.finding("mtasts.max-age-too-long", "max_age exceeds one year", "low", "RFC 8461 caps max_age at 31557600.",
                    assurance="verified_condition", location=policy_url)
    elif int(age) < 86400:
        ctx.finding("mtasts.max-age-short", f"max_age is short ({age} s)", "low",
                    "Short policies expire quickly, leaving gaps an attacker can use; weeks are recommended.",
                    assurance="verified_condition", location=policy_url)
    patterns = fields["mx"]
    if mode in ("enforce", "testing") and not patterns:
        ctx.finding("mtasts.no-mx", "Policy lists no mx patterns", "high", "With no mx lines, no MX can satisfy the policy.",
                    assurance="verified_condition", location=policy_url)
    ctx.artifacts["policy"] = {k: v for k, v in fields.items()}
    if src is not None and patterns:
        mx = src.get(domain, "MX")
        if mx:
            hosts = [value.split()[-1].rstrip(".") for value in mx]
            unmatched = [h for h in hosts if not any(matches(p, h) for p in patterns)]
            ctx.artifacts["mx_hosts"] = hosts
            if unmatched:
                ctx.finding("mtasts.mx-mismatch", "MX hosts not covered by the policy", "high" if mode == "enforce" else "medium",
                            f"{', '.join(unmatched)} match no mx pattern; in enforce mode senders will refuse to deliver to them.",
                            assurance="verified_condition", location=f"MX {domain}")



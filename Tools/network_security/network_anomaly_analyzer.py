def _zeek(text):
    fields, rows = None, []
    for line in text.splitlines():
        if line.startswith("#fields"):
            fields = line.split("\t")[1:]
        elif line.startswith("#") or not line.strip():
            continue
        elif fields:
            rows.append({k: (None if v in ("-", "(empty)") else v) for k, v in zip(fields, line.split("\t"))})
    return rows


def _rows(data):
    if data.get("flows"):
        return data["flows"], "json"
    text = data.get("content")
    if not text:
        raise ToolInputError("Provide 'flows' (list of objects) or 'content' (JSON, CSV or Zeek conn.log).")
    fmt = data.get("format", "auto")
    if fmt == "auto":
        stripped = text.lstrip()
        fmt = "zeek" if stripped.startswith("#separator") or "#fields" in text[:4000] else "json" if stripped[:1] in "[{" else "csv"
    if fmt == "zeek":
        return _zeek(text), "zeek"
    if fmt == "json":
        try:
            parsed = json.loads(text)
        except ValueError as exc:
            raise ToolInputError("content is not valid JSON.") from exc
        if isinstance(parsed, dict):
            parsed = parsed.get("flows", [])
        if not isinstance(parsed, list):
            raise ToolInputError("JSON content must be a list of flow objects.")
        return parsed, "json"
    return list(csv.DictReader(io.StringIO(text))), "csv"


def _analyze(ctx, data):
    rows, kind = _rows(data)
    ctx.input_kind = kind
    flows = [netflow.normalize(r) for r in rows if isinstance(r, dict)]
    valid = [f for f in flows if f]
    if not valid:
        raise ToolInputError("No usable flow records (each needs at least src and dst).")
    if len(valid) < len(rows):
        ctx.limit(f"{len(rows) - len(valid)} record(s) lacked src/dst or had non-numeric fields and were skipped.")
    stats = netflow.analyze(ctx, valid, include_cleartext=data.get("include_cleartext", True))
    stats["top_ports"] = [list(p) for p in stats["top_ports"]]
    ctx.artifacts.update(stats)
    if len(valid) < 50:
        ctx.limit("Fewer than 50 flows: statistical detections (outliers, beaconing) have little to compare against.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

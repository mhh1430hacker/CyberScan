WEAK_SSH = {
    "ciphers": re.compile(r"\b(?:3des-cbc|aes(?:128|192|256)-cbc|blowfish-cbc|cast128-cbc|arcfour\w*|rijndael-cbc@lysator\.liu\.se)\b", re.I),
    "macs": re.compile(r"\b(?:hmac-md5\S*|hmac-sha1(?:-96)?(?![\w-]*etm)|umac-64@openssh\.com|hmac-ripemd160\S*)\b", re.I),
    "kexalgorithms": re.compile(r"\b(?:diffie-hellman-group1-sha1|diffie-hellman-group14-sha1|diffie-hellman-group-exchange-sha1)\b", re.I),
    "hostkeyalgorithms": re.compile(r"\b(?:ssh-dss|ssh-rsa)(?![\w-])", re.I),
}


def _sshd(ctx, text, path):
    settings: dict[str, tuple[str, int]] = {}
    in_match = False
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        key, _, value = line.partition(" ")
        key = key.lower()
        if key == "match":
            in_match = True  # Match blocks override per user/host; the global settings are what we audit
            continue
        if not in_match and key not in settings:  # sshd uses the first value it reads
            settings[key] = (value.strip().strip('"'), number)

    def get(name, default):
        return settings.get(name, (default, 0))

    value, line = get("permitrootlogin", "prohibit-password")
    if value.lower() == "yes":
        ctx.finding("sshd.root-login", "Root can log in with a password", "high",
                    "PermitRootLogin yes lets attackers brute-force the most privileged account directly.",
                    assurance="verified_condition", location=f"{path}:{line}", recommendation="Set PermitRootLogin no (or prohibit-password).")
    value, line = get("passwordauthentication", "yes")
    if value.lower() == "yes":
        ctx.finding("sshd.password-auth", "Password authentication is enabled", "medium",
                    "Passwords can be guessed or reused; key-based authentication resists online brute force."
                    + ("" if line else " (Not set: OpenSSH's default is yes.)"),
                    assurance="verified_condition", location=f"{path}:{line or 'default'}",
                    recommendation="Set PasswordAuthentication no after deploying keys.")
    value, line = get("permitemptypasswords", "no")
    if value.lower() == "yes":
        ctx.finding("sshd.empty-passwords", "Empty passwords are permitted", "critical",
                    "Accounts without a password can log in remotely.", assurance="verified_condition", location=f"{path}:{line}")
    value, line = get("protocol", "2")
    if "1" in value.split(","):
        ctx.finding("sshd.protocol1", "SSH protocol 1 enabled", "high", "SSH-1 is cryptographically broken.",
                    assurance="verified_condition", location=f"{path}:{line}")
    for name in ("x11forwarding", "permittunnel", "allowagentforwarding"):
        value, line = get(name, "no" if name != "allowagentforwarding" else "yes")
        if value.lower() == "yes" and line:
            ctx.finding(f"sshd.{name}", f"{name} is enabled", "low",
                        "Forwarding features widen what a compromised session can reach; disable them unless needed.",
                        assurance="verified_condition", location=f"{path}:{line}")
    value, line = get("maxauthtries", "6")
    if value.isdigit() and int(value) > 6:
        ctx.finding("sshd.maxauthtries", f"MaxAuthTries is {value}", "low", "Many attempts per connection speed up guessing.",
                    assurance="verified_condition", location=f"{path}:{line}")
    value, line = get("logingracetime", "120")
    if value.isdigit() and (int(value) == 0 or int(value) > 120):
        ctx.finding("sshd.logingracetime", "Long or unlimited LoginGraceTime", "low",
                    "Unauthenticated connections are held open for a long time, which helps exhaustion attacks.",
                    assurance="verified_condition", location=f"{path}:{line}")
    for name, pattern in WEAK_SSH.items():
        value, line = get(name, "")
        weak = sorted(set(m.group(0).lower() for m in pattern.finditer(value)))
        if weak and not value.startswith("-"):
            ctx.finding(f"sshd.weak-{name}", f"Weak {name} enabled: {', '.join(weak)}", "medium",
                        "These algorithms are deprecated (CBC modes, MD5/SHA-1 MACs, SHA-1 key exchange, DSA keys).",
                        assurance="verified_condition", location=f"{path}:{line}")
    if "listenaddress" not in settings:
        ctx.finding("sshd.listen-all", "sshd listens on all interfaces", "info",
                    "No ListenAddress is set, so SSH is reachable on every interface; restrict it if only one network needs it.",
                    assurance="informational", location=path)


def _ios(ctx, text, path):
    lines = text.splitlines()
    joined = "\n".join(lines)

    def at(pattern):
        for number, line in enumerate(lines, start=1):
            if re.search(pattern, line, re.I):
                return number, line
        return 0, ""

    number, line = at(r"^\s*enable password\b")
    if number:
        ctx.finding("ios.enable-password", "Enable password uses reversible or no encryption", "high",
                    "'enable password' is stored in clear text or weak type-7; use 'enable secret' (type 8/9).",
                    assurance="verified_condition", location=f"{path}:{number}", evidence=line)
    if not re.search(r"^\s*service password-encryption\b", joined, re.I | re.M):
        ctx.finding("ios.no-password-encryption", "service password-encryption is off", "low",
                    "Line and user passwords appear in clear text in the configuration.", assurance="verified_condition", location=path)
    for number, line in enumerate(lines, start=1):
        if re.search(r"^\s*username \S+ (?:privilege \d+ )?password 0\b", line, re.I):
            ctx.finding("ios.cleartext-user-password", "Local user with clear-text password", "high",
                        "A local account password is stored unencrypted.", assurance="verified_condition",
                        location=f"{path}:{number}", evidence=line)
        if re.search(r"^\s*username \S+ (?:privilege \d+ )?password 7\b", line, re.I):
            ctx.finding("ios.type7-password", "Local user with type-7 password", "medium",
                        "Type 7 is a reversible encoding, not encryption; anyone with the config can recover the password.",
                        assurance="verified_condition", location=f"{path}:{number}", evidence=line)
        match = re.search(r"^\s*snmp-server community (\S+)(?:\s+(RO|RW))?", line, re.I)
        if match:
            community = match.group(1)
            access = (match.group(2) or "RO").upper()
            default = community.lower() in ("public", "private", "cisco", "community", "secret")
            ctx.finding("ios.snmp-community", f"SNMPv1/v2c community ({access})" + (" with a default name" if default else ""),
                        "high" if access == "RW" or default else "medium",
                        "SNMP v1/v2c communities travel in clear text; " + ("RW communities allow reconfiguration. " if access == "RW" else "")
                        + ("Default names are the first thing scanners try." if default else ""),
                        assurance="verified_condition", location=f"{path}:{number}", evidence=line,
                        recommendation="Use SNMPv3 with authPriv, or restrict the community with an ACL.")
        if re.search(r"^\s*ip http server\b", line, re.I):
            ctx.finding("ios.http-server", "Cleartext HTTP management server enabled", "medium",
                        "The device's web interface is reachable over unencrypted HTTP.", assurance="verified_condition",
                        location=f"{path}:{number}", recommendation="'no ip http server'; use 'ip http secure-server' if needed.")
        if re.search(r"^\s*transport input (?:.*\btelnet\b|all)", line, re.I):
            ctx.finding("ios.telnet", "Telnet allowed on management lines", "high",
                        "Telnet sends credentials and sessions in clear text.", assurance="verified_condition",
                        location=f"{path}:{number}", evidence=line, recommendation="'transport input ssh'.")
        if re.search(r"^\s*ip ssh version 1\b", line, re.I):
            ctx.finding("ios.ssh-v1", "SSH version 1 enabled", "high", "SSH-1 is broken.", assurance="verified_condition",
                        location=f"{path}:{number}")
        if re.search(r"^\s*(?:no )?cdp run\b", line, re.I) and not line.strip().lower().startswith("no "):
            ctx.finding("ios.cdp", "CDP enabled globally", "info", "CDP discloses device details to neighbours.",
                        assurance="informational", location=f"{path}:{number}")
    vty = [i for i, l in enumerate(lines) if re.match(r"^\s*line vty\b", l, re.I)]
    for start in vty:
        block = []
        for l in lines[start + 1:]:
            if not l.startswith((" ", "\t")):
                break
            block.append(l.strip().lower())
        if not any(b.startswith("access-class") for b in block):
            ctx.finding("ios.vty-no-acl", "Management lines accept connections from anywhere", "medium",
                        "No access-class restricts which hosts can reach the VTY lines.", assurance="verified_condition",
                        location=f"{path}:{start + 1}")
        if not any(b.startswith(("login local", "login authentication")) for b in block) and "login" in block:
            ctx.finding("ios.vty-line-password", "VTY uses a shared line password", "low",
                        "'login' without local or AAA authentication relies on one shared password.", assurance="verified_condition",
                        location=f"{path}:{start + 1}")
    if not re.search(r"^\s*logging (?:host )?\d", joined, re.I | re.M):
        ctx.finding("ios.no-remote-logging", "No remote logging target", "low",
                    "Logs stay on the device, where an attacker with access can erase them.", assurance="verified_condition", location=path)


def _detect(text):
    if re.search(r"^\s*(?:hostname|interface \S+|line vty|router \w+|ip route)\b", text, re.I | re.M):
        return "ios"
    if re.search(r"^\s*(?:PermitRootLogin|PasswordAuthentication|Port|Subsystem\s+sftp|ChallengeResponseAuthentication|UsePAM)\b", text, re.I | re.M):
        return "sshd"
    return None


def _analyze(ctx, data):
    text = text_or_bytes(data, max_bytes=5_000_000)
    fmt = data.get("format", "auto")
    if fmt == "auto":
        fmt = _detect(text)
        if fmt is None:
            raise Unsupported("the content is neither an sshd_config nor an IOS-style configuration; set 'format' explicitly.")
    ctx.input_kind = fmt
    path = data.get("path") or ("sshd_config" if fmt == "sshd" else "running-config")
    (_sshd if fmt == "sshd" else _ios)(ctx, text, path)


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

ONE_YEAR = 31536000
DIRECTIVE = re.compile(r'^\s*([A-Za-z][A-Za-z0-9-]*)\s*(?:=\s*("(?:[^"\\]|\\.)*"|[^;\s]*))?\s*$')


def _parse_headers(text):
    values, status = [], None
    for line in text.splitlines():
        if line.upper().startswith("HTTP/") and status is None:
            parts = line.split()
            status = int(parts[1]) if len(parts) > 1 and parts[1].isdigit() else None
        name, sep, value = line.partition(":")
        if sep and name.strip().lower() == "strict-transport-security":
            values.append(value.strip())
    return values, status


def _check(ctx, values, scheme, where):
    if scheme == "http":
        if values:
            ctx.finding("hsts.over-http", "HSTS header sent over plain HTTP", "low",
                        "Browsers ignore Strict-Transport-Security received over HTTP (RFC 6797 8.1); it must come from HTTPS.",
                        assurance="verified_condition", location=where)
        return
    if not values:
        ctx.finding("hsts.missing", "No Strict-Transport-Security header", "medium",
                    "Without HSTS, a first visit or a typed http:// link can be downgraded and intercepted (SSL stripping).",
                    assurance="verified_condition", location=where,
                    recommendation="Send 'Strict-Transport-Security: max-age=31536000; includeSubDomains' on every HTTPS response.")
        return
    if len(values) > 1:
        ctx.finding("hsts.duplicate", "Multiple HSTS headers", "low",
                    "User agents process only the first header (RFC 6797 8.1); duplicates usually mean two layers set it differently.",
                    assurance="verified_condition", location=where, evidence=" | ".join(values))
    value = values[0]
    ctx.evidence("header", f"Strict-Transport-Security: {value}", location=where)
    directives, invalid = {}, False
    for part in value.split(";"):
        if not part.strip():
            continue
        match = DIRECTIVE.match(part)
        if not match:
            invalid = True
            continue
        name = match.group(1).lower()
        if name in directives:
            invalid = True
        directives[name] = (match.group(2) or "").strip('"')
    if invalid:
        ctx.finding("hsts.invalid-syntax", "Malformed HSTS directive", "medium",
                    "A directive is malformed or repeated; RFC 6797 requires user agents to ignore the whole header.",
                    assurance="verified_condition", location=where)
    raw_age = directives.get("max-age")
    if raw_age is None or not raw_age.isdigit():
        ctx.finding("hsts.no-max-age", "max-age is missing or not a number", "high",
                    "max-age is required; without a valid value the header has no effect.", assurance="verified_condition", location=where)
        return
    age = int(raw_age)
    ctx.artifacts["max_age_seconds"] = age
    if age == 0:
        ctx.finding("hsts.disabled", "max-age=0 removes HSTS", "medium",
                    "max-age=0 tells browsers to forget the HSTS policy for this host.", assurance="verified_condition", location=where)
    elif age < 15552000:
        ctx.finding("hsts.short-max-age", f"max-age is short ({age} s, {age / 86400:.0f} days)", "low",
                    "Protection lapses for returning visitors who stay away longer than max-age; 6-12 months is typical.",
                    assurance="verified_condition", location=where)
    subdomains = "includesubdomains" in directives
    if not subdomains:
        ctx.finding("hsts.no-subdomains", "includeSubDomains is not set", "low",
                    "Sub-domains are not covered, so cookies scoped to the parent domain can still leak over HTTP via a sub-domain.",
                    assurance="verified_condition", location=where)
    if "preload" in directives:
        problems = [p for p, bad in (("max-age below one year", age < ONE_YEAR), ("includeSubDomains missing", not subdomains)) if bad]
        if problems:
            ctx.finding("hsts.preload-not-eligible", "preload requested but requirements are not met", "low",
                        "The preload list requires max-age >= 31536000 and includeSubDomains: " + ", ".join(problems) + ".",
                        assurance="verified_condition", location=where)
        else:
            ctx.finding("hsts.preload-ready", "Header meets preload-list requirements", "info",
                        "Submission at hstspreload.org also requires an HTTP-to-HTTPS redirect on the bare domain; that is not verified here "
                        "unless check_http_redirect is used. Preloading is hard to undo.", assurance="informational", location=where)


def _analyze(ctx, data):
    if data.get("headers"):
        ctx.input_kind = "headers"
        ctx.execution_mode = "local"
        values, _status = _parse_headers(data["headers"])
        _check(ctx, values, data.get("scheme", "https"), "supplied headers")
        return
    if not data.get("url"):
        raise ToolInputError("Provide 'headers' (raw response headers) or an https 'url'.")
    ctx.input_kind = "url"
    parts = httputil.parse_url(data["url"])
    try:
        response = httputil.fetch(data["url"], method="GET", timeout=min(10.0, ctx.deadline.remaining()), max_body=0)
    except httputil.FetchFailed as exc:
        raise Unavailable(f"Could not fetch {parts.hostname}: {exc}") from exc
    ctx.artifacts["https_status"] = response.status
    _check(ctx, response.header_values("Strict-Transport-Security"), "https", data["url"])
    if 300 <= response.status < 400:
        ctx.limit("The HTTPS URL answered with a redirect; the header was checked on that redirect response only.")
    if data.get("check_http_redirect"):
        plain = f"http://{parts.netloc}{parts.path or '/'}"
        try:
            reply = httputil.fetch(plain, method="GET", timeout=min(10.0, ctx.deadline.remaining()), max_body=0)
        except httputil.FetchFailed as exc:
            ctx.limit(f"Plain HTTP check failed ({exc}).", partial=True)
            return
        location = (reply.header_values("Location") or [""])[0]
        if not (300 <= reply.status < 400 and location.lower().startswith("https://")):
            ctx.finding("hsts.no-https-redirect", "Plain HTTP does not redirect to HTTPS", "medium",
                        f"http:// answered {reply.status} without a redirect to https://, so first visits stay unencrypted.",
                        assurance="verified_condition", location=plain)



SPF_LOOKUP_TERMS = re.compile(r"^(?:[+\-~?]?)(include:|a\b|a:|a/|mx\b|mx:|mx/|ptr\b|ptr:|exists:|redirect=)", re.I)


def _spf(ctx, src, domain):
    txt = src.get(domain, "TXT")
    if txt is None:
        return
    spf = [t for t in txt if t.lower().startswith("v=spf1")]
    if not spf:
        ctx.finding("spf.missing", "No SPF record", "medium",
                    f"{domain} publishes no SPF policy, so receivers cannot tell which servers may send its mail.",
                    assurance="verified_condition", location=f"TXT {domain}",
                    recommendation="Publish 'v=spf1 ... -all' listing your senders, or 'v=spf1 -all' if the domain sends no mail.")
        return
    if len(spf) > 1:
        ctx.finding("spf.multiple", "Multiple SPF records", "high",
                    "More than one v=spf1 record makes SPF evaluation fail (permerror) for every message.",
                    assurance="verified_condition", location=f"TXT {domain}", evidence=" | ".join(spf))
    record = spf[0]
    terms = record.split()[1:]
    ctx.evidence("spf", record, location=f"TXT {domain}")
    all_terms = [t for t in terms if t.lower().lstrip("+-~?") == "all"]
    if not all_terms and not any(t.lower().startswith("redirect=") for t in terms):
        ctx.finding("spf.no-all", "SPF has no 'all' mechanism", "low",
                    "Without a final 'all' mechanism, mail from unlisted servers gets a neutral result.",
                    assurance="verified_condition", location=f"TXT {domain}",
                    recommendation="End the record with '-all' (or '~all' while testing).")
    for term in all_terms:
        qualifier = term[0] if term[0] in "+-~?" else "+"
        if qualifier == "+":
            ctx.finding("spf.pass-all", "SPF allows every server (+all)", "high",
                        "'+all' authorizes any host on the internet to send mail as this domain.",
                        assurance="verified_condition", location=f"TXT {domain}", recommendation="Replace '+all' with '-all'.")
        elif qualifier == "?":
            ctx.finding("spf.neutral-all", "SPF ends with neutral '?all'", "medium",
                        "'?all' gives no protection: unlisted senders are treated as if no policy existed.",
                        assurance="verified_condition", location=f"TXT {domain}")
        elif qualifier == "~":
            ctx.finding("spf.softfail", "SPF ends with soft fail '~all'", "info",
                        "'~all' marks unlisted senders as suspicious but does not reject; rely on DMARC for enforcement.",
                        assurance="informational", location=f"TXT {domain}")
    lookups = sum(1 for t in terms if SPF_LOOKUP_TERMS.match(t))
    if lookups > 10:
        ctx.finding("spf.too-many-lookups", "SPF needs more than 10 DNS lookups", "medium",
                    f"The record has {lookups} lookup terms at the top level alone; over 10 makes SPF fail (RFC 7208 4.6.4).",
                    assurance="verified_condition", location=f"TXT {domain}")
    if any(t.lower().lstrip("+-~?").startswith("ptr") for t in terms):
        ctx.finding("spf.ptr", "SPF uses the deprecated 'ptr' mechanism", "low",
                    "'ptr' is slow, unreliable and discouraged by RFC 7208.", assurance="verified_condition",
                    location=f"TXT {domain}")


def _dmarc(ctx, src, domain):
    txt = src.get(f"_dmarc.{domain}", "TXT")
    if txt is None:
        return
    records = [t for t in txt if t.replace(" ", "").lower().startswith("v=dmarc1")]
    if not records:
        ctx.finding("dmarc.missing", "No DMARC policy", "medium",
                    "Without DMARC, receivers have no instruction for mail that fails SPF/DKIM, so spoofing the domain is easier.",
                    assurance="verified_condition", location=f"TXT _dmarc.{domain}",
                    recommendation="Publish 'v=DMARC1; p=none; rua=mailto:...' to start monitoring, then move to quarantine/reject.")
        return
    if len(records) > 1:
        ctx.finding("dmarc.multiple", "Multiple DMARC records", "high",
                    "More than one DMARC record means receivers must ignore DMARC entirely (RFC 7489 6.6.3).",
                    assurance="verified_condition", location=f"TXT _dmarc.{domain}")
    tags = {}
    for part in records[0].split(";"):
        if "=" in part:
            key, _, value = part.partition("=")
            tags[key.strip().lower()] = value.strip()
    ctx.evidence("dmarc", records[0], location=f"TXT _dmarc.{domain}")
    policy = tags.get("p", "").lower()
    if policy not in ("none", "quarantine", "reject"):
        ctx.finding("dmarc.invalid-policy", "DMARC policy tag missing or invalid", "medium",
                    "The required p= tag is missing or not none/quarantine/reject, so receivers may discard the record.",
                    assurance="verified_condition", location=f"TXT _dmarc.{domain}")
    elif policy == "none":
        ctx.finding("dmarc.monitor-only", "DMARC is in monitoring mode (p=none)", "low",
                    "p=none only collects reports; spoofed mail is still delivered.", assurance="verified_condition",
                    location=f"TXT _dmarc.{domain}", recommendation="Move to p=quarantine, then p=reject, once reports are clean.")
    pct = tags.get("pct")
    if pct and pct.isdigit() and int(pct) < 100 and policy in ("quarantine", "reject"):
        ctx.finding("dmarc.partial-pct", f"DMARC applies to only {pct}% of failing mail", "low",
                    "pct below 100 lets the rest of the failing mail through under a weaker policy.",
                    assurance="verified_condition", location=f"TXT _dmarc.{domain}")
    if "rua" not in tags:
        ctx.finding("dmarc.no-reports", "DMARC requests no aggregate reports", "info",
                    "Without rua= you will not see who sends mail as your domain.", assurance="informational",
                    location=f"TXT _dmarc.{domain}")


def _dkim(ctx, src, domain, selectors):
    for selector in selectors:
        name = f"{selector}._domainkey.{domain}"
        txt = src.get(name, "TXT")
        if txt is None:
            continue
        keys = [t for t in txt if "p=" in t.replace(" ", "")]
        if not keys:
            ctx.finding("dkim.missing", f"No DKIM key for selector '{selector}'", "low",
                        "The named selector publishes no DKIM key; mail signed with it will fail DKIM.",
                        assurance="verified_condition", location=f"TXT {name}")
            continue
        tags = dict((k.strip().lower(), v.strip()) for k, _, v in (p.partition("=") for p in keys[0].split(";")) if k.strip())
        p = re.sub(r"\s+", "", tags.get("p", ""))
        if not p:
            ctx.finding("dkim.revoked", f"DKIM selector '{selector}' is revoked (empty p=)", "info",
                        "An empty key revokes the selector; that is fine if it is no longer used.",
                        assurance="informational", location=f"TXT {name}")
            continue
        bits = _rsa_bits(p)
        if bits and bits < 1024:
            ctx.finding("dkim.weak-key", f"DKIM key for '{selector}' is only {bits} bits", "high",
                        "RSA keys under 1024 bits can be factored; receivers may treat the signature as invalid.",
                        assurance="verified_condition", location=f"TXT {name}", recommendation="Rotate to a 2048-bit key.")
        elif bits and bits < 2048:
            ctx.finding("dkim.short-key", f"DKIM key for '{selector}' is {bits} bits", "low",
                        "1024-bit RSA is the minimum; 2048 bits is the current recommendation (RFC 8301).",
                        assurance="verified_condition", location=f"TXT {name}")


def _rsa_bits(p: str) -> int | None:
    try:
        der = base64.b64decode(p + "=" * (-len(p) % 4), validate=False)
    except ValueError:
        return None
    try:
        from cryptography.hazmat.primitives.serialization import load_der_public_key

        return load_der_public_key(der).key_size
    except Exception:  # noqa: BLE001 - not RSA or not parseable: size unknown
        return None


def _infrastructure(ctx, src, domain):
    mx = src.get(domain, "MX")
    if mx is not None:
        if not mx:
            ctx.finding("mx.none", "No MX records", "info",
                        "The domain does not receive mail. If it sends none either, publish 'v=spf1 -all' and a null MX (RFC 7505).",
                        assurance="informational", location=f"MX {domain}")
        for value in mx:
            host = value.split()[-1].rstrip(".")
            if re.fullmatch(r"[\d.]+", host):
                ctx.finding("mx.ip-literal", "MX points to an IP address", "low",
                            "MX targets must be host names (RFC 5321); many senders will not deliver to an IP.",
                            assurance="verified_condition", location=f"MX {domain}", evidence=value)
    ns = src.get(domain, "NS")
    if ns is not None and 0 < len(ns) < 2:
        ctx.finding("ns.single", "Only one authoritative name server", "medium",
                    "A single NS is a single point of failure for the whole domain (RFC 1034 recommends at least two).",
                    assurance="verified_condition", location=f"NS {domain}", evidence=" ".join(ns))
    caa = src.get(domain, "CAA")
    if caa is not None and not caa:
        ctx.finding("caa.missing", "No CAA record", "low",
                    "Any public certificate authority may issue certificates for this domain.",
                    assurance="verified_condition", location=f"CAA {domain}",
                    recommendation="Publish CAA records naming the CAs you use, e.g. '0 issue \"letsencrypt.org\"'.")
    keys = src.get(domain, "DNSKEY")
    if keys is not None and not keys:
        ctx.finding("dnssec.unsigned", "Zone publishes no DNSSEC keys", "low",
                    "Without DNSSEC, resolvers cannot detect forged answers for this domain. Use tool 052 to validate signed zones.",
                    assurance="verified_condition", location=f"DNSKEY {domain}")


def _analyze(ctx, data):
    domain = normalize_domain(data["domain"])
    src = source_from_input(ctx, data)
    ctx.artifacts["domain"] = domain
    _spf(ctx, src, domain)
    _dmarc(ctx, src, domain)
    _dkim(ctx, src, domain, [s.strip().lower() for s in data.get("dkim_selectors", []) if re.fullmatch(r"[A-Za-z0-9_\-.]+", s)])
    _infrastructure(ctx, src, domain)
    if not src.live:
        ctx.limit("Offline mode: for each supplied owner name, record types that are not listed are treated as absent.")
    ctx.limit("DKIM is checked only for the selectors you name; selectors cannot be enumerated from DNS.")



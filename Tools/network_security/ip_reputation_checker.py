IP_IN_TEXT = re.compile(r"(?<![\w.:])(?:\d{1,3}\.){3}\d{1,3}(?![\w.])|(?<![\w:])[0-9a-fA-F]{0,4}(?::[0-9a-fA-F]{0,4}){2,7}(?![\w:])")
ENTRY = re.compile(r"^\s*([0-9a-fA-F:.]+(?:/\d{1,3})?)")


def _parse_list(text, name):
    nets = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].split(";", 1)[0]
        match = ENTRY.match(line)
        if not match:
            continue
        try:
            nets.append(ipaddress.ip_network(match.group(1), strict=False))
        except ValueError:
            continue
    if not nets:
        raise ToolInputError(f"Blocklist '{name}' contains no parseable addresses or CIDR ranges.")
    return nets


def _analyze(ctx, data):
    raw = list(data.get("ips") or [])
    if data.get("content"):
        raw.extend(m.group(0) for m in IP_IN_TEXT.finditer(data["content"]))
    addresses = []
    for value in raw:
        try:
            addresses.append(ipaddress.ip_address(value.strip().strip("[]")))
        except ValueError:
            continue
    addresses = sorted(set(addresses), key=lambda a: (a.version, int(a)))[:10000]
    if not addresses:
        raise ToolInputError("Provide 'ips' or 'content' containing at least one valid IP address.")
    ctx.input_kind = "ip-list"
    lists = [(b["name"], b.get("severity", "high"), _parse_list(b["entries"], b["name"])) for b in data.get("blocklists") or []]
    allow = []
    for value in data.get("allowlist") or []:
        try:
            allow.append(ipaddress.ip_network(value, strict=False))
        except ValueError:
            raise ToolInputError(f"allowlist entry '{value[:40]}' is not an IP or CIDR.") from None
    summary = {"addresses": len(addresses), "special_purpose": 0, "listed": 0, "global": 0}
    classes = {}
    for index, address in enumerate(addresses):
        if index % 500 == 0:
            ctx.check()
        label = next((lbl for net, lbl in SPECIAL if net.version == address.version and address in net), None)
        classes[str(address)] = label or "global unicast"
        if label:
            summary["special_purpose"] += 1
            if "bogon" in label or label.startswith("reserved"):
                ctx.finding("ip.bogon", f"Bogon address {address}", "low",
                            f"{address} is in a range that must never appear as a source on the public internet ({label}); "
                            "seeing it in external traffic suggests spoofing or misconfiguration.",
                            assurance="verified_condition", location=str(address))
            continue
        summary["global"] += 1
        if any(address in net for net in allow if net.version == address.version):
            continue
        for name, severity, nets in lists:
            hit = next((net for net in nets if net.version == address.version and address in net), None)
            if hit is not None:
                summary["listed"] += 1
                ctx.finding(f"ip.listed.{re.sub(r'[^a-z0-9]+', '-', name.lower())}", f"{address} is on blocklist '{name}'", severity,
                            f"{address} falls inside {hit} on the supplied list '{name}'. The listing reflects that list's "
                            "criteria and age; confirm with the list's documentation before blocking.",
                            assurance="verified_condition", location=str(address))
    ctx.artifacts.update({"summary": summary, "classification_by_address": dict(list(classes.items())[:2000])})
    if not lists:
        ctx.limit("No blocklists were supplied: only address classification was performed. CyberScan has no built-in reputation data.")
    ctx.summary = (f"{summary['addresses']} address(es): {summary['global']} global, {summary['special_purpose']} special-purpose, "
                   f"{summary['listed']} listed in the supplied lists.")



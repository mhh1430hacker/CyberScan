"""Generate the manifest and category READMEs for tools 051-100 from the tools' own literal metadata.

    python Tools/maintenance/build_manifest.py

Writes Tools/maintenance/tools_051_100.manifest.json and <category>/README.md. Metadata is read with ``ast``
exactly as the registry reads it, so the documents cannot drift from the code. Re-run after changing a tool.
"""
from __future__ import annotations

import ast
import hashlib
import json
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
CATEGORIES = {
    "network_security": "Category 6 - Network Security",
    "system_security": "Category 7 - System Security",
    "privacy_data_protection": "Category 8 - Privacy & Data Protection",
    "code_dependency_security": "Category 9 - Code & Dependency Security",
    "cloud_infrastructure": "Category 10 - Cloud & Infrastructure",
}
FIELDS = ("TOOL_ID", "TOOL_NUMBER", "NAME", "DESCRIPTION", "CATEGORY", "VERSION", "LICENSE", "SOURCE", "TIMEOUT_SECONDS",
          "INPUT_SCHEMA", "PRIVACY", "PROCESSING", "TOOLKIT_SHA256")


def metadata(path: Path) -> dict:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) and node.targets[0].id in FIELDS:
            values[node.targets[0].id] = ast.literal_eval(node.value)
    values["file"] = path.relative_to(TOOLS).as_posix()
    values["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
    values["output_schema"] = "security_toolkit.core.UNIFIED_OUTPUT_SCHEMA"
    return values


def main() -> int:
    tools = []
    for directory in CATEGORIES:
        tools += [metadata(p) for p in sorted((TOOLS / directory).glob("*.py")) if not p.name.startswith("_")]
    tools.sort(key=lambda t: t["TOOL_NUMBER"])
    manifest = {"tools": tools, "count": len(tools), "unified_output_schema": "Tools/security_toolkit/core.py",
                "note": "Generated by Tools/maintenance/build_manifest.py; sha256 values change whenever a tool or the toolkit pin changes."}
    out = TOOLS / "maintenance" / "tools_051_100.manifest.json"
    out.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    for directory, title in CATEGORIES.items():
        rows = [t for t in tools if t["file"].startswith(directory + "/")]
        lines = [f"# {title}", "", f"Tools {rows[0]['TOOL_NUMBER']:03d}-{rows[-1]['TOOL_NUMBER']:03d}. Generated by `Tools/maintenance/build_manifest.py`; "
                 "see `Tools/TOOLS_051_100.md` for the contract, inventory, limitations and integration.", "",
                 "| # | Tool | ID | Mode | Inputs | Dependencies | External services |", "|---|---|---|---|---|---|---|"]
        for t in rows:
            inputs = ", ".join(f"`{k}`" for k in t["INPUT_SCHEMA"].get("properties", {}))
            deps = ", ".join(t["PROCESSING"].get("dependencies") or []) or "stdlib"
            ext = ", ".join(t["PROCESSING"].get("external_services") or []) or "none"
            lines.append(f"| {t['TOOL_NUMBER']:03d} | {t['NAME']} | `{t['TOOL_ID']}` | {t['PROCESSING']['execution_mode']} | {inputs} | {deps} | {ext} |")
        lines += ["", "## What each tool does", ""]
        for t in rows:
            lines += [f"**{t['TOOL_NUMBER']:03d} {t['NAME']}** - {t['DESCRIPTION']}", "",
                      f"Data handling: {t['PRIVACY']['data_handling']} External: {t['PRIVACY']['external_services']} "
                      f"Timeout: {t['TIMEOUT_SECONDS']} s. Source: {t['SOURCE']}.", ""]
        (TOOLS / directory / "README.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(tools)} tools -> {out.relative_to(TOOLS)} and {len(CATEGORIES)} category READMEs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

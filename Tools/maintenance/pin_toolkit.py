"""Keep tools 051-100 consistent with ``security_toolkit``.

    python Tools/maintenance/pin_toolkit.py          # rewrite the generated blocks in every tool file
    python Tools/maintenance/pin_toolkit.py --check  # exit 1 if any tool is out of date

It maintains two things in each tool file:
  * ``TOOLKIT_SHA256``: the toolkit digest the tool verifies before importing the toolkit. A tool whose
    pin differs from the toolkit on disk refuses to load, so a registry approval of the tool's hash also
    covers the helper code it runs. Re-pinning changes the tool file's hash: approvals must be renewed.
  * the ``OUTPUT_SCHEMA`` literal between the generated-block markers, rendered from
    ``security_toolkit.core.UNIFIED_OUTPUT_SCHEMA`` (the registry reads it with ``ast``, so it must be a literal).
"""
from __future__ import annotations

import pprint
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
CATEGORIES = ("network_security", "system_security", "privacy_data_protection", "code_dependency_security",
              "cloud_infrastructure")
PIN = re.compile(r'^TOOLKIT_SHA256 = "[0-9a-f]{64}"$', re.M)
BEGIN = "# --- unified output schema: generated by Tools/maintenance/pin_toolkit.py, do not edit ---"
END = "# --- end of generated output schema ---"
BLOCK = re.compile(re.escape(BEGIN) + r"\n.*?\n" + re.escape(END), re.S)


def tool_files() -> list[Path]:
    return sorted(p for c in CATEGORIES for p in (TOOLS / c).glob("*.py") if not p.name.startswith("_"))


def render_schema() -> str:
    from security_toolkit.core import UNIFIED_OUTPUT_SCHEMA

    body = pprint.pformat(UNIFIED_OUTPUT_SCHEMA, width=118, sort_dicts=False)
    return f"{BEGIN}\nOUTPUT_SCHEMA = {body}\n{END}"


def updated(text: str, digest: str, schema: str) -> str:
    if not PIN.search(text) or not BLOCK.search(text):
        raise ValueError("missing TOOLKIT_SHA256 line or generated schema block")
    text = PIN.sub(f'TOOLKIT_SHA256 = "{digest}"', text, count=1)
    return BLOCK.sub(lambda _m: schema, text, count=1)


def main() -> int:
    sys.path.insert(0, str(TOOLS))
    from security_toolkit import digest

    current, schema = digest(), render_schema()
    stale = []
    for path in tool_files():
        text = path.read_text(encoding="utf-8")
        try:
            new = updated(text, current, schema)
        except ValueError as exc:
            print(f"{path.relative_to(TOOLS)}: {exc}", file=sys.stderr)
            return 2
        if new != text:
            stale.append(path)
            if "--check" not in sys.argv:
                path.write_text(new, encoding="utf-8", newline="\n")
    if "--check" in sys.argv:
        for path in stale:
            print(f"out of date: {path.relative_to(TOOLS)}")
        return 1 if stale else 0
    print(f"toolkit {current[:16]}: {len(stale)} of {len(tool_files())} tool file(s) updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

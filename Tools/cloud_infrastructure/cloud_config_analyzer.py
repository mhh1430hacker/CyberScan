def aws_security_groups(ctx, doc):
    for group in doc.get("SecurityGroups") or []:
        name = f"security group {group.get('GroupId')} ({group.get('GroupName', '')})"
        rules = []
        for perm in group.get("IpPermissions") or []:
            sources = [r.get("CidrIp") for r in perm.get("IpRanges") or []] + [r.get("CidrIpv6") for r in perm.get("Ipv6Ranges") or []]
            rules.append({"protocol": perm.get("IpProtocol"), "from_port": perm.get("FromPort"), "to_port": perm.get("ToPort"), "sources": sources})
        cloudrules.check_ingress(ctx, rules, resource=name, prefix="aws.sg")
    return len(doc.get("SecurityGroups") or [])


def aws_instances(ctx, doc):
    count = 0
    for reservation in doc.get("Reservations") or []:
        for instance in reservation.get("Instances") or []:
            count += 1
            name = f"instance {instance.get('InstanceId')}"
            options = instance.get("MetadataOptions") or {}
            if options.get("HttpTokens") == "optional" and options.get("HttpEndpoint", "enabled") == "enabled":
                ctx.finding(f"aws.ec2.imdsv1.{instance.get('InstanceId')}", f"{name} allows IMDSv1", "medium",
                            "Without required session tokens, an SSRF bug in the instance's software can steal its role credentials.",
                            assurance="verified_condition", location=name, recommendation="Set HttpTokens=required (IMDSv2 only).")
            if instance.get("PublicIpAddress") and instance.get("IamInstanceProfile"):
                ctx.finding(f"aws.ec2.public-with-role.{instance.get('InstanceId')}", f"{name} is internet-facing and has an IAM role", "low",
                            "Public instances with roles turn any compromise into cloud-API access; check the role's permissions.",
                            assurance="verified_condition", location=name)
    return count


def aws_rds(ctx, doc):
    for db in doc.get("DBInstances") or []:
        name = f"database {db.get('DBInstanceIdentifier')}"
        if db.get("PubliclyAccessible"):
            ctx.finding(f"aws.rds.public.{db.get('DBInstanceIdentifier')}", f"{name} is publicly accessible", "high",
                        "The database endpoint resolves to a public address.", assurance="verified_condition", location=name)
        if db.get("StorageEncrypted") is False:
            ctx.finding(f"aws.rds.unencrypted.{db.get('DBInstanceIdentifier')}", f"{name} storage is not encrypted", "medium",
                        "Snapshots and disks are stored without encryption at rest.", assurance="verified_condition", location=name)
        if int(db.get("BackupRetentionPeriod") or 0) == 0:
            ctx.finding(f"aws.rds.no-backups.{db.get('DBInstanceIdentifier')}", f"{name} has automated backups disabled", "medium",
                        "BackupRetentionPeriod is 0: point-in-time recovery is impossible.", assurance="verified_condition", location=name)
        if db.get("DeletionProtection") is False:
            ctx.finding(f"aws.rds.no-deletion-protection.{db.get('DBInstanceIdentifier')}", f"{name} has no deletion protection", "low",
                        "One API call can delete it.", assurance="verified_condition", location=name)
    return len(doc.get("DBInstances") or [])


def aws_volumes(ctx, doc):
    unencrypted = [v.get("VolumeId") for v in doc.get("Volumes") or [] if v.get("Encrypted") is False]
    if unencrypted:
        ctx.finding("aws.ebs.unencrypted", f"{len(unencrypted)} EBS volume(s) not encrypted", "medium",
                    f"e.g. {', '.join(unencrypted[:5])}. Enable EBS encryption by default.", assurance="verified_condition", location="volumes")
    return len(doc.get("Volumes") or [])


def aws_trails(ctx, doc):
    trails = doc.get("trailList") or []
    if not trails:
        ctx.finding("aws.cloudtrail.none", "No CloudTrail trail configured", "high",
                    "API activity is not recorded beyond the 90-day event history.", assurance="verified_condition", location="cloudtrail")
    elif not any(t.get("IsMultiRegionTrail") for t in trails):
        ctx.finding("aws.cloudtrail.single-region", "No multi-region CloudTrail trail", "medium",
                    "Activity in other regions is not logged.", assurance="verified_condition", location="cloudtrail")
    for trail in trails:
        name = f"trail {trail.get('Name')}"
        if trail.get("LogFileValidationEnabled") is False:
            ctx.finding(f"aws.cloudtrail.no-validation.{trail.get('Name')}", f"{name} has log file validation off", "low",
                        "Tampering with log files would go unnoticed.", assurance="verified_condition", location=name)
    if doc.get("IsLogging") is False:
        ctx.finding("aws.cloudtrail.stopped", "CloudTrail logging is stopped", "high", "get-trail-status reports IsLogging=false.",
                    assurance="verified_condition", location="cloudtrail")
    return len(trails)


def azure_storage(ctx, doc):
    for account in doc:
        name = f"storage account {account.get('name')}"
        if account.get("allowBlobPublicAccess") is True:
            ctx.finding(f"azure.storage.public-blobs.{account.get('name')}", f"{name} allows public blob access", "high",
                        "Containers in this account can be made anonymously readable.", assurance="verified_condition", location=name)
        if account.get("enableHttpsTrafficOnly", account.get("supportsHttpsTrafficOnly")) is False:
            ctx.finding(f"azure.storage.http.{account.get('name')}", f"{name} accepts plain HTTP", "medium", "Secure transfer is not required.",
                        assurance="verified_condition", location=name)
        if str(account.get("minimumTlsVersion", "TLS1_2")) in ("TLS1_0", "TLS1_1"):
            ctx.finding(f"azure.storage.tls.{account.get('name')}", f"{name} allows {account['minimumTlsVersion']}", "medium",
                        "Require TLS 1.2 or later.", assurance="verified_condition", location=name)
        if (account.get("networkRuleSet") or {}).get("defaultAction") == "Allow":
            ctx.finding(f"azure.storage.network-open.{account.get('name')}", f"{name} accepts traffic from all networks", "low",
                        "The firewall default action is Allow.", assurance="verified_condition", location=name)
    return len(doc)


def azure_nsgs(ctx, doc):
    for nsg in doc:
        name = f"NSG {nsg.get('name')}"
        rules = []
        for rule in nsg.get("securityRules") or []:
            if rule.get("access") != "Allow" or rule.get("direction") != "Inbound":
                continue
            ranges = [rule.get("destinationPortRange")] + list(rule.get("destinationPortRanges") or [])
            for value in [r for r in ranges if r]:
                low, _, high = str(value).partition("-")
                low = None if low == "*" else int(low)
                rules.append({"protocol": rule.get("protocol", "*"), "from_port": low, "to_port": int(high) if high else low,
                              "sources": [rule.get("sourceAddressPrefix")] + list(rule.get("sourceAddressPrefixes") or [])})
        cloudrules.check_ingress(ctx, rules, resource=name, prefix="azure.nsg")
    return len(doc)


def gcp_firewall(ctx, doc):
    for rule in doc:
        if rule.get("direction", "INGRESS") != "INGRESS" or rule.get("disabled"):
            continue
        name = f"firewall rule {rule.get('name')}"
        rules = []
        for allowed in rule.get("allowed") or []:
            ports = allowed.get("ports") or ["0-65535"]
            for port in ports:
                low, _, high = str(port).partition("-")
                rules.append({"protocol": allowed.get("IPProtocol", "all"), "from_port": int(low), "to_port": int(high or low),
                              "sources": rule.get("sourceRanges") or []})
        cloudrules.check_ingress(ctx, rules, resource=name, prefix="gcp.firewall")
    return len(doc)


def gcp_sql(ctx, doc):
    for instance in doc:
        name = f"Cloud SQL {instance.get('name')}"
        ip = ((instance.get("settings") or {}).get("ipConfiguration") or {})
        if any(n.get("value") in ("0.0.0.0/0", "::/0") for n in ip.get("authorizedNetworks") or []):
            ctx.finding(f"gcp.sql.public.{instance.get('name')}", f"{name} authorizes 0.0.0.0/0", "high",
                        "Any address can connect to the database.", assurance="verified_condition", location=name)
        if ip.get("ipv4Enabled") and not ip.get("requireSsl") and ip.get("sslMode") not in ("ENCRYPTED_ONLY", "TRUSTED_CLIENT_CERTIFICATE_REQUIRED"):
            ctx.finding(f"gcp.sql.no-ssl.{instance.get('name')}", f"{name} does not require SSL", "medium",
                        "Connections over the public IP can be unencrypted.", assurance="verified_condition", location=name)
    return len(doc)


def classify(doc):
    if isinstance(doc, dict):
        for key, handler in (("SecurityGroups", aws_security_groups), ("Reservations", aws_instances), ("DBInstances", aws_rds),
                             ("Volumes", aws_volumes), ("trailList", aws_trails), ("IsLogging", aws_trails)):
            if key in doc:
                return key, handler
    if isinstance(doc, list) and doc and isinstance(doc[0], dict):
        first = doc[0]
        if "securityRules" in first:
            return "azure-nsg", azure_nsgs
        if "allowBlobPublicAccess" in first or str(first.get("type", "")).lower() == "microsoft.storage/storageaccounts":
            return "azure-storage", azure_storage
        if "sourceRanges" in first or ("allowed" in first and "network" in first):
            return "gcp-firewall", gcp_firewall
        if "databaseVersion" in first:
            return "gcp-sql", gcp_sql
    return None, None


def _analyze(ctx, data):
    seen = {}
    for item in data["documents"]:
        ctx.check()
        text = text_or_bytes(item, max_bytes=30_000_000)
        try:
            doc = json.loads(text)
        except ValueError as exc:
            raise ToolInputError(f"{item['path']} is not valid JSON (use the CLI's --output json).") from exc
        kind, handler = classify(doc)
        if handler is None:
            ctx.limit(f"{item['path']}: document type not recognised; skipped.")
            continue
        seen[item["path"]] = {"type": kind, "resources": handler(ctx, doc)}
    if not seen:
        raise ToolInputError("None of the documents is a supported cloud export.")
    ctx.input_kind = "+".join(sorted({v["type"] for v in seen.values()}))
    ctx.artifacts["documents"] = seen
    ctx.limit("Only the exported configuration is evaluated; effective access also depends on SCPs, route tables and other layers.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

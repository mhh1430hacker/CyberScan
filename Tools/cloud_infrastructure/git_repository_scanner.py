IGNORE_SUGGESTIONS = {".env": r"(?m)^/?\*?\.env\b|^\.env\*?$", "*.pem": r"(?m)^\*\.pem$|^\*\.(?:key|pem)", "terraform.tfstate": r"(?m)tfstate"}


def _config(ctx, text, where):
    parser = configparser.RawConfigParser(strict=False)
    try:
        parser.read_string(re.sub(r"(?m)^\s+", "", text))
    except configparser.Error as exc:
        raise ToolInputError(f"{where} is not a valid git config ({type(exc).__name__}).") from exc
    for section in parser.sections():
        url = parser.get(section, "url", fallback="")
        if url:
            if re.match(r"(?i)^https?://[^/@\s]+:[^/@\s]+@", url) or re.match(r"(?i)^https?://[^/:@\s]{20,}@", url):
                ctx.finding("git.remote-credentials", f"Credentials embedded in remote URL ({section})", "critical",
                            "The token/password in the URL is stored in clear text and leaks via logs, backups and copied repos.",
                            assurance="verified_condition", location=f"{where} [{section}]", evidence=url,
                            recommendation="Revoke the token, remove it from the URL and use a credential manager or SSH keys.")
            elif url.lower().startswith(("http://", "git://")):
                ctx.finding("git.remote-insecure", f"Remote uses an unencrypted protocol ({section})", "medium",
                            "Fetches can be tampered with on the network.", assurance="verified_condition", location=f"{where} [{section}]", evidence=url)
        if parser.get(section, "sslverify", fallback="").lower() == "false":
            ctx.finding("git.sslverify-off", "http.sslVerify = false", "high", "Git accepts any TLS certificate for remotes.",
                        assurance="verified_condition", location=f"{where} [{section}]")
        if parser.get(section, "helper", fallback="").split(" ")[0] == "store":
            ctx.finding("git.credential-store", "credential.helper = store", "medium",
                        "Passwords and tokens are saved unencrypted in ~/.git-credentials.", assurance="verified_condition", location=f"{where} [{section}]")
        hooks = parser.get(section, "hookspath", fallback="")
        if hooks:
            ctx.finding("git.hooks-path", f"core.hooksPath = {hooks}", "info", "Hooks from this folder run on git commands; review them.",
                        assurance="informational", location=f"{where} [{section}]")


def _modules(ctx, text, where):
    for url in re.findall(r"(?im)^\s*url\s*=\s*(\S+)", text):
        if url.lower().startswith(("http://", "git://")):
            ctx.finding("git.submodule-insecure", "Submodule fetched over an unencrypted protocol", "medium", url, assurance="verified_condition", location=where)
        if re.match(r"(?i)^https?://[^/@\s]+:[^/@\s]+@", url):
            ctx.finding("git.submodule-credentials", "Credentials in a submodule URL", "critical", "Committed for everyone to see.",
                        assurance="verified_condition", location=where, evidence=url)


def _tracked(ctx, paths, gitignore):
    flagged = 0
    for path in paths:
        for pattern, label, severity, why in SENSITIVE:
            if pattern.search(path) and not re.search(r"(?i)(?:^|/)(?:test|tests|fixtures?|examples?|docs?)/", path):
                ctx.finding(f"git.tracked.{label.lower().replace(' ', '-')}", f"{label} in the repository: {path}", severity, why,
                            assurance="verified_condition", location=path, recommendation="Remove it, purge it from history and rotate what it contains.")
                flagged += 1
                break
    if gitignore is not None:
        missing = [name for name, pattern in IGNORE_SUGGESTIONS.items() if not re.search(pattern, gitignore)]
        if missing:
            ctx.finding("git.gitignore-gaps", f".gitignore does not exclude {', '.join(missing)}", "low",
                        "Common secret-bearing files are not ignored, so they are easy to commit by accident.", location=".gitignore")
    return flagged


def _walk(ctx, root):
    base = Path(root)
    if not (base / ".git").exists():
        raise ToolInputError("directory is not a Git working tree (no .git).")
    out = {"config": None, "modules": None, "ignore": None, "paths": [], "texts": []}
    git_dir = base / ".git"
    if git_dir.is_file():  # worktree or submodule: "gitdir: <path>"
        target = git_dir.read_text(encoding="utf-8", errors="replace").partition("gitdir:")[2].strip()
        git_dir = (base / target).resolve()
    if (git_dir / "config").is_file():
        out["config"] = (git_dir / "config").read_text(encoding="utf-8", errors="replace")
    hooks = [h.name for h in (git_dir / "hooks").glob("*") if h.is_file() and not h.name.endswith(".sample")] if (git_dir / "hooks").is_dir() else []
    if hooks:
        ctx.finding("git.active-hooks", f"Active local hooks: {', '.join(sorted(hooks)[:8])}", "info",
                    "Hooks run automatically on git commands; review them if the repository came from someone else.",
                    assurance="informational", location=str(git_dir / "hooks"))
    for name, key in ((".gitmodules", "modules"), (".gitignore", "ignore")):
        if (base / name).is_file():
            out[key] = (base / name).read_text(encoding="utf-8", errors="replace")
    total = 0
    for current, dirs, names in os.walk(base, followlinks=False):
        ctx.check()
        dirs[:] = [d for d in dirs if d not in (".git", "node_modules", ".venv", "venv", "__pycache__", "vendor", "dist", "build", "target")]
        for name in names:
            path = Path(current, name)
            rel = path.relative_to(base).as_posix()
            out["paths"].append(rel)
            if len(out["paths"]) >= 50000:
                ctx.limit("Stopped listing after 50,000 files.", partial=True)
                return out
            try:
                size = path.stat().st_size
            except OSError:
                continue
            if size <= 1024 * 1024 and total < 50 * 1024 * 1024 and not re.search(r"(?i)\.(?:png|jpe?g|gif|pdf|zip|gz|exe|dll|so|bin|woff2?|ico|mp4)$", name):
                try:
                    raw = path.read_bytes()
                except OSError:
                    continue
                if b"\x00" not in raw[:2048]:
                    total += len(raw)
                    out["texts"].append((rel, raw.decode("utf-8", errors="replace")))
    return out


def _analyze(ctx, data):
    scan_contents = data.get("scan_contents", True)
    if data.get("directory"):
        ctx.input_kind = "directory"
        repo = _walk(ctx, data["directory"])
    else:
        ctx.input_kind = "provided"
        texts = file_list(data, max_files=5000) if data.get("files") else []
        repo = {"config": data.get("git_config"), "modules": data.get("gitmodules"), "ignore": data.get("gitignore"),
                "paths": list(data.get("tracked_files") or []) + [p for p, _ in texts], "texts": texts}
        if not any((repo["config"], repo["modules"], repo["paths"])):
            raise ToolInputError("Provide a local directory, or git_config / gitmodules / tracked_files / files.")
    if repo["config"]:
        _config(ctx, repo["config"], ".git/config")
    if repo["modules"]:
        _modules(ctx, repo["modules"], ".gitmodules")
    flagged = _tracked(ctx, repo["paths"], repo["ignore"])
    secrets = 0
    if scan_contents:
        for path, text in repo["texts"]:
            ctx.check()
            for item in secrets_kit.scan(text, max_items=50):
                if item["placeholder"] or secrets_kit.is_test_path(path):
                    continue
                secrets += 1
                ctx.finding(f"git.secret.{item['type']}", f"{item['label']} in {path}", item["severity"],
                            "Committed secrets are visible to everyone with clone access, including in history.",
                            location=f"{path}:{item['line']}")
    ctx.artifacts.update({"files": len(repo["paths"]), "sensitive_files": flagged, "secrets": secrets})
    ctx.limit("Only the current tree is examined; commits in history are not scanned (that needs git or a packfile reader).")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

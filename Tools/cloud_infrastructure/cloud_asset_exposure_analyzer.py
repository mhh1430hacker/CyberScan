# Cloud hostname suffixes where a deleted resource's name can be re-registered by someone else.
TAKEOVER_SUFFIXES = (".s3.amazonaws.com", ".s3-website", ".elasticbeanstalk.com", ".cloudfront.net", ".azurewebsites.net",
                     ".cloudapp.net", ".cloudapp.azure.com", ".blob.core.windows.net", ".trafficmanager.net", ".azureedge.net",
                     ".herokuapp.com", ".herokudns.com", ".github.io", ".netlify.app", ".pages.dev", ".vercel.app", ".firebaseapp.com",
                     ".appspot.com", ".storage.googleapis.com", ".ghost.io", ".myshopify.com", ".wordpress.com", ".zendesk.com")
DATA_TYPES = re.compile(r"(?i)(?:rds|db|database|sql|redis|elasticache|elasticsearch|opensearch|mongo|cosmos|bucket|storage|s3|blob)")


def _public(asset):
    return bool(asset.get("public_ip") or asset.get("internet_facing") or asset.get("public_endpoint"))


def _analyze(ctx, data):
    if data.get("inventory"):
        try:
            doc = json.loads(data["inventory"])
        except ValueError as exc:
            raise ToolInputError("inventory is not valid JSON.") from exc
        assets, records = doc.get("assets") or [], doc.get("dns_records") or []
    else:
        assets, records = data.get("assets") or [], data.get("dns_records") or []
    if not assets and not records:
        raise ToolInputError("Provide an inventory with 'assets' and/or 'dns_records' (see the tool description for the schema).")
    ctx.input_kind = "inventory"
    required = data.get("required_tags") or ["owner"]
    exposure = []
    known_hosts = set()
    for index, asset in enumerate(assets):
        if index % 1000 == 0:
            ctx.check()
        if not isinstance(asset, dict):
            continue
        asset_id = str(asset.get("id") or f"asset-{index}")
        kind = str(asset.get("type", "resource"))
        label = f"{kind} {asset_id}"
        for host in (asset.get("hostname"), asset.get("public_dns"), asset.get("endpoint")):
            if host:
                known_hosts.add(str(host).lower().rstrip("."))
        tags = {str(k).lower(): v for k, v in (asset.get("tags") or {}).items()}
        if not _public(asset):
            continue
        reasons = [r for r, flag in (("public IP", asset.get("public_ip")), ("internet-facing", asset.get("internet_facing")),
                                     ("public endpoint", asset.get("public_endpoint"))) if flag]
        exposure.append({"asset": asset_id, "type": kind, "via": reasons})
        cloudrules.check_ingress(ctx, asset.get("ingress") or [], resource=label, prefix=f"exposure.{asset_id}")
        if DATA_TYPES.search(kind):
            ctx.finding(f"exposure.data-store.{asset_id}", f"{label}: data store reachable from the internet", "high",
                        f"Exposed via {', '.join(reasons)}. Databases and storage should sit behind private networking.",
                        assurance="verified_condition", location=label)
        protocols = {str(l.get("protocol", "")).upper() for l in asset.get("listeners") or [] if isinstance(l, dict)}
        if "HTTP" in protocols and not protocols & {"HTTPS", "TLS"}:
            ctx.finding(f"exposure.http.{asset_id}", f"{label}: serves plain HTTP only", "medium",
                        "The internet-facing listener has no TLS and there is no HTTPS listener beside it.", assurance="verified_condition", location=label)
        missing = [t for t in required if t.lower() not in tags]
        if missing:
            ctx.finding(f"exposure.unowned.{asset_id}", f"{label}: internet-facing without {', '.join(missing)} tag", "low",
                        "Exposed assets without an owner are the ones nobody patches or decommissions.", assurance="verified_condition", location=label)
    for record in records:
        if not isinstance(record, dict) or str(record.get("type", "")).upper() != "CNAME":
            continue
        name = str(record.get("name", "")).rstrip(".").lower()
        target = str(record.get("value", "")).rstrip(".").lower()
        if any(suffix in target for suffix in TAKEOVER_SUFFIXES) and target not in known_hosts:
            ctx.finding(f"dns.dangling.{name}", f"{name} points at {target}, which is not in the inventory", "high",
                        "If that cloud resource was deleted, anyone can create one with the same name and serve content on your "
                        "sub-domain (subdomain takeover). Confirm the target exists in an account you control.",
                        location=name, recommendation="Delete the record or recreate the resource; then re-run this check.")
    ctx.artifacts.update({"assets": len(assets), "internet_facing": exposure[:1000], "dns_records": len(records)})
    ctx.summary = f"{len(exposure)} of {len(assets)} asset(s) are internet-facing; {len(ctx.findings)} finding(s)."
    ctx.limit("Exposure is computed from the inventory alone; route tables, WAFs and provider firewalls in front of assets are not modelled.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

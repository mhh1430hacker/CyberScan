SECRET_NAME = re.compile(r"(?i)(?:password|passwd|secret|token|api_?key|private_?key|credentials?|access_?key)")
DANGEROUS_CAPS = {"SYS_ADMIN", "ALL", "NET_ADMIN", "SYS_PTRACE", "SYS_MODULE", "DAC_READ_SEARCH", "SYS_RAWIO", "BPF"}
DB_PORTS = {"3306", "5432", "6379", "27017", "9200", "1433", "11211", "5984", "2379"}


def _dockerfile(ctx, path, text):
    lines = re.sub(r"\\\r?\n", " ", text).splitlines()
    user, stages, healthcheck = None, 0, False
    for number, raw in enumerate(lines, start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        instruction, _, args = line.partition(" ")
        instruction = instruction.upper()
        where = f"{path}:{number}"
        if instruction == "FROM":
            stages += 1
            image = args.split()[0] if args.split() else ""
            if image.lower() != "scratch" and "@sha256:" not in image and not re.match(r"^\$\{?\w+", image):
                tag = image.rsplit(":", 1)[1] if ":" in image.rsplit("/", 1)[-1] else ""
                if not tag or tag == "latest":
                    ctx.finding("docker.unpinned-image", f"Base image '{image}' is not pinned", "medium",
                                "Without a fixed tag (better: a digest) every build may pull a different, possibly compromised, image.",
                                assurance="verified_condition", location=where)
            user = None  # each stage starts as root again
        elif instruction == "USER":
            user = args.strip()
        elif instruction == "ADD" and re.search(r"https?://", args):
            ctx.finding("docker.add-url", "ADD downloads from a URL", "medium",
                        "ADD from a URL has no checksum verification; use curl with a checksum or COPY.", assurance="verified_condition", location=where)
        elif instruction in ("ENV", "ARG"):
            for name in re.findall(r"([A-Za-z_][\w]*)\s*=", args) or [args.split()[0] if args.split() else ""]:
                if SECRET_NAME.search(name):
                    value = re.search(rf"{re.escape(name)}\s*=\s*(\S+)", args)
                    if value and value.group(1) not in ('""', "''") and not value.group(1).startswith("$"):
                        ctx.finding("docker.secret-in-env", f"Secret-like {instruction} '{name}' has a value", "high",
                                    "ENV and ARG values are stored in the image metadata and history; anyone who pulls the image can read them.",
                                    assurance="verified_condition", location=where, recommendation="Use BuildKit secrets (--mount=type=secret) or runtime injection.")
        elif instruction in ("COPY", "ADD") and re.search(r"(?i)(?:^|\s)(?:\.env|id_rsa|\S+\.pem|\S+\.key|credentials\S*|\.npmrc|\.pypirc)(?:\s|$)", args):
            ctx.finding("docker.copies-secret-file", "A secret file is copied into the image", "high",
                        "Credentials copied into a layer stay in the image even if deleted later.", assurance="verified_condition", location=where)
        elif instruction == "RUN":
            analyze_command(ctx, args, location=where, context="RUN step", prefix="docker.run")
            if re.search(r"\bchmod\s+(?:-R\s+)?0?777\b", args):
                ctx.finding("docker.chmod-777", "chmod 777 in the image", "medium", "World-writable files invite tampering.",
                            assurance="verified_condition", location=where)
            if re.search(r"\bsudo\b", args):
                ctx.finding("docker.sudo", "sudo used in a RUN step", "low", "Build steps already run as the current USER; sudo in images is usually a smell.",
                            assurance="verified_condition", location=where)
        elif instruction == "EXPOSE" and re.search(r"(?:^|\s)22(?:/tcp)?(?:\s|$)", args):
            ctx.finding("docker.ssh", "SSH port exposed", "low", "Containers should not run SSH; use docker exec / kubectl exec.",
                        assurance="verified_condition", location=where)
        elif instruction == "HEALTHCHECK":
            healthcheck = True
    if stages and (user is None or user.split(":")[0] in ("root", "0")):
        ctx.finding("docker.runs-as-root", "Container runs as root", "medium",
                    "The final stage has no USER instruction (or USER root): a container escape or volume mount gives root on the host's files.",
                    assurance="verified_condition", location=path, recommendation="Add a non-root USER in the final stage.")
    if stages and not healthcheck:
        ctx.finding("docker.no-healthcheck", "No HEALTHCHECK", "info", "Orchestrators cannot tell when the app inside is unhealthy.",
                    assurance="informational", location=path)
    for item in secrets_kit.scan(text):
        if not item["placeholder"]:
            ctx.finding(f"docker.secret.{item['type']}", f"{item['label']} in {path}", "high", "Secrets in build files end up in images and repositories.",
                        location=f"{path}:{item['line']}")


def _compose(ctx, path, text):
    docs = load_documents(text, path=path)
    services = (docs[0] or {}).get("services") if docs and isinstance(docs[0], dict) else None
    if not isinstance(services, dict):
        raise ToolInputError(f"{path} has no 'services' section.")
    for name, svc in services.items():
        if not isinstance(svc, dict):
            continue
        where = f"{path}: service {name}"
        if svc.get("privileged") is True:
            ctx.finding(f"compose.privileged.{name}", f"{name} runs privileged", "critical",
                        "A privileged container has full access to the host's devices and kernel; escaping it is trivial.",
                        assurance="verified_condition", location=where)
        for key in ("network_mode", "pid", "ipc"):
            if str(svc.get(key, "")) == "host":
                ctx.finding(f"compose.host-{key}.{name}", f"{name} shares the host {key.replace('_mode', '')} namespace", "high",
                            f"{key}: host removes isolation from the host's {'network' if key == 'network_mode' else key.upper()}.",
                            assurance="verified_condition", location=where)
        for volume in svc.get("volumes") or []:
            source = volume.split(":")[0] if isinstance(volume, str) else str((volume or {}).get("source", ""))
            if source.rstrip("/") in ("/var/run/docker.sock", "/run/docker.sock"):
                ctx.finding(f"compose.docker-socket.{name}", f"{name} mounts the Docker socket", "critical",
                            "Access to the Docker API equals root on the host.", assurance="verified_condition", location=where)
            elif source in ("/", "/etc", "/root", "/proc", "/sys", "/var/lib/docker") or source.startswith(("/etc/", "/root/")):
                ctx.finding(f"compose.host-mount.{name}", f"{name} mounts host path {source}", "high",
                            "Sensitive host directories become writable from the container.", assurance="verified_condition", location=where)
        caps = {str(c).upper().replace("CAP_", "") for c in svc.get("cap_add") or []}
        if caps & DANGEROUS_CAPS:
            ctx.finding(f"compose.capabilities.{name}", f"{name} adds {', '.join(sorted(caps & DANGEROUS_CAPS))}", "high",
                        "These capabilities allow container escape or host network control.", assurance="verified_condition", location=where)
        for option in svc.get("security_opt") or []:
            if re.search(r"(?:seccomp|apparmor)[:=]unconfined", str(option)):
                ctx.finding(f"compose.unconfined.{name}", f"{name} disables {str(option).split(':')[0].split('=')[0]}", "high",
                            "Kernel syscall/MAC filtering is turned off.", assurance="verified_condition", location=where)
        for port in svc.get("ports") or []:
            text_port = str(port if not isinstance(port, dict) else f"{port.get('published')}:{port.get('target')}")
            parts = text_port.split(":")
            if len(parts) == 2 and parts[1].split("/")[0] in DB_PORTS:
                ctx.finding(f"compose.db-published.{name}", f"{name} publishes database port {parts[1]} on all interfaces", "medium",
                            "Bind it to 127.0.0.1 ('127.0.0.1:5432:5432') or remove the mapping.", assurance="verified_condition", location=where)
        environment = svc.get("environment") or {}
        if isinstance(environment, dict):  # mapping form: KEY: value
            pairs = list(environment.items())
        else:  # list form: - KEY=value
            pairs = [tuple((entry.split("=", 1) + [""])[:2]) for entry in environment if isinstance(entry, str)]
        for key, value in pairs:
            if SECRET_NAME.search(str(key)) and value not in (None, "") and not str(value).startswith("${"):
                ctx.finding(f"compose.secret-env.{name}", f"{name}: secret '{key}' set inline", "high",
                            "Use Docker secrets or an env_file excluded from version control.", assurance="verified_condition", location=where)
                break


def _analyze(ctx, data):
    kinds = []
    for path, text in file_list(data, max_files=500):
        ctx.check()
        name = path.rsplit("/", 1)[-1].lower()
        if name == "dockerfile" or name.startswith("dockerfile.") or name.endswith(".dockerfile") or re.match(r"^\s*FROM\s+\S", text, re.I | re.M) and "services:" not in text:
            _dockerfile(ctx, path, text)
            kinds.append("dockerfile")
        elif re.search(r"(?:docker-)?compose[\w.-]*\.ya?ml$", name) or re.search(r"^services:\s*$", text, re.M):
            _compose(ctx, path, text)
            kinds.append("compose")
        else:
            ctx.limit(f"{path}: neither a Dockerfile nor a Compose file; skipped.")
    if not kinds:
        raise ToolInputError("No Dockerfile or Compose file was found.")
    ctx.input_kind = "+".join(sorted(set(kinds)))


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

WORKLOADS = {"Pod", "Deployment", "StatefulSet", "DaemonSet", "ReplicaSet", "Job", "CronJob", "ReplicationController"}
DANGEROUS_CAPS = {"SYS_ADMIN", "ALL", "NET_ADMIN", "SYS_PTRACE", "SYS_MODULE", "DAC_READ_SEARCH", "NET_RAW", "BPF", "SYS_RAWIO"}
SENSITIVE_HOST_PATHS = ("/", "/etc", "/var/run/docker.sock", "/run/containerd", "/var/lib/kubelet", "/root", "/proc", "/sys", "/var/run/crio")
SECRET_NAME = re.compile(r"(?i)(?:password|passwd|secret|token|api_?key|private_?key|credentials?)")


def _pod_spec(doc):
    kind = doc.get("kind")
    spec = doc.get("spec") or {}
    if kind == "Pod":
        return spec
    if kind == "CronJob":
        return (((spec.get("jobTemplate") or {}).get("spec") or {}).get("template") or {}).get("spec") or {}
    return (spec.get("template") or {}).get("spec") or {}


def _workload(ctx, doc, where):
    pod = _pod_spec(doc)
    name = f"{doc.get('kind')}/{(doc.get('metadata') or {}).get('name', '?')}"
    loc = f"{where} {name}"
    for key, title in (("hostNetwork", "host network"), ("hostPID", "host PID namespace"), ("hostIPC", "host IPC namespace")):
        if pod.get(key) is True:
            ctx.finding(f"k8s.{key}", f"{name} uses the {title}", "high", f"{key}: true breaks Pod isolation (PSS baseline).",
                        assurance="verified_condition", location=loc)
    for volume in pod.get("volumes") or []:
        host = (volume or {}).get("hostPath") or {}
        path = str(host.get("path", "")).rstrip("/") or ("/" if host.get("path") == "/" else "")
        if host:
            sensitive = path in SENSITIVE_HOST_PATHS or any(path.startswith(p + "/") for p in SENSITIVE_HOST_PATHS if p != "/")
            ctx.finding("k8s.hostpath" + (".sensitive" if sensitive else ""), f"{name} mounts hostPath {path or '/'}", "critical" if sensitive else "medium",
                        "hostPath volumes expose the node's filesystem" + (" (this path allows node takeover)." if sensitive else "."),
                        assurance="verified_condition", location=loc)
    if pod.get("automountServiceAccountToken") is not False and doc.get("kind") != "Job":
        ctx.finding("k8s.sa-token-automount", f"{name} mounts a service-account token", "info",
                    "Set automountServiceAccountToken: false unless the workload calls the Kubernetes API.", assurance="informational", location=loc)
    pod_security = pod.get("securityContext") or {}
    containers = [(c, "container") for c in pod.get("containers") or []] + [(c, "initContainer") for c in pod.get("initContainers") or []]
    for container, role in containers:
        cname = f"{name}/{container.get('name', '?')}"
        cloc = f"{loc} container {container.get('name', '?')}"  # per-container, so findings are not merged
        sc = container.get("securityContext") or {}
        if sc.get("privileged") is True:
            ctx.finding("k8s.privileged", f"{cname} is privileged", "critical", "Privileged containers can take over the node (PSS baseline).",
                        assurance="verified_condition", location=cloc)
        if sc.get("allowPrivilegeEscalation") is not False:
            ctx.finding("k8s.allow-privilege-escalation", f"{cname} allows privilege escalation", "medium",
                        "allowPrivilegeEscalation is not false (PSS restricted): setuid binaries can gain root.", assurance="verified_condition", location=cloc)
        run_as_user = sc.get("runAsUser", pod_security.get("runAsUser"))
        non_root = sc.get("runAsNonRoot", pod_security.get("runAsNonRoot"))
        if run_as_user == 0:
            ctx.finding("k8s.run-as-root", f"{cname} runs as UID 0", "high", "runAsUser: 0 runs the process as root.", assurance="verified_condition", location=cloc)
        elif non_root is not True and run_as_user is None:
            ctx.finding("k8s.no-run-as-non-root", f"{cname} may run as root", "medium",
                        "Neither runAsNonRoot: true nor a non-zero runAsUser is set (PSS restricted).", assurance="verified_condition", location=cloc)
        caps = {str(c).upper() for c in ((sc.get("capabilities") or {}).get("add") or [])}
        if caps & DANGEROUS_CAPS:
            ctx.finding("k8s.capabilities", f"{cname} adds {', '.join(sorted(caps & DANGEROUS_CAPS))}", "high",
                        "These capabilities are disallowed by PSS baseline.", assurance="verified_condition", location=cloc)
        seccomp = (sc.get("seccompProfile") or pod_security.get("seccompProfile") or {}).get("type")
        if seccomp in (None, "Unconfined"):
            ctx.finding("k8s.no-seccomp", f"{cname} has no seccomp profile", "low",
                        "Set seccompProfile type RuntimeDefault (PSS restricted).", assurance="verified_condition", location=cloc)
        if sc.get("readOnlyRootFilesystem") is not True:
            ctx.finding("k8s.writable-rootfs", f"{cname} has a writable root filesystem", "info",
                        "readOnlyRootFilesystem: true makes tampering harder.", assurance="informational", location=cloc)
        image = str(container.get("image", ""))
        if image and "@sha256:" not in image and (":" not in image.rsplit("/", 1)[-1] or image.endswith(":latest")):
            ctx.finding("k8s.image-latest", f"{cname} uses an unpinned image ({image})", "low",
                        "':latest' or no tag means unreviewed images can roll out.", assurance="verified_condition", location=cloc)
        limits = (container.get("resources") or {}).get("limits") or {}
        if role == "container" and not (limits.get("memory") and limits.get("cpu")):
            ctx.finding("k8s.no-limits", f"{cname} has no CPU/memory limits", "low",
                        "One container can starve the node.", assurance="verified_condition", location=cloc)
        for env in container.get("env") or []:
            if isinstance(env, dict) and SECRET_NAME.search(str(env.get("name", ""))) and isinstance(env.get("value"), str) and env["value"]:
                ctx.finding("k8s.secret-in-env", f"{cname}: secret '{env['name']}' set as a literal", "high",
                            "Use valueFrom.secretKeyRef; literal values are visible to anyone who can read the manifest.",
                            assurance="verified_condition", location=cloc)


def _rbac(ctx, doc, where):
    kind = doc.get("kind")
    name = f"{kind}/{(doc.get('metadata') or {}).get('name', '?')}"
    loc = f"{where} {name}"
    if kind in ("Role", "ClusterRole"):
        for rule in doc.get("rules") or []:
            verbs, resources = set(rule.get("verbs") or []), set(rule.get("resources") or [])
            if "*" in verbs and "*" in resources:
                ctx.finding("rbac.wildcard", f"{name} grants every verb on every resource", "critical" if kind == "ClusterRole" else "high",
                            "Equivalent to cluster-admin within its scope.", assurance="verified_condition", location=loc)
            elif "secrets" in resources and verbs & {"get", "list", "watch", "*"}:
                ctx.finding("rbac.read-secrets", f"{name} can read Secrets", "medium", "Secret read access exposes every credential in scope.",
                            assurance="verified_condition", location=loc)
            if verbs & {"escalate", "bind", "impersonate"} or (resources & {"pods/exec", "pods/attach"} and verbs & {"create", "*"}):
                ctx.finding("rbac.escalation", f"{name} allows escalate/bind/impersonate or pods/exec", "high",
                            "These permissions let the holder gain more privileges or run commands in other pods.",
                            assurance="verified_condition", location=loc)
    elif kind in ("RoleBinding", "ClusterRoleBinding"):
        role = (doc.get("roleRef") or {}).get("name", "")
        for subject in doc.get("subjects") or []:
            subject_name = str(subject.get("name", ""))
            if subject_name in ("system:anonymous", "system:unauthenticated"):
                ctx.finding("rbac.anonymous-binding", f"{name} binds {role} to {subject_name}", "critical",
                            "Unauthenticated users receive these permissions.", assurance="verified_condition", location=loc)
            elif role == "cluster-admin" and subject.get("kind") in ("ServiceAccount", "Group") and subject_name not in ("system:masters",):
                ctx.finding("rbac.cluster-admin-binding", f"{name} grants cluster-admin to {subject.get('kind')} {subject_name}", "high",
                            "cluster-admin for workloads or broad groups is rarely needed.", assurance="verified_condition", location=loc)


def _service(ctx, doc, where):
    spec = doc.get("spec") or {}
    name = f"Service/{(doc.get('metadata') or {}).get('name', '?')}"
    if spec.get("type") in ("LoadBalancer", "NodePort"):
        ranges = spec.get("loadBalancerSourceRanges") or []
        ctx.finding(f"k8s.service-{spec['type'].lower()}", f"{name} is exposed via {spec['type']}", "low" if ranges else "medium",
                    "Reachable from outside the cluster" + ("" if ranges else " with no loadBalancerSourceRanges restriction") + ".",
                    assurance="verified_condition", location=f"{where} {name}")


def _analyze(ctx, data):
    kinds = {}
    for path, text in file_list(data, max_files=1000):
        ctx.check()
        for index, doc in enumerate(load_documents(text, path=path)):
            items = doc.get("items") if isinstance(doc, dict) and doc.get("kind", "").endswith("List") else [doc]
            for item in items or []:
                if not isinstance(item, dict) or "kind" not in item:
                    continue
                kind = item["kind"]
                kinds[kind] = kinds.get(kind, 0) + 1
                where = f"{path}#{index + 1}"
                if kind in WORKLOADS:
                    _workload(ctx, item, where)
                elif kind in ("Role", "ClusterRole", "RoleBinding", "ClusterRoleBinding"):
                    _rbac(ctx, item, where)
                elif kind == "Service":
                    _service(ctx, item, where)
    if not kinds:
        raise ToolInputError("No Kubernetes objects (documents with 'kind') were found.")
    ctx.input_kind = "kubernetes"
    ctx.artifacts["objects"] = kinds
    if "NetworkPolicy" not in kinds and any(k in WORKLOADS for k in kinds):
        ctx.finding("k8s.no-network-policy", "No NetworkPolicy in the supplied manifests", "low",
                    "Without NetworkPolicies every pod can reach every other pod (it may be defined elsewhere).", location="manifests")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

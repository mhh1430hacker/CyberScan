UNTRUSTED = re.compile(r"\$\{\{\s*(github\.event\.(?:issue\.(?:title|body)|pull_request\.(?:title|body|head\.ref|head\.label|head\.repo\.default_branch)|"
                       r"comment\.body|review\.body|review_comment\.body|discussion\.(?:title|body)|head_commit\.(?:message|author\.(?:name|email))|"
                       r"commits\[?\*?\]?\.?\w*|pages\.\*?\.?page_name|workflow_run\.head_branch)|github\.head_ref)\s*\}\}")
PR_HEAD = re.compile(r"github\.event\.pull_request\.head\.(?:sha|ref)|github\.head_ref|refs/pull/")
SECRET_ECHO = re.compile(r"(?:echo|printf|Write-Host|cat)\b[^\n]*\$\{\{\s*secrets\.\w+\s*\}\}")
SHA_PIN = re.compile(r"@[0-9a-f]{40}$")
SECRET_NAME = re.compile(r"(?i)(?:password|passwd|secret|token|api_?key|private_?key|access_?key)")


def _triggers(workflow):
    on = workflow.get("on", workflow.get(True))  # YAML 1.1 reads an unquoted 'on' key as boolean True
    if isinstance(on, str):
        return {on}
    if isinstance(on, list):
        return set(on)
    if isinstance(on, dict):
        return set(on)
    return set()


def _github(ctx, path, workflow, public):
    triggers = _triggers(workflow)
    privileged_trigger = bool(triggers & {"pull_request_target", "workflow_run"})
    if "permissions" not in workflow:
        ctx.finding("gha.no-permissions", f"{path}: no top-level permissions block", "low",
                    "The GITHUB_TOKEN gets the repository's default permissions, which may include write access.",
                    assurance="verified_condition", location=path, recommendation="Add 'permissions: contents: read' and widen per job.")
    elif workflow.get("permissions") == "write-all":
        ctx.finding("gha.write-all", f"{path}: permissions: write-all", "medium", "Every job token can push code and change releases.",
                    assurance="verified_condition", location=path)
    for job_name, job in (workflow.get("jobs") or {}).items():
        if not isinstance(job, dict):
            continue
        where = f"{path} job {job_name}"
        runs_on = job.get("runs-on")
        labels = runs_on if isinstance(runs_on, list) else [runs_on]
        if "self-hosted" in labels and triggers & {"pull_request", "pull_request_target"} and public:
            ctx.finding("gha.self-hosted-pr", f"{where}: self-hosted runner on pull-request trigger", "high",
                        "Anyone can open a PR in a public repository and run code on your runner machine.", assurance="verified_condition", location=where)
        if job.get("permissions") == "write-all":
            ctx.finding("gha.job-write-all", f"{where}: permissions: write-all", "medium", "Broad token for this job.",
                        assurance="verified_condition", location=where)
        env_blocks = [workflow.get("env") or {}, job.get("env") or {}]
        for step_index, step in enumerate(job.get("steps") or []):
            if not isinstance(step, dict):
                continue
            step_where = f"{where} step {step.get('name') or step_index + 1}"
            uses = str(step.get("uses", ""))
            if uses and not uses.startswith("./"):
                if uses.startswith("docker://"):
                    if uses.endswith(":latest") or ":" not in uses[len("docker://"):]:
                        ctx.finding("gha.docker-unpinned", f"{step_where}: docker action not pinned ({uses})", "low", "Pin the image by digest.",
                                    assurance="verified_condition", location=step_where)
                elif not SHA_PIN.search(uses):
                    first_party = uses.split("/")[0] in ("actions", "github")
                    ctx.finding(f"gha.unpinned-action.{uses.split('@')[0]}", f"{step_where}: {uses} is not pinned to a commit SHA",
                                "info" if first_party else "low",
                                "A tag can be moved to malicious code (as in the 2025 tj-actions/changed-files compromise); pin third-party "
                                "actions to a full commit SHA.", assurance="informational" if first_party else "verified_condition", location=step_where)
            if privileged_trigger and uses.startswith("actions/checkout"):
                ref = str((step.get("with") or {}).get("ref", ""))
                if PR_HEAD.search(ref):
                    ctx.finding("gha.pwn-request", f"{step_where}: {'/'.join(sorted(triggers & {'pull_request_target', 'workflow_run'}))} checks out PR code",
                                "critical", "The workflow runs with secrets and a write token, and then checks out and runs code from the pull "
                                "request: any contributor can steal the secrets ('pwn request').", assurance="verified_condition", location=step_where,
                                recommendation="Use pull_request for untrusted code, or split into an unprivileged build and a privileged follow-up.")
            script = str(step.get("run", "")) + "\n" + str((step.get("with") or {}).get("script", "") if "github-script" in uses else "")
            for match in UNTRUSTED.finditer(script):
                ctx.finding("gha.script-injection", f"{step_where}: {match.group(1)} interpolated into a script", "high",
                            "Attacker-controlled text (titles, branch names, comments) is inserted into the shell script before it runs.",
                            assurance="verified_condition", location=step_where, evidence=match.group(0),
                            recommendation="Pass it through an environment variable: env: TITLE: ${{ ... }} and use \"$TITLE\".")
            if SECRET_ECHO.search(script):
                ctx.finding("gha.secret-echo", f"{step_where}: a secret is printed", "high", "Masking can be bypassed (e.g. base64); never echo secrets.",
                            assurance="verified_condition", location=step_where)
            if step.get("run"):
                analyze_command(ctx, str(step["run"]).replace("\n", " ; "), location=step_where, context="CI step", prefix="gha.run")
            env_blocks.append(step.get("env") or {})
        if any(str(env.get("ACTIONS_ALLOW_UNSECURE_COMMANDS", "")).lower() == "true" for env in env_blocks if isinstance(env, dict)):
            ctx.finding("gha.unsecure-commands", f"{where}: ACTIONS_ALLOW_UNSECURE_COMMANDS enabled", "high",
                        "Re-enables set-env/add-path workflow commands, which allow injection through logs.", assurance="verified_condition", location=where)


def _gitlab(ctx, path, config):
    variables = config.get("variables") or {}
    for name, value in (variables.items() if isinstance(variables, dict) else []):
        literal = value.get("value") if isinstance(value, dict) else value
        if SECRET_NAME.search(str(name)) and isinstance(literal, str) and literal and not literal.startswith("$"):
            ctx.finding("gitlab.secret-variable", f"{path}: secret variable '{name}' defined in the file", "high",
                        "Use masked, protected CI/CD variables in project settings instead.", assurance="verified_condition", location=path)
    for name, job in config.items():
        if not isinstance(job, dict) or name.startswith(".") and not job.get("script"):
            continue
        where = f"{path} job {name}"
        image = job.get("image", config.get("image"))
        image = image.get("name") if isinstance(image, dict) else image
        if isinstance(image, str) and (image.endswith(":latest") or ":" not in image.rsplit("/", 1)[-1]) and name not in ("variables", "stages", "default"):
            ctx.finding(f"gitlab.unpinned-image.{name}", f"{where}: image '{image}' is not pinned", "low", "Pin a tag or digest.",
                        assurance="verified_condition", location=where)
        for service in job.get("services") or []:
            service_name = service.get("name") if isinstance(service, dict) else str(service)
            if "dind" in str(service_name):
                ctx.finding(f"gitlab.dind.{name}", f"{where}: Docker-in-Docker service", "info",
                            "dind requires privileged runners; a malicious job can escape to the runner host.", assurance="informational", location=where)
        for line in (job.get("script") or []) + (job.get("before_script") or []):
            analyze_command(ctx, str(line), location=where, context="CI script", prefix="gitlab.script")


def _jenkins(ctx, path, text):
    for number, line in enumerate(text.splitlines(), start=1):
        if re.search(r"\b(?:sh|bat|powershell)\s*\(?\s*\"[^\"]*\$\{?(?:params|env\.CHANGE_TITLE|env\.BRANCH_NAME|env\.CHANGE_BRANCH)", line):
            ctx.finding("jenkins.param-injection", "Build parameter interpolated into a shell step", "high",
                        "Groovy expands the value inside a double-quoted string before the shell runs it; use single quotes and $VAR.",
                        assurance="verified_condition", location=f"{path}:{number}", evidence=line.strip())
        match = re.search(r"\b(?:sh|bat)\s*\(?\s*['\"]{1,3}(.+?)['\"]{1,3}", line)
        if match:
            analyze_command(ctx, match.group(1), location=f"{path}:{number}", context="Jenkins step", prefix="jenkins.sh")


def _analyze(ctx, data):
    public = data.get("public_repository", True)
    kinds = []
    for path, text in file_list(data, max_files=500):
        ctx.check()
        lower = path.lower()
        if lower.endswith("jenkinsfile") or lower.endswith(".jenkinsfile"):
            _jenkins(ctx, path, text)
            kinds.append("jenkins")
        elif lower.endswith((".yml", ".yaml")):
            docs = load_documents(text, path=path)
            doc = docs[0] if docs and isinstance(docs[0], dict) else {}
            if "jobs" in doc and ("on" in doc or True in doc):
                _github(ctx, path, doc, public)
                kinds.append("github-actions")
            elif lower.endswith(".gitlab-ci.yml") or "stages" in doc or any(isinstance(v, dict) and "script" in v for v in doc.values()):
                _gitlab(ctx, path, doc)
                kinds.append("gitlab-ci")
            else:
                ctx.limit(f"{path}: not a recognised pipeline definition; skipped.")
                continue
        else:
            ctx.limit(f"{path}: unsupported pipeline format; skipped.")
            continue
        for item in secrets_kit.scan(text):
            if not item["placeholder"]:
                ctx.finding(f"ci.secret.{item['type']}", f"{item['label']} in {path}", "high", "Pipeline files are visible to every contributor.",
                            location=f"{path}:{item['line']}")
    if not kinds:
        raise ToolInputError("No GitHub Actions workflow, GitLab CI file or Jenkinsfile was recognised.")
    ctx.input_kind = "+".join(sorted(set(kinds)))


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

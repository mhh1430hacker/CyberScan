PUBLIC_ACLS = {"public-read", "public-read-write", "authenticated-read", "publicread", "publicreadwrite", "authenticatedread"}


def _list(value):
    return value if isinstance(value, list) else [] if value is None else [value]


def _literal(value):
    return None if isinstance(value, dict) and "__expr__" in value else value


def _check(ctx, kind, name, props, where, unknown):
    """Provider-neutral checks on one AWS resource (Terraform or CloudFormation property names)."""
    resource = f"{kind} {name} ({where})"
    get = lambda *keys: next((props[k] for k in keys if k in props), None)
    if kind in ("aws_security_group", "aws_security_group_rule", "AWS::EC2::SecurityGroup", "AWS::EC2::SecurityGroupIngress",
                "aws_vpc_security_group_ingress_rule"):
        rules = []
        ingress = _list(props.get("ingress")) + _list(props.get("SecurityGroupIngress"))
        if kind in ("aws_security_group_rule",) and _literal(props.get("type")) == "ingress" or kind in ("AWS::EC2::SecurityGroupIngress", "aws_vpc_security_group_ingress_rule"):
            ingress.append(props)
        for rule in ingress:
            if not isinstance(rule, dict):
                continue
            sources = [_literal(c) for c in _list(rule.get("cidr_blocks")) + _list(rule.get("ipv6_cidr_blocks"))]
            sources += [_literal(rule.get(k)) for k in ("CidrIp", "CidrIpv6", "cidr_ipv4", "cidr_ipv6") if rule.get(k) is not None]
            if any(s is None for s in sources):
                unknown.append(f"{resource}: CIDR from an expression")
            rules.append({"protocol": _literal(get_from(rule, "protocol", "IpProtocol", "ip_protocol")) or "tcp",
                          "from_port": _int(get_from(rule, "from_port", "FromPort")), "to_port": _int(get_from(rule, "to_port", "ToPort")),
                          "sources": [s for s in sources if s]})
        cloudrules.check_ingress(ctx, rules, resource=resource, prefix="iac.sg")
    elif kind in ("aws_s3_bucket", "aws_s3_bucket_acl", "AWS::S3::Bucket"):
        acl = str(_literal(get("acl", "AccessControl")) or "").lower()
        if acl in PUBLIC_ACLS:
            ctx.finding("iac.s3.public-acl", f"{resource}: bucket ACL '{acl}'", "critical" if "write" in acl else "high",
                        "The canned ACL makes the bucket readable (or writable) by everyone.", assurance="verified_condition", location=where)
        block = props.get("PublicAccessBlockConfiguration")
        if isinstance(block, dict):
            _public_access_block(ctx, resource, where, {k: _literal(v) for k, v in block.items()})
        if kind == "AWS::S3::Bucket" and "BucketEncryption" not in props:
            ctx.finding("iac.s3.no-encryption-config", f"{resource}: no BucketEncryption", "info",
                        "S3 encrypts new objects with SSE-S3 by default since 2023; set SSE-KMS explicitly if you need key control.",
                        assurance="informational", location=where)
    elif kind == "aws_s3_bucket_public_access_block":
        _public_access_block(ctx, resource, where, {k: _literal(v) for k, v in props.items()})
    elif kind in ("aws_s3_bucket_policy", "AWS::S3::BucketPolicy"):
        policy = _literal(get("policy", "PolicyDocument"))
        if isinstance(policy, (str, dict)):
            cloudrules.check_resource_policy(ctx, policy, resource=resource, prefix="iac.s3-policy")
        else:
            unknown.append(f"{resource}: policy built with an expression (jsonencode/data source)")
    elif kind in ("aws_db_instance", "aws_rds_cluster", "AWS::RDS::DBInstance", "AWS::RDS::DBCluster"):
        if _literal(get("publicly_accessible", "PubliclyAccessible")) in (True, "true"):
            ctx.finding("iac.rds.public", f"{resource}: database is publicly accessible", "high", "The endpoint gets a public address.",
                        assurance="verified_condition", location=where)
        if _literal(get("storage_encrypted", "StorageEncrypted")) in (False, "false", None) and not get("kms_key_id", "KmsKeyId"):
            ctx.finding("iac.rds.unencrypted", f"{resource}: storage encryption not enabled", "medium",
                        "storage_encrypted is false or unset (the default is unencrypted).", assurance="verified_condition", location=where)
        if _literal(get("backup_retention_period", "BackupRetentionPeriod")) in (0, "0"):
            ctx.finding("iac.rds.no-backups", f"{resource}: automated backups disabled", "medium", "backup_retention_period = 0.",
                        assurance="verified_condition", location=where)
    elif kind in ("aws_ebs_volume", "AWS::EC2::Volume"):
        if _literal(get("encrypted", "Encrypted")) in (False, "false", None):
            ctx.finding("iac.ebs.unencrypted", f"{resource}: volume not encrypted", "medium", "encrypted is false or unset.",
                        assurance="verified_condition", location=where)
    elif kind in ("aws_instance", "aws_launch_template", "AWS::EC2::Instance", "AWS::EC2::LaunchTemplate"):
        options = (_list(props.get("metadata_options")) or [{}])[0]
        data = props.get("LaunchTemplateData") or props
        cfn_options = (data.get("MetadataOptions") if isinstance(data, dict) else None) or {}
        tokens = _literal(options.get("http_tokens")) if isinstance(options, dict) else None
        tokens = tokens or _literal(cfn_options.get("HttpTokens"))
        if tokens != "required":
            ctx.finding("iac.ec2.imdsv1", f"{resource}: IMDSv2 not required", "medium",
                        "http_tokens is not 'required', so SSRF bugs can read instance role credentials from IMDSv1.",
                        assurance="verified_condition", location=where)
        if _literal(get("associate_public_ip_address")) is True:
            ctx.finding("iac.ec2.public-ip", f"{resource}: instance gets a public IP", "low", "Confirm the instance must be internet-facing.",
                        assurance="verified_condition", location=where)
    elif kind in ("aws_iam_policy", "aws_iam_role_policy", "aws_iam_user_policy", "aws_iam_group_policy", "AWS::IAM::Policy",
                  "AWS::IAM::ManagedPolicy"):
        policy = _literal(get("policy", "PolicyDocument"))
        if isinstance(policy, (str, dict)):
            cloudrules.check_identity_policy(ctx, policy, resource=resource, prefix="iac.iam")
        else:
            unknown.append(f"{resource}: policy built with an expression")
    elif kind in ("aws_iam_role", "AWS::IAM::Role"):
        trust = _literal(get("assume_role_policy", "AssumeRolePolicyDocument"))
        if isinstance(trust, (str, dict)):
            cloudrules.check_trust_policy(ctx, trust, resource=resource, prefix="iac.trust")
        for inline in _list(props.get("Policies")):
            if isinstance(inline, dict) and isinstance(inline.get("PolicyDocument"), dict):
                cloudrules.check_identity_policy(ctx, inline["PolicyDocument"], resource=resource, prefix="iac.iam")


def get_from(rule, *keys):
    return next((rule[k] for k in keys if k in rule), None)


def _int(value):
    value = _literal(value)
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _public_access_block(ctx, resource, where, block):
    names = {"block_public_acls": "BlockPublicAcls", "ignore_public_acls": "IgnorePublicAcls", "block_public_policy": "BlockPublicPolicy",
             "restrict_public_buckets": "RestrictPublicBuckets"}
    off = [cfn for tf, cfn in names.items() if block.get(tf, block.get(cfn)) in (False, "false")]
    if off:
        ctx.finding("iac.s3.block-public-access-off", f"{resource}: Block Public Access settings disabled", "medium",
                    f"Disabled: {', '.join(off)}.", assurance="verified_condition", location=where)


def _terraform(ctx, path, text, unknown):
    try:
        blocks = parse_hcl(text)
    except HclError as exc:
        raise ToolInputError(f"{path}: Terraform could not be parsed ({exc}).") from exc
    count = 0
    for block in blocks:
        if block["type"] != "resource" or len(block["labels"]) < 2:
            continue
        count += 1
        kind, name = block["labels"][0], block["labels"][1]
        body = dict(block["body"])
        for key in ("policy", "assume_role_policy"):
            if isinstance(body.get(key), str) and body[key].strip().startswith("{"):
                try:
                    body[key] = json.loads(body[key])
                except ValueError:
                    pass
        _check(ctx, kind, name, body, f"{path}:{block['line']}", unknown)
    return count


def _cloudformation(ctx, path, text, unknown):
    docs = load_documents(text, path=path)
    count = 0
    for doc in docs:
        resources = doc.get("Resources") if isinstance(doc, dict) else None
        if not isinstance(resources, dict):
            continue
        for logical_id, resource in resources.items():
            if not isinstance(resource, dict):
                continue
            count += 1
            props = resource.get("Properties") or {}
            props = {k: v for k, v in props.items()}
            for key, value in list(props.items()):
                if isinstance(value, dict) and len(value) == 1 and next(iter(value)).startswith(("!", "Fn::", "Ref")):
                    props[key] = {"__expr__": json.dumps(value)[:200]}
            _check(ctx, str(resource.get("Type", "")), logical_id, props, f"{path}:{logical_id}", unknown)
    return count


def _analyze(ctx, data):
    files = file_list(data, max_files=1000)
    unknown, counts = [], {"terraform": 0, "cloudformation": 0}
    for path, text in files:
        ctx.check()
        if path.endswith(".tf"):
            counts["terraform"] += _terraform(ctx, path, text, unknown)
        elif path.endswith((".yaml", ".yml", ".json", ".template")) and re.search(r"AWSTemplateFormatVersion|\bResources\b", text):
            counts["cloudformation"] += _cloudformation(ctx, path, text, unknown)
        else:
            ctx.limit(f"{path}: not a Terraform (.tf) or CloudFormation template; skipped.")
    if not any(counts.values()):
        raise ToolInputError("No Terraform resources or CloudFormation Resources were found.")
    ctx.input_kind = "+".join(k for k, v in counts.items() if v)
    ctx.artifacts.update({"resources": counts, "unresolved": unknown[:50]})
    if unknown:
        ctx.limit(f"{len(unknown)} value(s) come from expressions, variables or data sources and were not evaluated.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

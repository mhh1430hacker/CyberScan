PRIMITIVE_ROLES = {"roles/owner": "high", "roles/editor": "medium"}


def _date(value):
    try:
        return dt.datetime.fromisoformat(value.replace("Z", "+00:00")).date()
    except (AttributeError, ValueError):
        return None


def _credential_report(ctx, text, today, max_age):
    rows = list(csv.DictReader(io.StringIO(text.lstrip("﻿"))))
    if not rows or "user" not in rows[0]:
        raise ToolInputError("credential_report must be the CSV from 'aws iam get-credential-report' (decoded).")
    for row in rows:
        user = row["user"]
        where = f"user {user}"
        keys = [k for k in ("1", "2") if row.get(f"access_key_{k}_active") == "true"]
        if user == "<root_account>":
            if keys:
                ctx.finding("root.access-keys", "Root account has active access keys", "critical",
                            "Root keys cannot be restricted by IAM policy; delete them and use roles.", assurance="verified_condition", location=where)
            if row.get("mfa_active") != "true":
                ctx.finding("root.no-mfa", "Root account has no MFA", "critical", "The account's most powerful login is protected by a password only.",
                            assurance="verified_condition", location=where)
            used = _date(row.get("password_last_used", ""))
            if used and (today - used).days < 30:
                ctx.finding("root.recent-use", f"Root account signed in on {used}", "low", "Daily work should not use root.",
                            assurance="verified_condition", location=where)
            continue
        if row.get("password_enabled") == "true" and row.get("mfa_active") != "true":
            ctx.finding(f"user.no-mfa.{user}", f"{user} can sign in without MFA", "high", "Console access is protected by a password only.",
                        assurance="verified_condition", location=where)
        for key in keys:
            rotated = _date(row.get(f"access_key_{key}_last_rotated", ""))
            used = _date(row.get(f"access_key_{key}_last_used_date", ""))
            if rotated and (today - rotated).days > max_age:
                ctx.finding(f"user.old-key.{user}.{key}", f"{user}: access key {key} is {(today - rotated).days} days old", "medium",
                            f"Keys older than {max_age} days should be rotated.", assurance="verified_condition", location=where)
            if rotated and (used is None or (today - used).days > 90) and (today - rotated).days > 90:
                ctx.finding(f"user.unused-key.{user}.{key}", f"{user}: access key {key} unused for 90+ days", "low",
                            "Unused active keys are pure risk; deactivate them.", assurance="verified_condition", location=where)
    return len(rows)


def _azure(ctx, text):
    try:
        roles = json.loads(text)
    except ValueError as exc:
        raise ToolInputError("azure_role_definitions is not valid JSON.") from exc
    for role in roles if isinstance(roles, list) else [roles]:
        name = role.get("roleName") or role.get("name") or "role"
        if role.get("roleType", "CustomRole") != "CustomRole":
            continue
        for permission in role.get("permissions") or [{"actions": role.get("actions", [])}]:
            actions = permission.get("actions") or []
            if "*" in actions:
                ctx.finding(f"azure.role-wildcard.{name}", f"Custom role {name} allows all actions (*)", "critical",
                            "Equivalent to Owner within its assignable scopes.", assurance="verified_condition", location=name)
            elif any(a.lower().startswith("microsoft.authorization/") and a.endswith(("*", "write")) for a in actions):
                ctx.finding(f"azure.role-authorization.{name}", f"Custom role {name} can change role assignments", "high",
                            "Microsoft.Authorization write access lets the holder grant itself any role.", assurance="verified_condition", location=name)
        if "/" in (role.get("assignableScopes") or []):
            ctx.finding(f"azure.role-root-scope.{name}", f"Custom role {name} is assignable at the tenant root", "low",
                        "Root-scope custom roles apply everywhere.", assurance="verified_condition", location=name)
    return len(roles) if isinstance(roles, list) else 1


def _gcp(ctx, text):
    try:
        policy = json.loads(text)
    except ValueError as exc:
        raise ToolInputError("gcp_iam_policy is not valid JSON.") from exc
    for binding in policy.get("bindings") or []:
        role = binding.get("role", "")
        members = binding.get("members") or []
        public = [m for m in members if m in ("allUsers", "allAuthenticatedUsers")]
        if public:
            ctx.finding(f"gcp.public.{role}", f"{role} granted to {', '.join(public)}", "critical",
                        "A public member holds a project-level role.", assurance="verified_condition", location=role)
        if role in PRIMITIVE_ROLES:
            users = [m for m in members if m.startswith(("user:", "serviceAccount:", "group:"))]
            if users:
                ctx.finding(f"gcp.primitive.{role}", f"Primitive role {role} granted to {len(users)} member(s)", PRIMITIVE_ROLES[role],
                            "Owner/Editor cover almost every service; use predefined least-privilege roles.", assurance="verified_condition",
                            location=role, evidence=", ".join(users[:5]))
        if role == "roles/iam.serviceAccountTokenCreator" and any(m.startswith("user:") for m in members):
            ctx.finding("gcp.token-creator", "Users can mint tokens for service accounts", "medium",
                        "serviceAccountTokenCreator at project level lets users impersonate every service account.",
                        assurance="verified_condition", location=role)
    return len(policy.get("bindings") or [])


def _analyze(ctx, data):
    today = dt.date.fromisoformat(data["today"]) if data.get("today") else dt.date.today()
    counts, kinds = {}, []
    for policy in data.get("policies") or []:
        ctx.check()
        document = cloudrules.load_policy(policy["document"])
        if document is None:
            raise ToolInputError(f"Policy '{policy['name'][:60]}' is not valid JSON.")
        document = document.get("PolicyVersion", {}).get("Document", document) if "PolicyVersion" in document else document
        kind = policy.get("kind") or ("trust" if any("sts:AssumeRole" in json.dumps(s) and s.get("Principal") for s in
                                                      cloudrules._as_list(document.get("Statement")) if isinstance(s, dict)) else "identity")
        if kind == "trust":
            cloudrules.check_trust_policy(ctx, document, resource=policy["name"])
        else:
            cloudrules.check_identity_policy(ctx, document, resource=policy["name"])
        counts[kind] = counts.get(kind, 0) + 1
    if counts:
        kinds.append("policies")
    if data.get("credential_report"):
        counts["credential_report_rows"] = _credential_report(ctx, data["credential_report"], today, int(data.get("max_key_age_days") or 90))
        kinds.append("credential-report")
    if data.get("azure_role_definitions"):
        counts["azure_roles"] = _azure(ctx, data["azure_role_definitions"])
        kinds.append("azure")
    if data.get("gcp_iam_policy"):
        counts["gcp_bindings"] = _gcp(ctx, data["gcp_iam_policy"])
        kinds.append("gcp")
    if not kinds:
        raise ToolInputError("Provide policies, credential_report, azure_role_definitions or gcp_iam_policy.")
    ctx.input_kind = "+".join(kinds)
    ctx.artifacts["counts"] = counts
    ctx.limit("Policies are evaluated one at a time; permission boundaries, SCPs and resource policies can further restrict them.")



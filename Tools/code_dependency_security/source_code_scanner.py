def _python(ctx, text, path):
    tree = ts.parse_python(text)
    if tree is None:
        ctx.limit(f"{path} could not be parsed as Python; it was skipped.")
        return
    aliases = ts.import_aliases(tree)
    for call in ts.iter_calls(tree):
        name = ts.call_name(call, aliases)
        line = call.lineno
        where = f"{path}:{line}"
        first = call.args[0] if call.args else None
        if name in ("eval", "exec", "builtins.eval", "builtins.exec") and first is not None and not ts.is_constant_string(first):
            ctx.finding("py.eval", f"{name}() on a non-literal value", "high", "Evaluating dynamic input runs arbitrary code (CWE-95).",
                        location=where, evidence=ts.excerpt(text, line))
        elif name.startswith("subprocess.") and isinstance(ts.keyword(call, "shell"), ast.Constant) and ts.keyword(call, "shell").value is True:
            dynamic = first is not None and not ts.is_constant_string(first)
            ctx.finding("py.shell-true", "subprocess with shell=True" + (" and a built command" if dynamic else ""), "high" if dynamic else "low",
                        "shell=True passes the command to a shell; with interpolated input this is command injection (CWE-78). "
                        "Pass an argument list without shell=True.", location=where, evidence=ts.excerpt(text, line))
        elif name in ("os.system", "os.popen", "commands.getoutput") and first is not None and not ts.is_constant_string(first):
            ctx.finding("py.os-system", f"{name}() with a built command", "high", "Runs a shell with dynamic input (CWE-78).",
                        location=where, evidence=ts.excerpt(text, line))
        elif name in ("hashlib.md5", "hashlib.sha1") or (name == "hashlib.new" and ts.is_constant_string(first) and first.value.lower() in ("md5", "sha1")):
            used_for_security = ts.keyword(call, "usedforsecurity")
            if not (isinstance(used_for_security, ast.Constant) and used_for_security.value is False):
                ctx.finding("py.weak-hash", "MD5/SHA-1 hash", "low", "Fine for checksums, broken for passwords or signatures (CWE-327). "
                            "Pass usedforsecurity=False to document non-security use.", location=where, evidence=ts.excerpt(text, line))
        elif name.startswith("random.") and name.split(".")[-1] in ("random", "randint", "choice", "choices", "getrandbits", "randrange", "sample"):
            target = ts.excerpt(text, line)
            if SECRET_NAME.search(target.split("=")[0] if "=" in target else target):
                ctx.finding("py.insecure-random", "random module used for a secret", "medium",
                            "The random module is predictable; use the secrets module (CWE-330).", location=where, evidence=target)
        elif name.split(".")[0] in ("requests", "httpx", "urllib3") and isinstance(ts.keyword(call, "verify"), ast.Constant) and ts.keyword(call, "verify").value is False:
            ctx.finding("py.tls-verify-false", "TLS verification disabled (verify=False)", "high",
                        "The request accepts any certificate, so it can be intercepted (CWE-295).", location=where, evidence=ts.excerpt(text, line))
        elif name in ("ssl._create_unverified_context",):
            ctx.finding("py.ssl-unverified", "Unverified SSL context", "high", "Certificates are not checked (CWE-295).", location=where)
        elif name in ("tempfile.mktemp",):
            ctx.finding("py.mktemp", "tempfile.mktemp() race condition", "medium", "Use NamedTemporaryFile/mkstemp (CWE-377).", location=where)
        elif name.endswith(".run") and isinstance(ts.keyword(call, "debug"), ast.Constant) and ts.keyword(call, "debug").value is True:
            ctx.finding("py.debug-mode", "Application started in debug mode", "medium",
                        "Debug servers (Flask/Werkzeug) expose an interactive debugger that runs code (CWE-489).", location=where)
        elif name in ("jwt.decode",):
            options = ts.keyword(call, "options")
            algorithms = ts.keyword(call, "algorithms")
            unsafe = (isinstance(options, ast.Dict) and any(isinstance(k, ast.Constant) and k.value == "verify_signature" and
                                                            isinstance(v, ast.Constant) and v.value is False for k, v in zip(options.keys, options.values)))
            unsafe = unsafe or (isinstance(algorithms, (ast.List, ast.Tuple)) and any(isinstance(e, ast.Constant) and str(e.value).lower() == "none" for e in algorithms.elts))
            if unsafe:
                ctx.finding("py.jwt-unverified", "JWT decoded without signature verification", "high",
                            "Anyone can forge tokens that this code accepts (CWE-347).", location=where, evidence=ts.excerpt(text, line))
        elif name == "os.chmod" and len(call.args) > 1 and isinstance(call.args[1], ast.Constant) and isinstance(call.args[1].value, int) and call.args[1].value & 0o002:
            ctx.finding("py.world-writable", "os.chmod makes a file world-writable", "medium", "Any local user can modify it (CWE-732).", location=where)
    for node in ast.walk(tree):
        if isinstance(node, ast.Attribute) and node.attr == "CERT_NONE" and ts.dotted_name(node).startswith("ssl"):
            ctx.finding("py.cert-none", "ssl.CERT_NONE", "high", "Certificate verification is turned off (CWE-295).", location=f"{path}:{node.lineno}")


def _analyze(ctx, data):
    if data.get("files"):
        files = file_list(data)
    elif data.get("content") is not None:
        files = [(data.get("path") or "input.py", data["content"])]
    else:
        raise ToolInputError("Provide files [{path, content}] or content with a path.")
    ctx.input_kind = "source"
    languages = {}
    for path, text in files:
        ctx.check()
        language = ts.language_of(path, text)
        languages[language] = languages.get(language, 0) + 1
        if language == "python":
            _python(ctx, text, path)
        elif language != "unknown":
            ts.apply_rules(ctx, text, REGEX_RULES, path=path, language=language)
    ctx.artifacts.update({"files": len(files), "languages": languages})
    if languages.get("unknown"):
        ctx.limit(f"{languages['unknown']} file(s) had no recognized language and were skipped.")
    ctx.limit("Non-Python languages use line patterns without data-flow analysis; review each finding in context.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

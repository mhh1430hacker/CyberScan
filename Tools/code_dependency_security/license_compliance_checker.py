def normalize(identifier):
    token = identifier.strip().strip("()")
    lowered = token.lower()
    if lowered in ALIASES:
        return ALIASES[lowered]
    token = re.sub(r"(?i)-(?:only|or-later)$|\+$", "", token)
    for known in CLASS_OF:
        if known.lower() == token.lower():
            return known
    return token


def tokenize(expression):
    return re.findall(r"\(|\)|\bAND\b|\bOR\b|\bWITH\b|[^\s()]+", expression.replace(" and ", " AND ").replace(" or ", " OR "))


RANK = {"permissive": 0, "weak-copyleft": 1, "strong-copyleft": 2, "network-copyleft": 3, "source-available": 3, "unknown": 4}


def evaluate(expression):
    """Most restrictive class the user must accept: OR picks the least restrictive option, AND the most restrictive."""
    if not re.search(r"\b(?:AND|OR|WITH|and|or)\b|[()]", expression):
        # a single license, possibly a free-text name with spaces ("Apache 2.0", "MIT License")
        license_id = normalize(expression)
        return CLASS_OF.get(license_id, "unknown"), [license_id]
    tokens = tokenize(expression)
    position = 0

    def primary():
        nonlocal position
        if position < len(tokens) and tokens[position] == "(":
            position += 1
            value = disjunction()
            position += 1 if position < len(tokens) and tokens[position] == ")" else 0
            return value
        token = tokens[position] if position < len(tokens) else ""
        position += 1
        license_id = normalize(token)
        cls = CLASS_OF.get(license_id, "unknown")
        if position < len(tokens) and tokens[position] == "WITH":
            exception = tokens[position + 1] if position + 1 < len(tokens) else ""
            position += 2
            if exception in PERMISSIVE_EXCEPTIONS and cls in ("strong-copyleft", "weak-copyleft"):
                cls = "weak-copyleft"
        return cls, [license_id]

    def conjunction():
        nonlocal position
        cls, ids = primary()
        while position < len(tokens) and tokens[position] == "AND":
            position += 1
            other, more = primary()
            cls, ids = (cls if RANK[cls] >= RANK[other] else other), ids + more
        return cls, ids

    def disjunction():
        nonlocal position
        cls, ids = conjunction()
        while position < len(tokens) and tokens[position] == "OR":
            position += 1
            other, more = conjunction()
            cls, ids = (cls if RANK[cls] <= RANK[other] else other), ids + more
        return cls, ids

    if not tokens:
        return "unknown", []
    return disjunction()


def identify_text(text):
    for license_id, pattern in TEXT_SIGNATURES:
        if re.search(pattern, text, re.I):
            return license_id
    return None


def _analyze(ctx, data):
    model = data.get("distribution", "proprietary")
    allow = {normalize(a) for a in data.get("allow") or []}
    deny = {normalize(d) for d in data.get("deny") or []}
    entries = [(p["name"], p.get("version", ""), p.get("license", ""), "packages") for p in data.get("packages") or []]
    if data.get("files"):
        for path, text in file_list(data, max_files=200):
            kind, packages, _ = manifests.parse(path, text)
            if kind:
                entries += [(p.name, p.version or "", p.license, path) for p in packages if kind in ("package_lock", "composer_lock") or p.license]
                if kind not in ("package_lock", "composer_lock"):
                    ctx.limit(f"{path}: this format does not record licenses; pass 'packages' with licenses (e.g. from pip-licenses).")
            else:
                identified = identify_text(text)
                entries.append((path.rsplit("/", 1)[-1], "", identified or "", path))
                if identified is None:
                    ctx.limit(f"{path}: license text not recognized.")
    if not entries:
        raise ToolInputError("Provide packages [{name, license}] and/or files (lockfiles with licenses, LICENSE texts).")
    ctx.input_kind = model
    summary: dict[str, int] = {}
    for index, (name, version, expression, origin) in enumerate(entries):
        if index % 1000 == 0:
            ctx.check()
        label = f"{name}@{version}" if version else name
        expression = (expression or "").strip()
        if not expression or expression.upper() in ("NOASSERTION", "UNKNOWN", "UNLICENSED", "SEE LICENSE IN LICENSE"):
            summary["unknown"] = summary.get("unknown", 0) + 1
            ctx.finding(f"license.unknown.{name}", f"{label}: license unknown", "low",
                        "Without a declared license you have no right to use the code; find the license or replace the package.",
                        location=origin)
            continue
        cls, ids = evaluate(expression)
        summary[cls] = summary.get(cls, 0) + 1
        denied = sorted(set(ids) & deny)
        if denied:
            ctx.finding(f"license.denied.{name}", f"{label}: denied license {', '.join(denied)}", "high",
                        f"The expression '{expression}' includes a license on your deny list.", assurance="verified_condition", location=origin)
            continue
        if allow and not (set(ids) & allow) and cls != "permissive":
            ctx.finding(f"license.not-allowed.{name}", f"{label}: {expression} is not on the allow list", "medium",
                        "Review it with your legal team.", assurance="verified_condition", location=origin)
            continue
        severity = CONFLICTS[model].get(cls)
        if severity and not (set(ids) & allow):
            ctx.finding(f"license.{cls}.{name}", f"{label}: {cls.replace('-', ' ')} license ({expression})", severity,
                        f"Under a {model} distribution model, {cls.replace('-', ' ')} terms can require releasing source code or restrict use. "
                        "Confirm how the package is used (linking, modification, network use).", assurance="verified_condition", location=origin)
        if cls == "unknown":
            ctx.finding(f"license.unrecognized.{name}", f"{label}: unrecognized license '{expression[:60]}'", "low",
                        "Not an SPDX identifier known to this tool; review it manually.", location=origin)
    ctx.artifacts.update({"distribution": model, "by_class": summary, "packages": len(entries)})
    ctx.limit("License classification is engineering guidance only and is not legal advice.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

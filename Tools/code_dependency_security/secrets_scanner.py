def _walk(root, excludes, ctx):
    base = Path(root)
    if not base.is_dir():
        raise ToolInputError("directory does not exist or is not a folder.")
    files, total = [], 0
    for current, dirs, names in os.walk(base, followlinks=False):
        ctx.check()
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".cache")]
        for name in names:
            path = Path(current, name)
            rel = path.relative_to(base).as_posix()
            if BINARY_SUFFIX.search(name) or any(re.search(x, rel) for x in excludes) or path.is_symlink():
                continue
            try:
                size = path.stat().st_size
                if size > 2 * 1024 * 1024:
                    continue
                raw = path.read_bytes()
            except OSError:
                continue
            if b"\x00" in raw[:4096]:
                continue
            total += len(raw)
            if total > 100 * 1024 * 1024 or len(files) >= 20000:
                ctx.limit("Stopped after 20,000 files / 100 MB.", partial=True)
                return files
            files.append((rel, raw.decode("utf-8", errors="replace")))
    return files


def _analyze(ctx, data):
    excludes = [x for x in data.get("exclude") or []]
    for pattern in excludes:
        try:
            re.compile(pattern)
        except re.error as exc:
            raise ToolInputError(f"exclude pattern is not a valid regular expression: {pattern[:40]}") from exc
    if data.get("directory"):
        ctx.input_kind = "directory"
        files = _walk(data["directory"], excludes, ctx)
    elif data.get("files"):
        ctx.input_kind = "files"
        files = [(p, t) for p, t in file_list(data, max_files=5000, max_total=100 * 1024 * 1024)
                 if not any(re.search(x, p) for x in excludes)]
    else:
        raise ToolInputError("Provide files [{path, content}] or a local directory.")
    occurrences: dict[tuple[str, str], list[str]] = {}
    meta: dict[tuple[str, str], dict] = {}
    suppressed = 0
    for index, (path, text) in enumerate(files):
        if index % 100 == 0:
            ctx.check()
        if SECRET_FILES.search(path) and not PUBLIC_KEY_FILE.search(path):
            ctx.finding("file.secret-bearing", f"Secret-bearing file in the repository: {path.rsplit('/', 1)[-1]}", "high",
                        "Files like this hold credentials by design and should never be committed; add them to .gitignore.",
                        location=path)
        for item in secrets_kit.scan(text, max_items=100):
            if item["placeholder"]:
                suppressed += 1
                continue
            key = (item["type"], item["fingerprint"])
            occurrences.setdefault(key, []).append(f"{path}:{item['line']}")
            meta.setdefault(key, item)
    for (kind, fp), places in occurrences.items():
        item = meta[(kind, fp)]
        in_tests = all(secrets_kit.is_test_path(p.rsplit(":", 1)[0]) for p in places)
        severity = item["severity"]
        if in_tests:
            severity = {"critical": "medium", "high": "low", "medium": "low"}.get(severity, severity)
        ctx.finding(f"secret.{kind}.{fp[:8]}", f"{item['label']}" + (" (only in tests/docs)" if in_tests else ""), severity,
                    f"Found in {len(places)} place(s): {', '.join(places[:5])}{'…' if len(places) > 5 else ''}. "
                    + ("Test fixtures are often fake, but confirm it is not a real credential." if in_tests else
                       "Anyone with repository access (and its history) can use it: revoke and rotate."),
                    location=places[0], recommendation="Rotate the secret, remove it from the code and the git history (git filter-repo / BFG).")
        ctx.evidence("masked_secret", f"{item['label']}: {item['masked']} (fingerprint {fp})", finding_id=f"secret.{kind}.{fp[:8]}")
    ctx.artifacts.update({"files_scanned": len(files), "unique_secrets": len(occurrences), "placeholders_ignored": suppressed})
    ctx.limit("Only the current file contents are scanned; secrets removed from files may still exist in version-control history.")



ALGORITHMS = {"sha1": "SHA-1", "sha256": "SHA-256", "sha384": "SHA-384", "sha512": "SHA-512"}


def _hashes(package):
    out = []
    for item in package.integrity:
        algorithm, _, value = item.partition("-") if item.startswith(("sha1-", "sha256-", "sha384-", "sha512-")) else item.partition(":")
        if algorithm in ALGORITHMS and value:
            try:
                hex_value = value if all(c in "0123456789abcdefABCDEF" for c in value) else base64.b64decode(value).hex()
            except (binascii.Error, ValueError):
                continue
            out.append({"alg": ALGORITHMS[algorithm], "content": hex_value.lower()})
        elif package.ecosystem in ("Packagist",) and len(item) == 40:
            out.append({"alg": "SHA-1", "content": item.lower()})
        elif package.ecosystem == "crates.io" and len(item) == 64:
            out.append({"alg": "SHA-256", "content": item.lower()})
    return out[:4]


def _analyze(ctx, data):
    files = file_list(data, max_files=200)
    packages, kinds = [], []
    for path, text in files:
        kind, found, _ = manifests.parse(path, text)
        if kind:
            kinds.append(kind)
            packages.extend(found)
        else:
            ctx.limit(f"{path} is not a supported manifest and was skipped.")
    if not kinds:
        raise ToolInputError("No supported manifest or lockfile was supplied.")
    ctx.input_kind = "+".join(sorted(set(kinds)))
    include_dev = data.get("include_dev", True)
    components, seen, unresolved = [], set(), 0
    for package in packages:
        if package.dev and not include_dev:
            continue
        if not package.version:
            unresolved += 1
            continue
        ref = package.purl
        if ref in seen:
            continue
        seen.add(ref)
        component = {"type": "library", "bom-ref": ref, "name": package.name, "version": package.version, "purl": ref,
                     "scope": "optional" if package.dev else "required"}
        if package.ecosystem == "Maven" and ":" in package.name:
            component["group"], component["name"] = package.name.split(":", 1)
        hashes = _hashes(package)
        if hashes:
            component["hashes"] = hashes
        if package.license:
            component["licenses"] = [{"expression": package.license}] if " " in package.license else [{"license": {"id": package.license}}]
        components.append(component)
    components.sort(key=lambda c: c["bom-ref"])
    serial = uuid.UUID(hashlib.sha256("\n".join(c["bom-ref"] for c in components).encode()).hexdigest()[:32])
    metadata = {"tools": {"components": [{"type": "application", "name": "CyberScan SBOM Generator", "version": VERSION}]}}
    if data.get("timestamp"):
        metadata["timestamp"] = data["timestamp"]
    if data.get("project_name"):
        metadata["component"] = {"type": "application", "name": data["project_name"], "version": data.get("project_version", ""),
                                 "bom-ref": "root"}
    sbom = {"bomFormat": "CycloneDX", "specVersion": "1.5", "serialNumber": f"urn:uuid:{serial}", "version": 1,
            "metadata": metadata, "components": components}
    ctx.artifacts.update({"sbom": sbom, "component_count": len(components), "formats": sorted(set(kinds))})
    if unresolved:
        ctx.finding("sbom.unresolved-versions", f"{unresolved} dependency(ies) without a resolved version", "info",
                    "Manifests such as package.json or unpinned requirements declare ranges only; add the lockfile for a complete SBOM.",
                    assurance="informational", location=ctx.input_kind)
    without_hashes = sum(1 for c in components if "hashes" not in c)
    if components and without_hashes:
        ctx.finding("sbom.missing-hashes", f"{without_hashes} of {len(components)} component(s) have no hash", "info",
                    "Hashes let consumers verify they received the same artifacts; pip --require-hashes or npm lockfiles provide them.",
                    assurance="informational", location=ctx.input_kind)
    ctx.summary = f"CycloneDX 1.5 SBOM with {len(components)} component(s)."



def _python(ctx, text, path):
    tree = ts.parse_python(text)
    if tree is None:
        ctx.limit(f"{path} could not be parsed as Python; skipped.")
        return
    tainted = ts.function_sources(tree, text)
    assignments = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) and ts.is_dynamic_string(node.value):
            if SQL.search(ts.string_parts(node.value)):
                assignments[node.targets[0].id] = node.lineno
    for call in ts.iter_calls(tree):
        method = call.func.attr if isinstance(call.func, ast.Attribute) else (call.func.id if isinstance(call.func, ast.Name) else "")
        if method not in PY_METHODS or not call.args and method != "extra":
            continue
        query = call.args[0] if call.args else None
        if method == "extra":
            values = [kw.value for kw in call.keywords if kw.arg in ("where", "select", "tables")]
            query = next((e for v in values if isinstance(v, (ast.List, ast.Tuple)) for e in v.elts if ts.is_dynamic_string(e)), None)
        line = call.lineno
        where = f"{path}:{line}"
        literal = ts.string_parts(query) if query is not None else ""
        # execute()-style sinks take SQL by definition; text() is also a common non-SQL method name, so it needs SQL keywords
        looks_sql = bool(SQL.search(literal)) if (method == "text" or literal.strip()) else True
        if query is not None and ts.is_dynamic_string(query) and looks_sql:
            ctx.finding("py.dynamic-sql", f"SQL built dynamically and passed to {method}()", "critical" if tainted.get(line) else "high",
                        "The query text is an f-string / % / .format / concatenation, so input can alter the SQL (CWE-89)."
                        + (" The same function reads request/user input." if tainted.get(line) else ""),
                        location=where, evidence=ts.excerpt(text, line),
                        recommendation="Pass values separately: cursor.execute('... WHERE id = %s', (value,)).")
        elif isinstance(query, ast.Name) and query.id in assignments and len(call.args) == 1:
            ctx.finding("py.dynamic-sql-variable", f"Dynamically built SQL variable '{query.id}' executed", "high" if tainted.get(line) else "medium",
                        f"'{query.id}' is assembled with string formatting at line {assignments[query.id]} and executed without parameters (CWE-89).",
                        location=where, evidence=ts.excerpt(text, line))


def _analyze(ctx, data):
    if data.get("files"):
        files = file_list(data)
    elif data.get("content") is not None:
        files = [(data.get("path") or "input.py", data["content"])]
    else:
        raise ToolInputError("Provide files [{path, content}] or content with a path.")
    ctx.input_kind = "source"
    for path, text in files:
        ctx.check()
        language = ts.language_of(path, text)
        if language == "python":
            _python(ctx, text, path)
        elif language != "unknown":
            ts.apply_rules(ctx, text, REGEX_RULES, path=path, language=language)
    ctx.artifacts["files"] = len(files)
    ctx.limit("Data flow is not traced across functions or files; ORM query builders and stored procedures are assumed safe.")



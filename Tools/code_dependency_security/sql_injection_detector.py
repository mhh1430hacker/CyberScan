PY_METHODS = {"execute", "executemany", "executescript", "raw", "extra", "exec_driver_sql", "read_sql", "read_sql_query", "RawSQL", "text", "mogrify"}
SQL_LITERAL = r"(?i)[\"'`](?:\s*(?:SELECT\b[^\"'`]*\bFROM|INSERT\s+INTO|UPDATE\s+\w+\s+SET|DELETE\s+FROM)[^\"'`]*)"

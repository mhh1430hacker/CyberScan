DEFAULT_REGISTRIES = {"registry.npmjs.org", "registry.yarnpkg.com", "files.pythonhosted.org", "pypi.org", "proxy.golang.org",
                      "repo.packagist.org", "api.github.com", "codeload.github.com", "static.crates.io", "index.crates.io", "repo1.maven.org"}


def _host(url):
    match = re.match(r"^[a-z+]+://([^/:]+)", url or "")
    return match.group(1).lower() if match else ""


def _source_checks(ctx, package, registries):
    url = package.resolved
    where = f"{package.source_file}: {package.name}@{package.version or package.spec}"
    if not url:
        return
    if url.startswith("http://"):
        ctx.finding(f"source.http.{package.name}", f"{package.name} is downloaded over plain HTTP", "high",
                    "Anyone on the network path can replace the package.", assurance="verified_condition", location=where, evidence=url)
    elif re.match(r"^(?:git\+|git:|github:|gitlab:|bitbucket:)", url) or "/tarball/" in url and "github" in url:
        ctx.finding(f"source.git.{package.name}", f"{package.name} comes from a git repository, not a registry", "medium",
                    "Git sources bypass registry integrity metadata and can change if the ref is not a full commit hash.",
                    assurance="verified_condition", location=where)
    elif url.startswith("file:"):
        ctx.finding(f"source.file.{package.name}", f"{package.name} is installed from a local file", "low",
                    "Builds depend on a file outside the registry.", assurance="verified_condition", location=where)
    elif _host(url) and _host(url) not in registries and not any(_host(url).endswith("." + r) for r in registries):
        ctx.finding(f"source.registry.{_host(url)}", f"Packages from non-default registry {_host(url)}", "info",
                    "Expected for private registries; list it in trusted_registries to silence this.", assurance="informational", location=where)


def _npm_integrity(ctx, packages, path):
    missing = [p for p in packages if p.version and not p.integrity and not p.resolved.startswith(("file:", "git"))]
    if missing:
        ctx.finding("integrity.missing", f"{len(missing)} npm package(s) without an integrity hash", "medium",
                    f"e.g. {missing[0].name}@{missing[0].version}; npm cannot verify these downloads.", assurance="verified_condition", location=path)
    sha1 = [p for p in packages if p.integrity and all(i.startswith("sha1-") for i in p.integrity)]
    if sha1:
        ctx.finding("integrity.sha1", f"{len(sha1)} npm package(s) pinned only by SHA-1", "low",
                    "SHA-1 integrity is weak; regenerate the lockfile with a current npm to get sha512.", assurance="verified_condition", location=path)


def _requirements(ctx, packages, options, path):
    unpinned = [p for p in packages if not p.version and not p.resolved]
    if unpinned:
        ctx.finding("pin.unpinned", f"{len(unpinned)} requirement(s) not pinned with ==", "medium",
                    f"e.g. '{unpinned[0].name}{unpinned[0].spec}'. Installs differ over time and can pick up a malicious new release.",
                    assurance="verified_condition", location=f"{path}:{unpinned[0].line}", recommendation="Pin with == (pip-compile) and add --hash entries.")
    if options.get("hashes_seen"):
        without = [p for p in packages if not p.integrity]
        if without:
            ctx.finding("hash.partial", f"Hash-checking mode is incomplete ({len(without)} requirement(s) without --hash)", "medium",
                        "pip turns on hash-checking when any requirement has a hash and then refuses the rest; or, if hashes are "
                        "dropped, nothing is verified.", assurance="verified_condition", location=f"{path}:{without[0].line}")
    for url in options.get("index_urls", []):
        if url.startswith("http://"):
            ctx.finding("index.http", "Package index over plain HTTP", "high", f"--index-url {url}", assurance="verified_condition", location=path)
    if options.get("extra_index_urls"):
        ctx.finding("index.extra", "Extra package index configured", "medium",
                    "pip installs the highest version from any index: a public package with your private package's name wins "
                    "(dependency confusion). Use a single proxy index or per-package index pinning.", assurance="verified_condition",
                    location=path, evidence=", ".join(options["extra_index_urls"][:3]))
    for line in options.get("urls", []):
        ctx.finding("source.url", "Requirement installed from a URL or VCS", "medium", "Direct URLs bypass the index and its integrity data.",
                    assurance="verified_condition", location=path, evidence=line[:200])


def _analyze(ctx, data):
    registries = DEFAULT_REGISTRIES | {r.lower() for r in data.get("trusted_registries") or []}
    files = file_list(data, max_files=200)
    parsed = {}
    for path, text in files:
        ctx.check()
        kind, packages, options = manifests.parse(path, text)
        if kind is None:
            ctx.limit(f"{path} is not a supported lockfile/manifest and was skipped.")
            continue
        parsed[kind] = (path, packages, text)
        if kind == "requirements":
            _requirements(ctx, packages, options, path)
        if kind in ("package_lock", "yarn_lock"):
            _npm_integrity(ctx, packages, path)
            if kind == "package_lock" and json.loads(text).get("lockfileVersion", 1) == 1:
                ctx.finding("npm.lockfile-v1", "package-lock.json uses lockfile version 1", "info",
                            "Regenerate with npm 7+ for v3 metadata (integrity for every package).", assurance="informational", location=path)
        if kind in ("pipfile_lock", "poetry_lock"):
            missing = [p for p in packages if not p.integrity]
            if missing:
                ctx.finding("integrity.missing-python", f"{len(missing)} locked Python package(s) without hashes", "medium",
                            f"e.g. {missing[0].name}; regenerate the lockfile so installs are verified.", assurance="verified_condition", location=path)
        if kind == "pipfile_lock":
            for source in (json.loads(text).get("_meta") or {}).get("sources") or []:
                if str(source.get("url", "")).startswith("http://"):
                    ctx.finding("index.http", "Pipfile source over plain HTTP", "high", source["url"], assurance="verified_condition", location=path)
        for package in packages:
            _source_checks(ctx, package, registries)
    if "package_json" in parsed and "package_lock" in parsed:
        declared = {p.name for p in parsed["package_json"][1]}
        locked = {p.name for p in parsed["package_lock"][1]}
        drift = sorted(declared - locked)
        if drift:
            ctx.finding("drift.npm", f"{len(drift)} dependency(ies) in package.json are missing from package-lock.json", "medium",
                        f"e.g. {', '.join(drift[:5])}: the lockfile is out of date, so installs resolve them freshly.",
                        assurance="verified_condition", location=parsed["package_lock"][0], recommendation="Run npm install and commit the lockfile.")
    if "go_mod" in parsed and "go_sum" in parsed:
        summed = {(p.name, p.version) for p in parsed["go_sum"][1]}
        missing = [p for p in parsed["go_mod"][1] if (p.name, p.version) not in summed]
        if missing:
            ctx.finding("drift.go", f"{len(missing)} go.mod requirement(s) have no go.sum entry", "medium",
                        f"e.g. {missing[0].name} {missing[0].version}; run 'go mod tidy'.", assurance="verified_condition", location=parsed["go_sum"][0])
    if not parsed:
        raise ToolInputError("No supported lockfile or manifest was supplied.")
    ctx.input_kind = "+".join(sorted(parsed))
    ctx.artifacts["files"] = {kind: len(value[1]) for kind, value in parsed.items()}


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

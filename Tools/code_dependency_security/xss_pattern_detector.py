def _python(ctx, text, path):
    tree = ts.parse_python(text)
    if tree is None:
        return
    aliases = ts.import_aliases(tree)
    tainted = ts.function_sources(tree, text)
    for call in ts.iter_calls(tree):
        name = ts.call_name(call, aliases)
        first = call.args[0] if call.args else None
        where = f"{path}:{call.lineno}"
        if name.endswith(("Markup", "mark_safe", "SafeString")) and first is not None and (ts.is_dynamic_string(first) or isinstance(first, ast.Name)):
            ctx.finding("py.markup-dynamic", f"{name.split('.')[-1]}() on a built string", "critical" if tainted.get(call.lineno) else "high",
                        "Marking formatted input as safe HTML disables escaping for it (CWE-79).", location=where, evidence=ts.excerpt(text, call.lineno))
        elif name.endswith("render_template_string") and first is not None and not ts.is_constant_string(first):
            ctx.finding("py.render-template-string", "render_template_string with a dynamic template", "critical" if tainted.get(call.lineno) else "high",
                        "Building the template itself from input allows XSS and server-side template injection (CWE-79/1336).",
                        location=where, evidence=ts.excerpt(text, call.lineno))
        elif name.endswith(("make_response", "HttpResponse", "Response")) and first is not None and ts.is_dynamic_string(first) and tainted.get(call.lineno):
            if "<" in ts.string_parts(first):
                ctx.finding("py.html-response", "HTML response built from request input", "high",
                            "Markup is formatted with user input and returned without escaping (CWE-79).", location=where, evidence=ts.excerpt(text, call.lineno))


def _analyze(ctx, data):
    if data.get("files"):
        files = file_list(data)
    elif data.get("content") is not None:
        files = [(data.get("path") or "input.js", data["content"])]
    else:
        raise ToolInputError("Provide files [{path, content}] or content with a path.")
    ctx.input_kind = "source"
    for path, text in files:
        ctx.check()
        language = ts.language_of(path, text)
        if language == "python":
            _python(ctx, text, path)
        if language in ("javascript", "html", "template", "php") or path.endswith((".html", ".vue", ".svelte")):
            ts.apply_rules(ctx, text, RULES, path=path, language="javascript" if path.endswith((".vue", ".svelte")) else language)
    ctx.artifacts["files"] = len(files)
    ctx.limit("Sanitizers other than DOMPurify/htmlspecialchars are not recognised; data flow is not traced across files.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

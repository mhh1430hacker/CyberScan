def _python(ctx, text, path):
    tree = ts.parse_python(text)
    if tree is None:
        ctx.limit(f"{path} could not be parsed as Python; skipped.")
        return
    aliases = ts.import_aliases(tree)
    tainted = ts.function_sources(tree, text)
    for call in ts.iter_calls(tree):
        name = ts.call_name(call, aliases)
        where, line = f"{path}:{call.lineno}", call.lineno
        boost = tainted.get(line, False)
        if name in PY_SINKS:
            ctx.finding(f"py.{name}", f"{PY_SINKS[name]} deserialization ({name})", "critical" if boost else "high",
                        f"{name} executes code embedded in the data if an attacker controls it (CWE-502)."
                        + (" The same function reads request/user input." if boost else ""), location=where, evidence=ts.excerpt(text, line),
                        recommendation="Use JSON or another data-only format; never unpickle untrusted data.")
        elif name == "yaml.load":
            loader = ts.keyword(call, "Loader") or (call.args[1] if len(call.args) > 1 else None)
            loader_name = ts.dotted_name(loader).split(".")[-1] if loader is not None else ""
            if loader_name not in SAFE_YAML_LOADERS:
                ctx.finding("py.yaml.load", "yaml.load without a safe loader", "critical" if boost else "high",
                            f"Loader={loader_name or 'default'} can construct arbitrary Python objects (CWE-502). Use yaml.safe_load.",
                            location=where, evidence=ts.excerpt(text, line))
        elif name in ("torch.load",):
            weights = ts.keyword(call, "weights_only")
            if not (isinstance(weights, ast.Constant) and weights.value is True):
                ctx.finding("py.torch.load", "torch.load without weights_only=True", "high",
                            "Model files are pickles; loading an untrusted checkpoint runs code (CWE-502).", location=where)
        elif name in ("numpy.load", "np.load"):
            allow = ts.keyword(call, "allow_pickle")
            if isinstance(allow, ast.Constant) and allow.value is True:
                ctx.finding("py.numpy.allow_pickle", "numpy.load(allow_pickle=True)", "high", "Object arrays are unpickled (CWE-502).", location=where)


def _blob(ctx, raw):
    if raw[:2] == b"\xac\xed" and raw[2:4] == b"\x00\x05":
        ctx.artifacts["format"] = "java-serialization"
        classes = sorted(set(m.decode("latin-1") for m in re.findall(rb"\x72\x00[\x01-\xff]([A-Za-z_$][\w$.]{2,120})", raw)))[:30]
        gadgets = [c for c in classes if re.search(r"(?i)commons\.collections|InvokerTransformer|TemplatesImpl|groovy|ysoserial|ChainedTransformer|BeanComparator", c)]
        ctx.finding("blob.java", "Java serialized object stream", "high" if gadgets else "medium",
                    "Data in Java native serialization format" + (f"; it references known gadget classes: {', '.join(gadgets[:5])}." if gadgets else "."),
                    assurance="verified_condition", location="blob")
        ctx.artifacts["classes"] = classes
        return
    if raw[:17] == b"\x00\x01\x00\x00\x00\xff\xff\xff\xff\x01\x00\x00\x00\x00\x00\x00\x00":
        ctx.artifacts["format"] = "dotnet-binaryformatter"
        ctx.finding("blob.binaryformatter", ".NET BinaryFormatter payload", "high", "BinaryFormatter data can carry gadget chains (ysoserial.net).",
                    assurance="verified_condition", location="blob")
        return
    if re.match(rb'^(?:a:\d+:\{|O:\d+:"[A-Za-z_\\][\w\\]*":\d+:\{)', raw):
        ctx.artifacts["format"] = "php-serialize"
        objects = sorted(set(m.decode() for m in re.findall(rb'O:\d+:"([A-Za-z_\\][\w\\]*)"', raw)))[:30]
        ctx.finding("blob.php", "PHP serialized data" + (" with objects" if objects else ""), "high" if objects else "low",
                    f"Objects: {', '.join(objects) or 'none'}. Unserializing objects triggers their magic methods.", assurance="verified_condition", location="blob")
        return
    if raw[:1] in (b"\x80", b"(", b"c", b"}", b"]", b"\x8c") or raw[:2] in (b"\x80\x02", b"\x80\x03", b"\x80\x04", b"\x80\x05"):
        imports, calls, ops = [], 0, 0
        try:
            for opcode, arg, _pos in pickletools.genops(io.BytesIO(raw[:20_000_000])):
                ops += 1
                if ops % 20000 == 0:
                    ctx.check()
                if opcode.name in ("GLOBAL", "INST"):
                    imports.append(str(arg).replace(" ", "."))
                elif opcode.name == "STACK_GLOBAL":
                    imports.append("(stack global)")
                elif opcode.name in ("REDUCE", "OBJ", "NEWOBJ", "NEWOBJ_EX", "BUILD"):
                    calls += 1
        except Exception as exc:  # noqa: BLE001 - not a (complete) pickle
            if ops < 2:
                ctx.artifacts["format"] = "unknown"
                ctx.limit(f"The blob is not a recognised serialization format ({type(exc).__name__}).")
                return
            ctx.limit("The pickle stream is truncated or malformed after the first opcodes.")
        ctx.artifacts.update({"format": "python-pickle", "opcodes": ops, "imports": imports[:50]})
        dangerous = [i for i in imports if re.search(r"(?i)^(?:os|posix|nt|subprocess|builtins|__builtin__|sys|socket|shutil|importlib|runpy|pty|commands)\.|"
                                                     r"\.(?:system|popen|exec|eval|compile|getattr|__import__)$", i)]
        if imports and calls:
            ctx.finding("blob.pickle-callable", "Pickle imports and calls objects", "critical" if dangerous else "high",
                        f"Loading this pickle calls {', '.join((dangerous or imports)[:5])}: unpickling it executes that code.",
                        assurance="verified_condition", location="blob", recommendation="Never load it; inspect with pickletools.dis instead.")
        else:
            ctx.finding("blob.pickle-plain", "Pickle with plain data only", "info", "No imports/calls: loading it creates only built-in values.",
                        assurance="informational", location="blob")
        return
    ctx.artifacts["format"] = "unknown"
    ctx.limit("The blob is not a recognised serialization format.")


def _analyze(ctx, data):
    analysed = False
    if data.get("blob_base64"):
        ctx.input_kind = "blob"
        _blob(ctx, decode_base64(data["blob_base64"], max_bytes=20 * 1024 * 1024, field_name="blob_base64"))
        analysed = True
    if data.get("files") or data.get("content") is not None:
        files = file_list(data) if data.get("files") else [(data.get("path") or "input.py", data["content"])]
        ctx.input_kind = ctx.input_kind + "+source" if ctx.input_kind else "source"
        for path, text in files:
            ctx.check()
            language = ts.language_of(path, text)
            if language == "python":
                _python(ctx, text, path)
            elif language != "unknown":
                ts.apply_rules(ctx, text, REGEX_RULES, path=path, language=language)
        ctx.artifacts["files"] = len(files)
        analysed = True
    if not analysed:
        raise ToolInputError("Provide source (files/content) and/or blob_base64.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

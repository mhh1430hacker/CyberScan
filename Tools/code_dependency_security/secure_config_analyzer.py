def detect(path, text):
    name = path.replace("\\", "/").rsplit("/", 1)[-1].lower()
    if name == "settings.py" or re.search(r"^\s*INSTALLED_APPS\s*=", text, re.M):
        return "django"
    if name.endswith(".conf") and re.search(r"^\s*(?:server|http|location)\s*\{|^\s*ssl_protocols\b", text, re.M):
        return "nginx"
    if name in ("httpd.conf", "apache2.conf", "ssl.conf") or re.search(r"^\s*<(?:VirtualHost|Directory)\b|^\s*ServerTokens\b", text, re.M | re.I):
        return "apache"
    if name == "php.ini" or re.search(r"^\s*(?:expose_php|display_errors|allow_url_include)\s*=", text, re.M):
        return "php"
    if name.startswith(".env") or name.endswith(".env"):
        return "dotenv"
    if re.match(r"application(?:-\w+)?\.(?:properties|ya?ml)$", name) or "spring." in text or "management.endpoints" in text:
        return "spring"
    return None


def _nginx_headers(ctx, text, path):
    if re.search(r"^\s*listen\s+[^;]*\bssl\b|^\s*ssl_certificate\b", text, re.M):
        for header, fid in (("Strict-Transport-Security", "nginx.no-hsts"), ("X-Content-Type-Options", "nginx.no-nosniff")):
            if not re.search(rf"add_header\s+{header}\b", text, re.I):
                ctx.finding(fid, f"HTTPS server without {header}", "low", f"No add_header {header} in this configuration.",
                            assurance="verified_condition", location=path)


def _analyze(ctx, data):
    if data.get("files"):
        files = file_list(data, max_files=500)
    elif data.get("content") is not None:
        files = [(data.get("path") or "config", data["content"])]
    else:
        raise ToolInputError("Provide files [{path, content}] or content with a path.")
    formats = {}
    forced = data.get("format", "auto")
    for path, text in files:
        ctx.check()
        fmt = forced if forced != "auto" else detect(path, text)
        if fmt is None:
            ctx.limit(f"{path}: configuration format not recognised; only secrets were checked.")
        else:
            formats[path] = fmt
            ts.apply_rules(ctx, text, RULES[fmt], path=path, language="python" if fmt == "django" else "yaml", skip_comments=True)
            if fmt == "nginx":
                _nginx_headers(ctx, text, path)
        for item in secrets_kit.scan(text):
            if not item["placeholder"]:
                ctx.finding(f"config.secret.{item['type']}", f"{item['label']} in configuration", "high",
                            "Hard-coded secrets in configuration files end up in repositories and backups; inject them at deploy time.",
                            location=f"{path}:{item['line']}")
                ctx.evidence("masked_secret", f"{item['label']}: {item['masked']}", finding_id=f"config.secret.{item['type']}")
    if not formats and not ctx.findings:
        raise ToolInputError("No supported configuration format was recognised; set 'format' explicitly.")
    ctx.input_kind = "+".join(sorted(set(formats.values()))) or "unknown"
    ctx.artifacts["formats"] = formats


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

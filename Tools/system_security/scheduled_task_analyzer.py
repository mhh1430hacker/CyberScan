CRON_LINE = re.compile(r"^\s*(?:(@\w+)|((?:\S+\s+){4}\S+))\s+(?:(\w[\w.-]*)\s+)?(.+)$")


def _strip_ns(root):
    for element in root.iter():
        if isinstance(element.tag, str) and "}" in element.tag:
            element.tag = element.tag.split("}", 1)[1]
    return root


def _tasks(text):
    if re.search(r"<!DOCTYPE|<!ENTITY", text, re.I):
        raise ToolInputError("Task XML with DOCTYPE/ENTITY declarations is refused (XML entity attacks).")
    names = re.findall(r"<!--\s*(\\[^>]*?)\s*-->", text)
    bodies = re.findall(r"<Task\b.*?</Task>", text, re.S)
    if not bodies:
        raise ToolInputError("No <Task> elements found in task_xml.")
    out = []
    for index, body in enumerate(bodies):
        try:
            root = _strip_ns(ET.fromstring(body))
        except ET.ParseError as exc:
            raise ToolInputError(f"Task #{index + 1} is not well-formed XML.") from exc
        uri = root.findtext("RegistrationInfo/URI") or (names[index] if index < len(names) else f"task {index + 1}")
        out.append((uri.strip(), root))
    return out


def _windows(ctx, tasks):
    for uri, root in tasks:
        ctx.check()
        principal = root.find("Principals/Principal")
        user = (principal.findtext("UserId") if principal is not None else "") or ""
        level = (principal.findtext("RunLevel") if principal is not None else "") or ""
        system = user.upper() in ("S-1-5-18", "SYSTEM", "NT AUTHORITY\\SYSTEM")
        privileged = system or level == "HighestAvailable"
        hidden = (root.findtext("Settings/Hidden") or "").lower() == "true"
        enabled = (root.findtext("Settings/Enabled") or "true").lower() != "false"
        trigger_root = root.find("Triggers")
        triggers = [t.tag for t in trigger_root] if trigger_root is not None else []
        early = bool({"BootTrigger", "LogonTrigger"} & set(triggers))
        author = root.findtext("RegistrationInfo/Author") or ""
        # Built-in tasks often carry a resource-string author ("$(@%SystemRoot%\...)"), so the folder decides. Their Exec
        # commands are still analysed below, because malware also hides tasks under \Microsoft\Windows\.
        microsoft = uri.lower().startswith("\\microsoft\\windows\\") or (uri.lower().startswith("\\microsoft\\") and "microsoft" in author.lower())
        for action in root.findall("Actions/Exec"):
            command = (action.findtext("Command") or "").strip().strip('"')
            arguments = (action.findtext("Arguments") or "").strip()
            full = f'"{command}" {arguments}'.strip()
            added = analyze_command(ctx, full, location=uri, context="Scheduled task", prefix="task")
            if added and privileged:
                ctx.finding("task.privileged-suspicious", "Suspicious task runs with elevated rights", "high",
                            f"{uri} runs as {user or 'an elevated user'} ({level or 'default level'}); the problems above therefore "
                            "execute with administrative privileges.", location=uri)
        if hidden and privileged and early and not microsoft and enabled:
            ctx.finding("task.hidden-privileged-autostart", "Hidden privileged task at boot/logon", "medium",
                        f"{uri} is hidden, runs elevated and starts at {', '.join(triggers)}: the profile of a persistence task (T1053.005).",
                        location=uri)
        if root.find("Actions/ComHandler") is not None and not microsoft:
            ctx.finding("task.com-handler", "Task runs a COM handler", "info",
                        "COM-handler actions hide the executable behind a CLSID; resolve it to see what runs.",
                        assurance="informational", location=uri)
    ctx.artifacts["windows_tasks"] = len(tasks)


def _cron(ctx, text):
    count = 0
    for number, line in enumerate(text.splitlines(), start=1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or re.match(r"^[A-Z_]+=", stripped):
            continue
        match = CRON_LINE.match(stripped)
        if not match:
            continue
        count += 1
        schedule = match.group(1) or match.group(2)
        command = match.group(4)
        user = match.group(3) if match.group(3) and match.group(3) in ("root",) else None
        where = f"crontab line {number}"
        analyze_command(ctx, command, location=where, context="Cron job", prefix="cron")
        if schedule == "@reboot" and re.search(r"(?:/tmp/|/dev/shm/|\bnohup\b.*&)", command):
            ctx.finding("cron.reboot-transient", "@reboot job starts something from a temporary path", "high",
                        "Starting a program from /tmp or /dev/shm at every boot is a common Linux persistence pattern.",
                        location=where, evidence=stripped)
        if re.search(r"\b(?:curl|wget)\b", command) and schedule.startswith("*"):
            ctx.finding("cron.frequent-download", "Cron job downloads something every minute", "medium",
                        "A very frequent job fetching remote content is typical of miner and botnet persistence.",
                        location=where, evidence=stripped)
        if user == "root" and re.search(r"(?:/tmp/|/home/)", command):
            ctx.finding("cron.root-user-path", "Root cron job runs a script from a user-controlled path", "high",
                        "Whoever can write that path can run code as root.", location=where, evidence=stripped)
    ctx.artifacts["cron_entries"] = count
    return count


def _analyze(ctx, data):
    task_xml = data.get("task_xml")
    if data.get("source") == "local":
        ctx.input_kind = "local"
        task_xml = winlocal.run_readonly(["schtasks", "/query", "/xml", "ONE"], ctx.deadline.remaining())
    else:
        ctx.input_kind, ctx.execution_mode = "provided", "local"
    if not task_xml and not data.get("crontab"):
        raise ToolInputError("Provide task_xml, crontab or source='local'.")
    if task_xml:
        _windows(ctx, _tasks(task_xml))
    if data.get("crontab") and _cron(ctx, data["crontab"]) == 0:
        raise ToolInputError("No cron entries were recognized.")



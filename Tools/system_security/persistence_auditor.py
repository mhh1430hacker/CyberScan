HKLM = "hkey_local_machine\\"
DEFAULT_LSA_AUTH = {"msv1_0"}
DEFAULT_LSA_SECURITY = {"", '""', "kerberos", "msv1_0", "schannel", "wdigest", "tspkg", "pku2u", "cloudap", "negoextender", "livessp"}


def _windows(ctx, keys):
    winlogon = keys.get(HKLM + r"software\microsoft\windows nt\currentversion\winlogon", {})
    shell = str(winlogon.get("shell", "explorer.exe")).strip().lower()
    if shell and shell not in ("explorer.exe", "explorer"):
        ctx.finding("winlogon.shell", "Winlogon Shell is not explorer.exe", "high",
                    f"Shell = '{shell}': this program starts at every logon (T1547.004).", location="Winlogon\\Shell", evidence=shell)
    userinit = str(winlogon.get("userinit", "")).strip().lower().rstrip(",")
    if userinit and userinit not in (r"c:\windows\system32\userinit.exe", "userinit.exe", r"c:\windows\system32\userinit.exe,"):
        ctx.finding("winlogon.userinit", "Winlogon Userinit runs extra programs", "high",
                    f"Userinit = '{userinit}'; anything appended runs at every logon (T1547.004).", location="Winlogon\\Userinit", evidence=userinit)
    for key, values in keys.items():
        ctx.check()
        if "\\image file execution options\\" in key and "debugger" in values:
            target = key.rsplit("\\", 1)[-1]
            ctx.finding(f"ifeo.debugger.{target}", f"IFEO debugger set for {target}", "high",
                        f"Starting {target} launches '{values['debugger']}' instead (T1546.012). Accessibility binaries "
                        "(sethc, utilman) with a debugger are a classic backdoor.", location=key, evidence=str(values["debugger"]))
        if "\\silentprocessexit\\" in key and "monitorprocess" in values:
            ctx.finding(f"ifeo.silent-exit.{key.rsplit(chr(92), 1)[-1]}", "SilentProcessExit monitor process", "high",
                        "A program runs whenever the monitored process exits (T1546.012).", location=key, evidence=str(values["monitorprocess"]))
        if key.endswith("\\currentversion\\windows") and str(values.get("appinit_dlls", "")).strip():
            loaded = values.get("loadappinit_dlls", 0) == 1
            ctx.finding("appinit.dlls", "AppInit_DLLs configured", "high" if loaded else "medium",
                        f"DLLs '{values['appinit_dlls']}' are injected into every GUI process" + ("" if loaded else " if LoadAppInit_DLLs is enabled") + " (T1546.010).",
                        location=key)
        if key.endswith("\\control\\session manager\\appcertdlls") and values:
            ctx.finding("appcert.dlls", "AppCertDLLs configured", "high", "These DLLs load into every process that calls CreateProcess (T1546.009).",
                        location=key, evidence=", ".join(str(v) for v in values.values()))
        if key.endswith("\\control\\lsa"):
            for name, defaults in (("authentication packages", DEFAULT_LSA_AUTH), ("security packages", DEFAULT_LSA_SECURITY)):
                packages = {p.strip().lower() for p in re.split(r"[\n,]", str(values.get(name, ""))) if p.strip()}
                extra = sorted(packages - defaults)
                if extra:
                    ctx.finding(f"lsa.{name.split()[0]}-package", f"Non-default LSA {name}: {', '.join(extra)}", "high",
                                "LSA loads these DLLs into LSASS at boot; malicious packages capture every password (T1547.002/.005).",
                                location=key)
        if key.endswith("\\control\\session manager") and "bootexecute" in values:
            entries = [e.strip() for e in str(values["bootexecute"]).split("\n") if e.strip()]
            unusual = [e for e in entries if e.lower() not in ("autocheck autochk *",)]
            if unusual:
                ctx.finding("bootexecute.extra", "BootExecute runs extra programs", "high",
                            f"{', '.join(unusual)} run before Windows starts (T1547.001).", location=key)
        if re.search(r"\\currentcontrolset\\services\\[^\\]+$", key) and isinstance(values.get("imagepath"), str):
            analyze_command(ctx, values["imagepath"], location=key, context="Service", prefix="service")
        if "\\active setup\\installed components\\" in key and isinstance(values.get("stubpath"), str):
            analyze_command(ctx, values["stubpath"], location=key, context="Active Setup", prefix="activesetup")
        if key.startswith("hkey_current_user\\software\\classes\\clsid\\") and key.endswith("\\inprocserver32") and values.get(""):
            ctx.finding("com.user-hijack", "Per-user COM server registration", "medium",
                        f"HKCU overrides the machine-wide COM class with '{values['']}'; per-user CLSID entries are a common hijack (T1546.015).",
                        location=key, evidence=str(values[""]))
        if key.endswith("\\control panel\\desktop") and values.get("scrnsave.exe"):
            analyze_command(ctx, str(values["scrnsave.exe"]), location=key, context="Screensaver", prefix="screensaver")
            if not str(values["scrnsave.exe"]).lower().endswith(".scr"):
                ctx.finding("screensaver.not-scr", "Screensaver is not a .scr file", "medium",
                            "The screensaver setting launches a non-screensaver program after idle time (T1546.002).", location=key)
        if key.endswith("\\software\\microsoft\\netsh") and values:
            unusual = [v for v in values.values() if isinstance(v, str) and not re.match(r"(?i)^[\w-]+\.dll$", v)]
            if unusual:
                ctx.finding("netsh.helper", "Netsh helper DLL with a path", "medium",
                            "Netsh loads helper DLLs whenever it runs; helpers with full paths are unusual (T1546.007).", location=key,
                            evidence=", ".join(unusual))


def _linux(ctx, files):
    for path, text in files:
        ctx.check()
        lower = path.lower()
        name = lower.rsplit("/", 1)[-1]
        if lower.endswith(("/etc/ld.so.preload", "ld.so.preload")):
            libs = [l.strip() for l in text.splitlines() if l.strip() and not l.startswith("#")]
            if libs:
                ctx.finding("linux.ld-preload", "/etc/ld.so.preload loads libraries into every process", "high",
                            f"{', '.join(libs)} are injected into every dynamically linked program, a rootkit technique (T1574.006).",
                            location=path)
        elif name.endswith((".service", ".timer")) or "/systemd/" in lower:
            for number, line in enumerate(text.splitlines(), start=1):
                match = re.match(r"^\s*Exec(?:Start|StartPre|StartPost|Reload|Stop)\s*=\s*[-@+!:]*(.+)$", line)
                if match:
                    analyze_command(ctx, match.group(1), location=f"{path}:{number}", context="systemd unit", prefix="systemd")
        elif name in ("rc.local",) or lower.endswith(("/etc/rc.local", "/etc/init.d/rc.local")):
            for number, line in enumerate(text.splitlines(), start=1):
                if line.strip() and not line.strip().startswith(("#", "exit")):
                    analyze_command(ctx, line, location=f"{path}:{number}", context="rc.local", prefix="rclocal")
        elif name in (".bashrc", ".bash_profile", ".profile", ".zshrc", ".zprofile", "profile", "bash.bashrc") or "/profile.d/" in lower:
            for number, line in enumerate(text.splitlines(), start=1):
                if not line.strip() or line.strip().startswith("#"):
                    continue
                analyze_command(ctx, line, location=f"{path}:{number}", context="Shell start-up file", prefix="shellrc")
                if re.search(r"(?:^|\s)(?:alias\s+(?:sudo|su|ssh)=|export\s+(?:LD_PRELOAD|PROMPT_COMMAND)=)", line):
                    ctx.finding("shellrc.hijack", "Shell start-up file hooks sudo/ssh or sets LD_PRELOAD/PROMPT_COMMAND", "high",
                                "Aliasing sudo/ssh or preloading libraries captures passwords and commands (T1546.004).",
                                location=f"{path}:{number}", evidence=line)
        elif name in ("authorized_keys", "authorized_keys2"):
            for number, line in enumerate(text.splitlines(), start=1):
                if 'command="' in line or "command='" in line:
                    ctx.finding("ssh.forced-command", "authorized_keys entry with a forced command", "low",
                                "command= runs a fixed program at login; legitimate for backups, but also used to hide backdoor logic.",
                                location=f"{path}:{number}", evidence=line[:80])
                if re.match(r"^\s*(?:ssh-|ecdsa-|sk-)", line) and "from=" not in line and "root" in lower:
                    ctx.finding("ssh.root-key-unrestricted", "root accepts a key from any address", "medium",
                                "A key in root's authorized_keys without from= restrictions allows root login from anywhere.",
                                location=f"{path}:{number}")
        elif lower.endswith(".rules") and "/udev/" in lower:
            for number, line in enumerate(text.splitlines(), start=1):
                match = re.search(r'RUN\+?="([^"]+)"', line)
                if match:
                    analyze_command(ctx, match.group(1), location=f"{path}:{number}", context="udev rule", prefix="udev")


def _analyze(ctx, data):
    if not data.get("reg_export") and not data.get("files"):
        raise ToolInputError("Provide reg_export (Windows) and/or files (Linux persistence files).")
    if data.get("reg_export"):
        ctx.input_kind = "reg-export"
        keys = parse_reg(data["reg_export"])
        if not keys:
            raise ToolInputError("reg_export contains no registry keys.")
        _windows(ctx, keys)
        ctx.artifacts["registry_keys"] = len(keys)
    if data.get("files"):
        ctx.input_kind = (ctx.input_kind + "+files") if ctx.input_kind else "files"
        files = file_list(data, max_files=2000)
        _linux(ctx, files)
        ctx.artifacts["files"] = len(files)
    ctx.limit("WMI event subscriptions, kernel drivers and browser/Office add-ins are not covered by this tool.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

def _today(data):
    if data.get("today"):
        try:
            return dt.date.fromisoformat(data["today"])
        except ValueError as exc:
            raise ToolInputError("today must be YYYY-MM-DD.") from exc
    return dt.date.today()


def _eol(name, version):
    label = f"{name} {version}".strip().lower()
    for row_id, product, name_re, version_re, dates, source in datasets.SOFTWARE_EOL:
        if not re.search(name_re, name.strip().lower()):
            continue
        if version_re is None:
            return row_id, product, None, dates["*"], source
        match = re.search(version_re, label)
        if not match:
            return None
        key = match.group(1)
        for prefix, date in dates.items():
            if key == prefix or key.startswith(prefix + "."):
                return row_id, product, key, date, source
        return None
    return None


def _analyze(ctx, data):
    if data.get("source") == "local":
        ctx.input_kind = "local"
        software = winlocal.installed_software()
    else:
        ctx.input_kind = "provided"
        ctx.execution_mode = "local"
        software = data.get("software")
        if not software:
            raise ToolInputError("Provide 'software' (list of {name, version, publisher}) or source='local'.")
    today = _today(data)
    seen_products = {}
    for index, item in enumerate(software):
        if index % 1000 == 0:
            ctx.check()
        name, version = str(item.get("name", "")).strip(), str(item.get("version", "")).strip()
        if not name:
            continue
        where = f"{name} {version}".strip()
        eol = _eol(name, version)
        if eol:
            row_id, product, key, date, source = eol
            ends = dt.date.fromisoformat(date)
            if ends < today:
                ctx.finding(f"eol.{row_id}" + (f".{key}" if key else ""), f"{product}{' ' + key if key else ''} is past end of support",
                            "high" if (today - ends).days > 365 else "medium",
                            f"Support ended on {date} (bundled lifecycle table dated {datasets.DATA_AS_OF}); security fixes are no longer published.",
                            assurance="verified_condition", location=where, references=[source],
                            recommendation="Upgrade to a supported release or remove it.")
            elif (ends - today).days <= 90:
                ctx.finding(f"eol-soon.{row_id}" + (f".{key}" if key else ""), f"{product}{' ' + key if key else ''} reaches end of support on {date}",
                            "low", "Plan the upgrade before fixes stop.", assurance="verified_condition", location=where, references=[source])
            seen_products.setdefault(product, set()).add(key or version)
        if datasets.REMOTE_ACCESS.search(name):
            ctx.finding(f"remote-access.{re.sub(r'[^a-z0-9]+', '-', name.lower())[:40]}", f"Remote-access tool installed: {name}", "low",
                        "Remote-control software is legitimate but is also a favourite persistence and fraud tool (T1219). Confirm it is expected.",
                        location=where)
        location = str(item.get("install_location") or "")
        if location and USER_WRITABLE.search(location.lower().replace("/", "\\") + "\\"):
            ctx.finding(f"user-writable-install.{index}", f"{name} is installed in a user-writable folder", "low",
                        "Programs under AppData/Downloads/Temp can be replaced by any process running as that user.",
                        location=location)
        if not str(item.get("publisher") or "").strip():
            ctx.finding(f"no-publisher.{index}", f"{name} has no publisher", "info", "Unidentified publishers are worth a second look.",
                        assurance="informational", location=where)
    ctx.artifacts.update({"software_count": len(software), "lifecycle_table_date": datasets.DATA_AS_OF,
                          "multiple_versions": {k: sorted(v) for k, v in seen_products.items() if len(v) > 1}})
    ctx.limit(f"End-of-support detection covers {len(datasets.SOFTWARE_EOL)} product lines in a table dated {datasets.DATA_AS_OF}; "
              "absence of a finding does not mean software is current or free of vulnerabilities.")



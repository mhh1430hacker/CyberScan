OFFICE_AND_BROWSERS = {"winword.exe", "excel.exe", "powerpnt.exe", "outlook.exe", "msaccess.exe", "mspub.exe", "onenote.exe",
                       "acrord32.exe", "acrobat.exe", "chrome.exe", "msedge.exe", "firefox.exe", "iexplore.exe", "wordpad.exe"}
SHELLS = {"cmd.exe", "powershell.exe", "pwsh.exe", "wscript.exe", "cscript.exe", "mshta.exe", "rundll32.exe", "regsvr32.exe",
          "bash.exe", "certutil.exe", "bitsadmin.exe", "wmic.exe"}
SINGLETONS = {"lsass.exe", "services.exe", "wininit.exe", "lsaiso.exe"}


def _analyze(ctx, data):
    if data.get("source") == "local":
        ctx.input_kind = "local"
        processes = winlocal.processes()
    elif data.get("processes"):
        ctx.input_kind, ctx.execution_mode = "provided", "local"
        processes = data["processes"]
    else:
        raise ToolInputError("Provide 'processes' or source='local'.")
    names = Counter(str(p.get("name", "")).lower() for p in processes)
    for name in SINGLETONS:
        if names.get(name, 0) > 1:
            ctx.finding(f"process.duplicate.{name}", f"{names[name]} instances of {name}", "high",
                        f"Windows runs exactly one {name}; extra copies are a classic masquerading sign.", location=name)
    for index, proc in enumerate(processes):
        if index % 500 == 0:
            ctx.check()
        name = str(proc.get("name") or "").lower()
        exe = str(proc.get("exe") or "")
        cmdline = str(proc.get("cmdline") or exe)
        where = f"pid {proc.get('pid', '?')} {name}"
        analyze_command(ctx, f'"{exe}" {cmdline.split(" ", 1)[1] if " " in cmdline else ""}' if exe else cmdline,
                        location=where, context="Process", prefix="process")
        parent = str(proc.get("parent") or "").lower()
        if parent in OFFICE_AND_BROWSERS and name in SHELLS:
            ctx.finding("process.office-spawns-shell", f"{parent} started {name}", "high",
                        "Documents and browsers rarely start shells or script hosts; this chain is typical of malicious macros "
                        "and exploit payloads (T1204.002).", location=where, evidence=cmdline)
    ctx.artifacts["process_count"] = len(processes)
    ctx.limit("Signatures, loaded modules and memory are not inspected; this is a metadata review of one snapshot.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local-system", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

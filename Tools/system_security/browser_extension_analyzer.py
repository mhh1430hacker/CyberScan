ALL_SITES = {"<all_urls>", "*://*/*", "http://*/*", "https://*/*"}
OFFICIAL_STORES = {"clients2.google.com", "update.googleapis.com", "edge.microsoft.com", "extensionwebstorebase.edgesv2.microsoft.com",
                   "extension-updates.opera.com", "versioncheck.addons.mozilla.org"}


def _engine():
    try:
        from detection.archives import inspect_browser_extension, open_zip
    except Exception as exc:  # noqa: BLE001
        raise Unavailable("the frozen detection engine (Tools/detection) is required for extension scoring.") from exc
    return inspect_browser_extension, open_zip


def _unpack(raw):
    if raw[:4] == b"Cr24":  # CRX2: magic, version, key len, sig len; CRX3: magic, version, header len
        version = struct.unpack("<I", raw[4:8])[0]
        if version == 2:
            key_len, sig_len = struct.unpack("<II", raw[8:16])
            return raw[16 + key_len + sig_len:]
        if version == 3:
            header_len = struct.unpack("<I", raw[8:12])[0]
            return raw[12 + header_len:]
        raise Unsupported(f"CRX version {version} is not supported.")
    return raw


def _manifest_zip(manifest_text):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr("manifest.json", manifest_text)
    return buffer.getvalue()


def _inspect(ctx, package, label):
    inspect, open_zip = _engine()
    archive = open_zip(package)
    if archive is None:
        raise ToolInputError(f"{label} is not a valid extension package (ZIP/CRX/XPI).")
    with archive:
        try:
            peek = json.loads(archive.read("manifest.json").decode("utf-8-sig", errors="replace"))
        except (KeyError, ValueError, zipfile.BadZipFile, RuntimeError):
            peek = {}
        update_host = (urlsplit(str(peek.get("update_url", ""))).hostname or "").lower() if isinstance(peek, dict) else ""

        def add(severity, title, weight, explanation, **data):
            if title == "Off-store update URL" and update_host in OFFICIAL_STORES:
                return  # the engine knows only the Google and Mozilla stores; Edge/Opera stores are official too
            slug = "-".join(title.lower().replace("(", "").replace(")", "").split())[:50]
            ctx.finding(f"extension.{slug}", title, severity, explanation, weight=weight, location=label,
                        evidence=", ".join(data.get("permissions", [])) or None)
        details = inspect(archive, add)
        try:
            manifest = json.loads(archive.read("manifest.json").decode("utf-8-sig", errors="replace"))
        except (KeyError, ValueError, zipfile.BadZipFile, RuntimeError):
            manifest = {}
    if not details.get("name") and not manifest:
        raise ToolInputError(f"{label} has no manifest.json.")
    if isinstance(manifest, dict):
        _extra(ctx, manifest, label)
    return {"name": details.get("name"), "version": details.get("version"), "manifest_version": details.get("manifest_version"),
            "permissions": details.get("permissions", [])[:50], "location": label}


def _extra(ctx, manifest, label):
    if manifest.get("manifest_version") == 2:
        ctx.finding("extension.manifest-v2", "Manifest V2 extension", "low",
                    "Chromium browsers have phased out Manifest V2; such extensions no longer receive the newer platform protections "
                    "and may be abandoned.", assurance="verified_condition", location=label)
    resources = manifest.get("web_accessible_resources") or []
    exposed = False
    for item in resources if isinstance(resources, list) else []:
        if isinstance(item, str):
            exposed = True  # MV2: accessible from every site
        elif isinstance(item, dict) and ALL_SITES & set(item.get("matches") or []):
            exposed = True
    if exposed:
        ctx.finding("extension.web-accessible-all", "Resources are exposed to every website", "low",
                    "Any site can load these files, which lets pages detect (fingerprint) the extension and sometimes attack it.",
                    location=label)
    for script in manifest.get("content_scripts") or []:
        if not isinstance(script, dict):
            continue
        broad = ALL_SITES & set(script.get("matches") or [])
        if broad and script.get("all_frames") and script.get("run_at") == "document_start":
            ctx.finding("extension.early-all-frames", "Injects into every frame of every site at document start", "medium",
                        "Running before page scripts in all frames on all sites gives the extension full control of every page you visit.",
                        location=label)
            break


def _profiles():
    roots = []
    local = os.environ.get("LOCALAPPDATA")
    home = Path.home()
    if local:
        roots += [Path(local) / p for p in ("Google/Chrome/User Data", "Microsoft/Edge/User Data", "BraveSoftware/Brave-Browser/User Data")]
    roots += [home / ".config" / p for p in ("google-chrome", "chromium", "microsoft-edge", "BraveSoftware/Brave-Browser")]
    roots += [home / "Library/Application Support" / p for p in ("Google/Chrome", "Microsoft Edge")]
    manifests = []
    for root in roots:
        if not root.is_dir():
            continue
        for manifest in root.glob("*/Extensions/*/*/manifest.json"):
            manifests.append(manifest)
    firefox = [Path(os.environ.get("APPDATA", "")) / "Mozilla/Firefox/Profiles", home / ".mozilla/firefox"]
    xpis = [x for base in firefox if base.is_dir() for x in base.glob("*/extensions/*.xpi")]
    return manifests[:500], xpis[:200]


def _analyze(ctx, data):
    inventory = []
    if data.get("source") == "local":
        ctx.input_kind = "local"
        manifests, xpis = _profiles()
        if not manifests and not xpis:
            ctx.limit("No Chromium or Firefox extension folders were found for this user.")
        for path in manifests:
            ctx.check()
            try:
                text = path.read_text(encoding="utf-8-sig", errors="replace")[:1048576]
            except OSError:
                continue
            label = f"{path.parents[3].name}/{path.parents[1].name}"  # profile/extension-id
            inventory.append(_inspect(ctx, _manifest_zip(text), label))
        for path in xpis:
            ctx.check()
            try:
                inventory.append(_inspect(ctx, path.read_bytes()[:20 * 1024 * 1024], f"firefox/{path.name}"))
            except (OSError, ToolInputError):
                continue
    elif data.get("manifest"):
        ctx.input_kind, ctx.execution_mode = "manifest", "local"
        try:
            json.loads(data["manifest"])
        except ValueError as exc:
            raise ToolInputError("manifest is not valid JSON.") from exc
        inventory.append(_inspect(ctx, _manifest_zip(data["manifest"]), "manifest.json"))
    elif data.get("data_base64"):
        ctx.input_kind, ctx.execution_mode = "package", "local"
        raw = decode_base64(data["data_base64"], max_bytes=50 * 1024 * 1024)
        inventory.append(_inspect(ctx, _unpack(raw), data.get("file_name") or "extension package"))
    else:
        raise ToolInputError("Provide manifest, data_base64 (crx/zip/xpi) or source='local'.")
    ctx.artifacts["extensions"] = inventory
    ctx.limit("Bundled JavaScript is not reviewed for malicious behaviour; names may appear as __MSG_..__ placeholders.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local-system", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

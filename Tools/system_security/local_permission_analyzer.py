SECRET_FILE = re.compile(r"(?i)(?:^|/)(?:id_(?:rsa|dsa|ecdsa|ed25519)|[^/]+\.(?:pem|key|p12|pfx|ppk|kdbx)|\.env(?:\.[\w.-]+)?|"
                         r"\.pgpass|\.netrc|\.git-credentials|credentials(?:\.json)?|\.npmrc|\.pypirc|shadow|gshadow)$")
BROAD_GROUPS = re.compile(r"(?i)^(?:everyone|builtin\\users|nt authority\\authenticated users|authenticated users|users|"
                          r"nt authority\\interactive|\\everyone)$")
WRITE_RIGHTS = re.compile(r"\((?:F|M|W|WD|AD|WDAC|WO|GA|GW)\)")
LS_LINE = re.compile(r"^(?P<mode>[-dlcbps][rwxsStT-]{9})[.+@]?\s+\d+\s+\S+\s+\S+\s+\d+(?:,\s*\d+)?\s+\S+\s+\S+\s+\S+\s+(?P<name>.+)$")
SYSTEM_DIRS = re.compile(r"(?i)^(?:/usr/|/bin/|/sbin/|/etc/|/lib|/opt/|/boot/|c:\\windows\\|c:\\program files)")


def _check_mode(ctx, path, mode, *, is_dir, is_link=False):
    if is_link:
        return
    other_write = bool(mode & stat.S_IWOTH)
    group_write = bool(mode & stat.S_IWGRP)
    sticky = bool(mode & stat.S_ISVTX)
    if other_write and not (is_dir and sticky):
        severity = "high" if SYSTEM_DIRS.search(path) or not is_dir else "medium"
        ctx.finding("perm.world-writable", f"World-writable {'directory' if is_dir else 'file'}", severity,
                    "Any local user can modify or replace this" + (" (no sticky bit, so they can also delete others' files)." if is_dir else "."),
                    assurance="verified_condition", location=path, recommendation=f"chmod o-w '{path}'")
    elif group_write and SYSTEM_DIRS.search(path) and not is_dir:
        ctx.finding("perm.group-writable-system", "Group-writable file in a system location", "low",
                    "Members of the owning group can change a system file.", assurance="verified_condition", location=path)
    if not is_dir and mode & (stat.S_ISUID | stat.S_ISGID):
        bit = "setuid" if mode & stat.S_ISUID else "setgid"
        ctx.finding(f"perm.{bit}", f"{bit} binary", "medium" if not SYSTEM_DIRS.search(path) else "info",
                    f"Runs with its owner's privileges; {bit} binaries outside system directories are a common privilege-escalation path.",
                    assurance="verified_condition" if not SYSTEM_DIRS.search(path) else "informational", location=path)
    if not is_dir and SECRET_FILE.search(path.replace("\\", "/")) and mode & (stat.S_IROTH | stat.S_IRGRP):
        ctx.finding("perm.secret-readable", "Private key or credential file readable by others", "high",
                    "Keys and credential files should be readable by their owner only (0600).", assurance="verified_condition",
                    location=path, recommendation=f"chmod 600 '{path}'")
    if is_dir and path.rstrip("/").endswith("/.ssh") and mode & 0o077:
        ctx.finding("perm.ssh-dir", ".ssh directory is accessible to others", "medium", "OpenSSH expects ~/.ssh to be 0700.",
                    assurance="verified_condition", location=path)


def _mode_from_ls(text):
    kinds = {"d": stat.S_IFDIR, "l": stat.S_IFLNK, "-": stat.S_IFREG}
    mode = kinds.get(text[0], stat.S_IFREG)
    bits = text[1:]
    for index, (char, flag) in enumerate(zip(bits, (stat.S_IRUSR, stat.S_IWUSR, stat.S_IXUSR, stat.S_IRGRP, stat.S_IWGRP,
                                                    stat.S_IXGRP, stat.S_IROTH, stat.S_IWOTH, stat.S_IXOTH))):
        if char in "rwxst":
            mode |= flag
        if index == 2 and char in "sS":
            mode |= stat.S_ISUID
        if index == 5 and char in "sS":
            mode |= stat.S_ISGID
        if index == 8 and char in "tT":
            mode |= stat.S_ISVTX
    return mode


def _ls(ctx, text):
    directory, count = "", 0
    for line in text.splitlines():
        if line.endswith(":") and not line.startswith(("-", "d", "l")):
            directory = line[:-1].rstrip("/") + "/"
            continue
        match = LS_LINE.match(line)
        if not match:
            continue
        count += 1
        name = match.group("name").split(" -> ")[0]
        mode = _mode_from_ls(match.group("mode"))
        path = name if name.startswith("/") else directory + name
        _check_mode(ctx, path, mode, is_dir=stat.S_ISDIR(mode), is_link=stat.S_ISLNK(mode))
    return count


PRINCIPAL_START = re.compile(r"(?i)^(?:(?:BUILTIN|NT AUTHORITY|NT SERVICE|APPLICATION PACKAGE AUTHORITY|[\w.-]+)\\[^:\\]+|"
                             r"Everyone|CREATOR OWNER|CREATOR GROUP|Users|Administrators|Authenticated Users):\(")


def _split_first_line(line, next_line):
    """icacls prints '<path> <first ACE>' and aligns later ACEs under the first one; use that indent."""
    indent = len(next_line) - len(next_line.lstrip(" ")) if next_line and next_line.startswith(" ") else 0
    if indent and PRINCIPAL_START.match(line[indent:]):
        return line[:indent].rstrip(), line[indent:].strip()
    for index, char in enumerate(line):  # fallback: first space after which a known principal starts
        if char == " " and PRINCIPAL_START.match(line[index + 1:]):
            return line[:index], line[index + 1:].strip()
    return None, None


def _icacls(ctx, text):
    lines = [l for l in text.splitlines() if l.strip() and not l.startswith("Successfully processed")]
    current, count = None, 0
    for index, line in enumerate(lines):
        if not line.startswith(" ") and re.match(r"^(?:[A-Za-z]:\\|\\\\)", line):
            current, ace = _split_first_line(line, lines[index + 1] if index + 1 < len(lines) else "")
            if current is None:
                continue
        elif current and ":" in line:
            ace = line.strip()
        else:
            continue
        count += 1
        principal, _, rights = ace.partition(":")
        if BROAD_GROUPS.match(principal.strip()) and WRITE_RIGHTS.search(rights) and "(DENY)" not in rights.upper():
            program = bool(re.search(r"(?i)\\program files|\\windows\\|\\programdata\\", current + "\\"))
            ctx.finding("acl.broad-write", f"{principal.strip()} can modify {current}", "high" if program else "medium",
                        f"The ACL grants {rights} to {principal.strip()}. In program or service folders this lets any user replace "
                        "binaries that run with higher privileges (T1574.010).", assurance="verified_condition", location=current,
                        evidence=f"{principal}:{rights}")
    return count


def _walk(ctx, roots, max_depth):
    count = 0
    for root in roots:
        base = Path(root)
        if not base.exists():
            ctx.limit(f"{root} does not exist; skipped.")
            continue
        stack = [(base, 0)]
        while stack:
            ctx.check()
            path, depth = stack.pop()
            try:
                info = os.lstat(path)
            except OSError:
                continue
            count += 1
            if count > 20000:
                ctx.limit("Stopped after 20,000 entries.", partial=True)
                return count
            is_dir = stat.S_ISDIR(info.st_mode)
            if os.name != "nt":
                _check_mode(ctx, str(path), info.st_mode, is_dir=is_dir, is_link=stat.S_ISLNK(info.st_mode))
            if is_dir and depth < max_depth and not stat.S_ISLNK(info.st_mode):
                try:
                    stack.extend((child, depth + 1) for child in path.iterdir())
                except OSError:
                    continue
        if os.name == "nt":
            _icacls(ctx, winlocal.run_readonly(["icacls", str(base)], min(10.0, ctx.deadline.remaining())))
    return count


def _analyze(ctx, data):
    count = 0
    if data.get("ls_output"):
        ctx.input_kind, ctx.execution_mode = "ls", "local"
        count += _ls(ctx, data["ls_output"])
    if data.get("icacls_output"):
        ctx.input_kind, ctx.execution_mode = "icacls", "local"
        count += _icacls(ctx, data["icacls_output"])
    if data.get("paths"):
        ctx.input_kind = "local-walk"
        count += _walk(ctx, data["paths"], max(0, min(int(data.get("max_depth") or 2), 6)))
    if not any(data.get(k) for k in ("ls_output", "icacls_output", "paths")):
        raise ToolInputError("Provide ls_output, icacls_output or paths.")
    if count == 0:
        raise ToolInputError("No permission entries were recognized in the input.")
    ctx.artifacts["entries_checked"] = count



LOCAL_KEYS = sorted({check[1] for check in WINDOWS_CHECKS})


def _windows(ctx, keys, *, local):
    unchecked = []
    for fid, key, name, default, bad, severity, title, why in WINDOWS_CHECKS:
        values = keys.get(normalize_key(HKLM + key))
        if values is None:
            if local:
                values = {}  # the key does not exist on this machine: the Windows default applies
            else:
                unchecked.append(key)
                continue
        value = values.get(name.lower(), default)
        if not isinstance(value, int):
            continue
        if bad(value):
            ctx.finding(f"windows.{fid}", title, severity, why + ("" if name.lower() in values else " (value not set: Windows default)"),
                        assurance="verified_condition" if severity != "info" else "informational",
                        location=f"HKLM\\{key}\\{name} = {value}")
    if unchecked:
        ctx.limit(f"{len(set(unchecked))} registry key(s) were not in the export, so their settings were not judged: "
                  + "; ".join(sorted(set(unchecked))[:6]) + ("…" if len(set(unchecked)) > 6 else ""))


def _sysctl(ctx, text):
    values = {}
    for line in text.splitlines():
        key, sep, value = line.partition("=")
        if sep:
            values[key.strip()] = value.strip()
    if not values:
        raise ToolInputError("No 'key = value' lines found in sysctl output.")
    for key, (bad, severity, title, why) in SYSCTL_CHECKS.items():
        if key in values and bad(values[key]):
            ctx.finding(f"sysctl.{key}", title, severity, why, assurance="verified_condition" if severity != "info" else "informational",
                        location=f"{key} = {values[key]}")
    missing = [k for k in SYSCTL_CHECKS if k not in values]
    if missing:
        ctx.limit(f"{len(missing)} sysctl key(s) were absent from the input and not judged.")


def _analyze(ctx, data):
    analysed = False
    if data.get("source") == "local":
        ctx.input_kind = "local"
        keys = {}
        for key in LOCAL_KEYS:
            values = winlocal.read_values("HKEY_LOCAL_MACHINE", key)
            if values:
                keys[normalize_key(HKLM + key)] = values
        _windows(ctx, keys, local=True)
        analysed = True
    else:
        ctx.execution_mode = "local"
    if data.get("reg_export"):
        ctx.input_kind = ctx.input_kind or "reg-export"
        _windows(ctx, parse_reg(data["reg_export"]), local=False)
        analysed = True
    if data.get("sysctl"):
        ctx.input_kind = ctx.input_kind or "sysctl"
        _sysctl(ctx, data["sysctl"])
        analysed = True
    if not analysed:
        raise ToolInputError("Provide reg_export, sysctl or source='local'.")



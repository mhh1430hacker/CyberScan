INTERNAL_HOST = re.compile(r"(?i)\b(?:[a-z0-9-]+\.)+(?:local|lan|corp|internal|intranet|home\.arpa|localdomain|ad|int)\b(?![.\w-])")
PRIVATE_IP = re.compile(r"(?<![\d.])(?:10\.\d{1,3}|172\.(?:1[6-9]|2\d|3[01])|192\.168)\.\d{1,3}\.\d{1,3}(?![\d.])")
UNC = re.compile(r"\\\\[A-Za-z0-9._-]{2,63}\\[A-Za-z0-9$._ -]{1,80}")
USER_PATH = re.compile(r"(?i)\b[A-Z]:\\Users\\(?!Public\\|Default\\|All Users\\)([^\\\s\"'<>|]{2,40})\\|/(?:home|Users)/([a-z_][a-z0-9_.-]{1,31})/")


def _text_checks(ctx, text, where, internal_domains):
    secrets = [s for s in secrets_kit.scan(text) if not s["placeholder"]]
    for item in secrets:
        ctx.finding(f"leak.secret.{item['type']}", f"{item['label']} would be shared", "critical" if item["category"] == "private_key" else "high",
                    f"Line {item['line']}. Remove it and rotate the secret.", location=f"{where}:{item['line']}")
        ctx.evidence("masked_secret", f"{item['label']}: {item['masked']}", finding_id=f"leak.secret.{item['type']}")
    counts = pii.summarize(pii.find(text))
    for kind, count in counts.items():
        ctx.finding(f"leak.pii.{kind}", f"{count} {pii.LABELS[kind].lower()}(s) would be shared",
                    "info" if kind == "ip_address" else pii.SEVERITY[kind], "Confirm every recipient may see this personal data.",
                    assurance="informational" if kind == "ip_address" else "heuristic", location=where)
    hosts = set(m.group(0).lower() for m in INTERNAL_HOST.finditer(text))
    for domain in internal_domains:
        hosts |= set(m.group(0).lower() for m in re.finditer(rf"(?i)\b(?:[a-z0-9-]+\.)*{re.escape(domain.lower().strip('.'))}\b", text))
    if hosts:
        ctx.finding("leak.internal-hosts", f"{len(hosts)} internal host name(s)", "medium",
                    f"e.g. {', '.join(sorted(hosts)[:5])}. Internal names map your network for an attacker.", location=where)
    ips = sorted({m.group(0) for m in PRIVATE_IP.finditer(text) if netflow.is_internal(m.group(0))})
    if ips:
        ctx.finding("leak.private-ips", f"{len(ips)} private IP address(es)", "low", f"e.g. {', '.join(ips[:5])}.", location=where)
    shares = sorted({m.group(0) for m in UNC.finditer(text)})
    if shares:
        ctx.finding("leak.unc-paths", f"{len(shares)} network share path(s)", "medium", f"e.g. {shares[0]}", location=where)
    users = sorted({(m.group(1) or m.group(2)) for m in USER_PATH.finditer(text)})
    if users:
        ctx.finding("leak.user-paths", f"Paths reveal {len(users)} user name(s)", "low",
                    f"User-profile paths expose account names (e.g. '{users[0]}').", location=where)
    return {"secrets": len(secrets), "pii": counts, "internal_hosts": len(hosts)}


def _ooxml(ctx, raw, where):
    try:
        info = metadata.ooxml_inventory(raw)
    except ValueError as exc:
        raise ToolInputError(str(exc)) from exc
    props = info["properties"]
    people = {k: props[k] for k in ("creator", "lastModifiedBy", "Manager", "Company") if props.get(k)}
    if people:
        ctx.finding("leak.doc-people", "Author / company metadata", "low",
                    f"Document properties name {', '.join(f'{k}={v}' for k, v in people.items())}.", assurance="verified_condition", location=where)
    if props.get("Template") and re.search(r"[\\/]", props["Template"]):
        ctx.finding("leak.template-path", "Template path reveals a local or network path", "low", props["Template"],
                    assurance="verified_condition", location=where)
    if info["comments"]:
        ctx.finding("leak.comments", f"{info['comments']} comment(s)", "medium",
                    "Review comments travel with the document" + (f"; authors: {', '.join(info['comment_authors'][:5])}" if info["comment_authors"] else "") + ".",
                    assurance="verified_condition", location=where)
    if info["tracked_insertions"] or info["tracked_deletions"]:
        ctx.finding("leak.tracked-changes", "Tracked changes are present", "high",
                    f"{info['tracked_deletions']} deletion(s) and {info['tracked_insertions']} insertion(s): deleted text can be read by "
                    "anyone who opens the file.", assurance="verified_condition", location=where, recommendation="Accept or reject all changes before sharing.")
    if info["hidden_text_runs"]:
        ctx.finding("leak.hidden-text", "Hidden text", "medium", f"{info['hidden_text_runs']} run(s) formatted as hidden.",
                    assurance="verified_condition", location=where)
    if info["custom_properties"]:
        ctx.finding("leak.custom-properties", "Custom document properties", "low", ", ".join(info["custom_properties"][:10]),
                    assurance="verified_condition", location=where)
    if info["embedded_objects"]:
        ctx.finding("leak.embedded-objects", f"{len(info['embedded_objects'])} embedded object(s)", "medium",
                    "Embedded files (spreadsheets, documents) carry their own full data, often more than is visible.",
                    assurance="verified_condition", location=where)
    if info["thumbnail"]:
        ctx.finding("leak.thumbnail", "Embedded thumbnail", "info", "A preview image of the first page is stored in the file.",
                    assurance="informational", location=where)
    ctx.artifacts["document"] = {k: v for k, v in info.items() if k != "properties"} | {"property_names": sorted(props)}


def _pdf(ctx, raw, where):
    info = metadata.pdf_inventory(raw)
    named = {k: v for k, v in info["info"].items() if k in ("Author", "Creator", "Producer", "Title", "Subject")}
    if named.get("Author"):
        ctx.finding("leak.pdf-author", "PDF names its author", "low", f"Author = {named['Author']}", assurance="verified_condition", location=where)
    if info["revisions"] > 1:
        ctx.finding("leak.pdf-revisions", f"PDF has {info['revisions']} saved revisions", "medium",
                    "Incremental saves keep earlier versions inside the file; redacted or removed content may still be recoverable.",
                    assurance="verified_condition", location=where, recommendation="Re-save as a new, flattened PDF ('Save As' / print to PDF).")
    if info["embedded_files"]:
        ctx.finding("leak.pdf-attachments", f"{info['embedded_files']} embedded file(s)", "medium", "Attachments inside the PDF are shared too.",
                    assurance="verified_condition", location=where)
    ctx.artifacts["document"] = {"pdf_info_keys": sorted(info["info"]), "revisions": info["revisions"], "xmp": info["xmp_metadata"]}


def _analyze(ctx, data):
    domains = [d for d in data.get("internal_domains") or [] if re.fullmatch(r"[A-Za-z0-9.-]{2,253}", d)]
    where = data.get("file_name") or "content"
    if data.get("content") is not None:
        ctx.input_kind = "text"
        ctx.artifacts["text"] = _text_checks(ctx, data["content"], where, domains)
        return
    if not data.get("data_base64"):
        raise ToolInputError("Provide content (text) or data_base64 (text, DOCX/XLSX/PPTX or PDF).")
    raw = decode_base64(data["data_base64"], max_bytes=50 * 1024 * 1024)
    kind = metadata.sniff(raw)
    ctx.input_kind = kind
    if kind == "ooxml":
        _ooxml(ctx, raw, where)
        text = _ooxml_text(raw)
    elif kind == "pdf":
        _pdf(ctx, raw, where)
        literals = re.findall(rb"\(([^()\\]{3,200})\)", raw[:20_000_000])[:20000]
        text = " ".join(s.decode("latin-1", errors="replace") for s in literals)
        ctx.limit("PDF text in compressed streams is not extracted; only literal strings were scanned.")
    else:
        text = raw.decode("utf-8", errors="replace")
    ctx.artifacts["text"] = _text_checks(ctx, text, where, domains)


def _ooxml_text(raw):
    import io
    import zipfile

    parts = []
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        for info in archive.infolist()[:2000]:
            if info.filename.endswith(".xml") and info.file_size < 4 * 1024 * 1024 and not info.flag_bits & 1 and (
                    info.filename.startswith(("word/", "xl/", "ppt/", "docProps/"))):
                xml = archive.read(info).decode("utf-8", errors="replace")
                parts.append(re.sub(r"<[^>]+>", " ", xml))
    return "\n".join(parts)



from security_toolkit import metadata  # noqa: E402
from security_toolkit.core import Unsupported, decode_base64, run_tool  # noqa: E402


def _analyze(ctx, data):
    raw = decode_base64(data["data_base64"], max_bytes=50 * 1024 * 1024)
    kind = metadata.sniff(raw)
    if kind not in ("jpeg", "png", "webp", "tiff"):
        raise Unsupported("the file is not a JPEG, PNG, WebP or TIFF image.")
    ctx.input_kind = kind
    name = data.get("file_name") or f"image.{kind}"
    inventory = metadata.image_inventory(raw)
    blocks = sorted({b["kind"] for b in inventory})
    ctx.artifacts["metadata_blocks"] = [{"kind": b["kind"], "bytes": b["bytes"]} for b in inventory][:100]
    if "xmp" in blocks:
        ctx.finding("exif.xmp", "XMP metadata block present", "low",
                    "XMP often records the editing history, creator tool and sometimes the author or document IDs.",
                    assurance="verified_condition", location=name)
    if "iptc" in blocks:
        ctx.finding("exif.iptc", "IPTC (Photoshop) metadata present", "low", "IPTC can name the photographer, contact details and captions.",
                    assurance="verified_condition", location=name)
    if "comment" in blocks or any(b.get("keyword", "").lower() in ("comment", "author", "description") for b in inventory):
        ctx.finding("exif.comment", "Embedded comment or text metadata", "low", "Free-text comments can contain names or notes.",
                    assurance="verified_condition", location=name)

    values = metadata.exif_values(raw)
    if values is None:
        if "exif" in blocks:
            ctx.finding("exif.present", "EXIF metadata present (values not decoded)", "medium",
                        "An EXIF block exists; install Pillow to see whether it holds location or serial numbers.",
                        assurance="verified_condition", location=name)
        ctx.limit("Pillow is not installed: EXIF values (GPS, serial numbers) could not be decoded.", partial=True)
        return
    gps = values.pop("GPS", None)
    if gps:
        coords = metadata.gps_coordinates(gps)
        if coords:
            ctx.artifacts["gps_rounded"] = {"latitude": round(coords[0], 2), "longitude": round(coords[1], 2)}
            ctx.finding("exif.gps", "Image contains a GPS location", "high",
                        "The photo records where it was taken (shown here rounded to ~1 km). Anyone you share the original with can "
                        "map it, e.g. to your home.", assurance="verified_condition", location=name,
                        recommendation="Strip metadata before sharing (tool 080 verifies the result).")
    for field, fid, severity, why in (("BodySerialNumber", "exif.camera-serial", "medium", "A camera serial number links all photos from one device."),
                                      ("LensSerialNumber", "exif.lens-serial", "low", "A lens serial number links photos to one owner."),
                                      ("CameraOwnerName", "exif.owner", "medium", "The camera owner's name is embedded."),
                                      ("Artist", "exif.artist", "medium", "An author/artist name is embedded."),
                                      ("XPAuthor", "exif.xp-author", "medium", "A Windows author name is embedded."),
                                      ("ImageUniqueID", "exif.unique-id", "low", "A unique image ID can link copies of the photo.")):
        if values.get(field):
            ctx.finding(fid, f"{field} is set", severity, why, assurance="verified_condition", location=name)
    if values.get("_has_thumbnail"):
        ctx.finding("exif.thumbnail", "Embedded EXIF thumbnail", "low",
                    "The thumbnail is generated by the camera; after cropping or blurring in some editors it still shows the original.",
                    assurance="verified_condition", location=name)
    device = " ".join(str(values[k]) for k in ("Make", "Model") if values.get(k))
    if device or values.get("DateTimeOriginal") or values.get("Software"):
        ctx.finding("exif.device-time", "Device model, capture time or software recorded", "info",
                    f"Device: {device or 'n/a'}; captured: {values.get('DateTimeOriginal', 'n/a')}; software: {values.get('Software', 'n/a')}.",
                    assurance="informational", location=name)
    ctx.artifacts["fields_present"] = sorted(k for k in values if not k.startswith("_"))


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

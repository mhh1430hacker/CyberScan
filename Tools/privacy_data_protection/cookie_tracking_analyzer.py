SESSION_NAME = re.compile(r"(?i)(?:sess|sid\b|^sid|auth|token|jwt|login|remember|csrf|xsrf)")
THIRTEEN_MONTHS = 395 * 86400


def _parse_set_cookie(header, origin_host, now):
    parts = [p.strip() for p in header.split(";")]
    name, _, _value = parts[0].partition("=")
    cookie = {"name": name.strip(), "domain": origin_host, "host_only": True, "secure": False, "httponly": False, "samesite": None,
              "expires": None, "path": "/"}
    for attribute in parts[1:]:
        key, _, val = attribute.partition("=")
        key = key.strip().lower()
        if key == "domain" and val:
            cookie["domain"], cookie["host_only"] = val.strip().lstrip(".").lower(), False
        elif key == "secure":
            cookie["secure"] = True
        elif key == "httponly":
            cookie["httponly"] = True
        elif key == "samesite":
            cookie["samesite"] = val.strip().lower()
        elif key == "max-age" and val.strip().lstrip("-").isdigit():
            cookie["expires"] = now + int(val.strip())
        elif key == "expires" and cookie["expires"] is None:
            try:
                cookie["expires"] = parsedate_to_datetime(val.strip()).timestamp()
            except (TypeError, ValueError):
                pass
        elif key == "path":
            cookie["path"] = val.strip()
    return cookie


def _from_har(text, now):
    try:
        har = json.loads(text)
        entries = har["log"]["entries"]
    except (ValueError, KeyError, TypeError) as exc:
        raise ToolInputError("har is not a valid HAR (log.entries missing).") from exc
    cookies, first_party = [], None
    for entry in entries[:20000]:
        url = (entry.get("request") or {}).get("url", "")
        host = (urlsplit(url).hostname or "").lower()
        if entry.get("_initiator") is None and first_party is None and (entry.get("response") or {}).get("content", {}).get("mimeType", "").startswith("text/html"):
            first_party = host
        for header in (entry.get("response") or {}).get("headers") or []:
            if str(header.get("name", "")).lower() == "set-cookie":
                for line in str(header.get("value", "")).split("\n"):
                    cookie = _parse_set_cookie(line, host, now)
                    cookie["scheme"] = urlsplit(url).scheme
                    cookies.append(cookie)
    return cookies, first_party


def _from_cookies_txt(text):
    cookies = []
    for line in text.splitlines():
        if not line.strip() or (line.startswith("#") and not line.startswith("#HttpOnly_")):
            continue
        httponly = line.startswith("#HttpOnly_")
        fields = (line[len("#HttpOnly_"):] if httponly else line).split("\t")
        if len(fields) < 7:
            continue
        domain, _flag, path, secure, expires, name = fields[:6]
        cookies.append({"name": name, "domain": domain.lstrip(".").lower(), "host_only": not domain.startswith("."), "secure": secure.upper() == "TRUE",
                        "httponly": httponly, "samesite": None, "expires": float(expires) if expires.isdigit() and expires != "0" else None,
                        "path": path})
    return cookies


def _analyze(ctx, data):
    now = float(data.get("now") or time.time())
    site = (data.get("site") or "").lower().strip(".") or None
    if data.get("har"):
        ctx.input_kind = "har"
        cookies, detected = _from_har(data["har"], now)
        site = site or detected
    elif data.get("cookies_txt"):
        ctx.input_kind = "cookies.txt"
        cookies = _from_cookies_txt(data["cookies_txt"])
    elif data.get("set_cookie"):
        ctx.input_kind = "set-cookie"
        host = site or "site.invalid"
        cookies = [_parse_set_cookie(re.sub(r"(?i)^set-cookie:\s*", "", line), host, now)
                   for line in data["set_cookie"].splitlines() if "=" in line]
    else:
        raise ToolInputError("Provide set_cookie (header lines), har or cookies_txt.")
    if not cookies:
        raise ToolInputError("No cookies were found in the input.")
    first_party = registrable_domain(site) if site else None
    vendors, third = {}, set()
    for cookie in cookies:
        ctx.check()
        name, domain = cookie["name"], cookie["domain"]
        where = f"{name} @ {domain}"
        vendor = datasets.tracker_vendor(name)
        if vendor:
            vendors.setdefault(vendor, set()).add(name)
        if first_party and registrable_domain(domain) != first_party:
            third.add(domain)
        if cookie["expires"] and cookie["expires"] - now > THIRTEEN_MONTHS:
            ctx.finding(f"cookie.long-lived.{name}", f"Cookie '{name}' lives longer than 13 months", "low",
                        f"Expires in {(cookie['expires'] - now) / 86400:.0f} days; EU regulators (CNIL) consider 13 months the maximum for consent-based cookies.",
                        assurance="verified_condition", location=where)
        if cookie["samesite"] == "none" and not cookie["secure"]:
            ctx.finding(f"cookie.samesite-none-insecure.{name}", f"'{name}' has SameSite=None without Secure", "medium",
                        "Browsers reject such cookies; if accepted by an old browser they are sent on cross-site requests over HTTP.",
                        assurance="verified_condition", location=where)
        if name.startswith("__Host-") and (not cookie["secure"] or not cookie["host_only"] or cookie["path"] != "/"):
            ctx.finding(f"cookie.host-prefix.{name}", f"'{name}' breaks the __Host- prefix rules", "medium",
                        "__Host- cookies must be Secure, have Path=/ and no Domain attribute; browsers discard violating cookies.",
                        assurance="verified_condition", location=where)
        if name.startswith("__Secure-") and not cookie["secure"]:
            ctx.finding(f"cookie.secure-prefix.{name}", f"'{name}' breaks the __Secure- prefix rule", "medium",
                        "__Secure- cookies must carry the Secure attribute.", assurance="verified_condition", location=where)
        if SESSION_NAME.search(name) and not vendor:
            if not cookie["secure"]:
                ctx.finding(f"cookie.session-not-secure.{name}", f"Session-like cookie '{name}' is not Secure", "medium",
                            "It can be sent over plain HTTP and captured on the network.", assurance="verified_condition", location=where)
            if not cookie["httponly"] and ctx.input_kind != "cookies.txt":
                ctx.finding(f"cookie.session-not-httponly.{name}", f"Session-like cookie '{name}' is readable by JavaScript", "medium",
                            "Without HttpOnly, any cross-site-scripting bug can steal the session.", assurance="verified_condition", location=where)
            if cookie["samesite"] in (None, "none") and ctx.input_kind != "cookies.txt":
                ctx.finding(f"cookie.session-samesite.{name}", f"Session-like cookie '{name}' has no SameSite protection", "low",
                            "Lax or Strict limits cross-site request forgery.", assurance="verified_condition", location=where)
    for vendor, names in vendors.items():
        ctx.finding(f"tracker.{re.sub(r'[^a-z0-9]+', '-', vendor.lower())}", f"Tracking cookies from {vendor}", "low",
                    f"Cookies {', '.join(sorted(names))} are set by {vendor}'s analytics/advertising scripts; in the EU/UK they need prior consent.",
                    location=", ".join(sorted(names)))
    if third:
        ctx.finding("cookie.third-party", f"{len(third)} third-party cookie domain(s)", "low",
                    f"Cookies from {', '.join(sorted(third)[:8])} belong to other sites than {first_party}; they can track visitors across sites.",
                    location=first_party)
    ctx.artifacts.update({"cookies": len(cookies), "first_party": first_party, "trackers": {v: sorted(n) for v, n in vendors.items()},
                          "third_party_domains": sorted(third)[:100], "tracker_list_date": datasets.DATA_AS_OF})
    if not site:
        ctx.limit("No 'site' was given, so first- vs third-party could not be decided.")



def _get(tree, dotted):
    node = tree
    for part in dotted.split("."):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def _chromium(ctx, text, label):
    try:
        prefs = json.loads(text)
    except ValueError as exc:
        raise ToolInputError(f"{label} is not valid JSON.") from exc
    if _get(prefs, "safebrowsing.enabled") is False:
        ctx.finding("chromium.safe-browsing-off", "Safe Browsing is disabled", "high",
                    "Known phishing and malware sites are no longer blocked.", assurance="verified_condition", location=label)
    mode = _get(prefs, "profile.cookie_controls_mode")
    blocked = _get(prefs, "profile.block_third_party_cookies")
    if mode == 0 or blocked is False:
        ctx.finding("chromium.third-party-cookies", "Third-party cookies are allowed", "medium",
                    "Cross-site trackers can follow you between sites.", assurance="verified_condition", location=label)
    if _get(prefs, "profile.password_manager_leak_detection") is False:
        ctx.finding("chromium.leak-detection-off", "Password leak detection is off", "medium",
                    "You will not be warned when a saved password appears in a breach.", assurance="verified_condition", location=label)
    if _get(prefs, "enable_do_not_track") is not True and _get(prefs, "enable_do_not_track") is not None:
        ctx.finding("chromium.dnt-off", "Do Not Track is off", "info", "Most sites ignore DNT; Global Privacy Control is more useful.",
                    assurance="informational", location=label)
    defaults = _get(prefs, "profile.default_content_setting_values") or {}
    for permission, severity in PERMISSIONS.items():
        if defaults.get(permission) == 1:  # 1 = allow for every site, 2 = block, 3 = ask
            ctx.finding(f"chromium.permission-allowed.{permission}", f"'{permission}' is allowed for every site by default", severity,
                        "Any site can use this capability without asking.", assurance="verified_condition", location=label)
    exceptions = _get(prefs, "profile.content_settings.exceptions") or {}
    granted = {p: [site for site, v in (exceptions.get(p) or {}).items() if isinstance(v, dict) and v.get("setting") == 1]
               for p in ("geolocation", "media_stream_camera", "media_stream_mic", "notifications")}
    ctx.artifacts["sites_with_permission"] = {p: sorted(s)[:20] for p, s in granted.items() if s}
    if _get(prefs, "autofill.credit_card_enabled") is True:
        ctx.finding("chromium.card-autofill", "Payment-card autofill is on", "info",
                    "Cards saved in the browser are available to anyone using this profile.", assurance="informational", location=label)


def _local_state(ctx, text):
    try:
        state = json.loads(text)
    except ValueError as exc:
        raise ToolInputError("chromium_local_state is not valid JSON.") from exc
    mode = _get(state, "dns_over_https.mode")
    if mode == "off":
        ctx.finding("chromium.doh-off", "DNS over HTTPS is off", "low",
                    "DNS lookups are sent unencrypted, so the network can see and alter which sites you visit.",
                    assurance="verified_condition", location="Local State")


def _firefox(ctx, text):
    prefs = {}
    for match in re.finditer(r'user_pref\(\s*"([^"]+)"\s*,\s*(true|false|-?\d+|"(?:[^"\\]|\\.)*")\s*\)', text):
        raw = match.group(2)
        prefs[match.group(1)] = True if raw == "true" else False if raw == "false" else int(raw) if raw.lstrip("-").isdigit() else raw.strip('"')
    if not prefs and "user_pref" not in text:
        raise ToolInputError("firefox_prefs contains no user_pref(...) lines.")
    for key, (bad, severity, title) in FIREFOX_CHECKS.items():
        if key in prefs and bad(prefs[key]):
            ctx.finding(f"firefox.{key}", title, severity, f"{key} = {prefs[key]}",
                        assurance="verified_condition" if severity != "info" else "informational", location="prefs.js")
    ctx.artifacts["firefox_prefs_set"] = len(prefs)


def _local_files():
    found = {}
    local = os.environ.get("LOCALAPPDATA")
    candidates = []
    if local:
        candidates += [Path(local) / p for p in ("Google/Chrome/User Data", "Microsoft/Edge/User Data", "BraveSoftware/Brave-Browser/User Data")]
    candidates += [Path.home() / ".config" / p for p in ("google-chrome", "chromium", "microsoft-edge")]
    for root in candidates:
        if (root / "Default/Preferences").is_file():
            found.setdefault("chromium", []).append(root)
    firefox_roots = [Path(os.environ.get("APPDATA", "")) / "Mozilla/Firefox/Profiles", Path.home() / ".mozilla/firefox"]
    for root in firefox_roots:
        if root.is_dir():
            found.setdefault("firefox", []).extend(sorted(root.glob("*/prefs.js"))[:5])
    return found


def _analyze(ctx, data):
    analysed = 0
    if data.get("source") == "local":
        ctx.input_kind = "local"
        found = _local_files()
        for root in found.get("chromium", []):
            ctx.check()
            _chromium(ctx, (root / "Default/Preferences").read_text(encoding="utf-8", errors="replace"), f"{root.parent.name}/{root.name} Preferences")
            if (root / "Local State").is_file():
                _local_state(ctx, (root / "Local State").read_text(encoding="utf-8", errors="replace"))
            analysed += 1
        for prefs in found.get("firefox", []):
            _firefox(ctx, prefs.read_text(encoding="utf-8", errors="replace"))
            analysed += 1
        if not analysed:
            ctx.limit("No Chromium or Firefox profile was found for this user.")
            return
    else:
        ctx.input_kind, ctx.execution_mode = "provided", "local"
        if data.get("chromium_preferences"):
            _chromium(ctx, data["chromium_preferences"], "Preferences")
            analysed += 1
        if data.get("chromium_local_state"):
            _local_state(ctx, data["chromium_local_state"])
            analysed += 1
        if data.get("firefox_prefs"):
            _firefox(ctx, data["firefox_prefs"])
            analysed += 1
        if not analysed:
            raise ToolInputError("Provide chromium_preferences, chromium_local_state, firefox_prefs or source='local'.")
    ctx.limit("Enterprise policies (registry/plist) can override these files and are not read.")



def _load_toolkit():
    digest = hashlib.sha256()
    for path in sorted((_TOOLS_ROOT / "security_toolkit").glob("*.py")):
        digest.update(path.name.encode("utf-8") + b"\0" + path.read_bytes() + b"\0")
    if digest.hexdigest() != TOOLKIT_SHA256:
        raise ImportError("security_toolkit differs from the version this tool was approved with.")
    if str(_TOOLS_ROOT) not in sys.path:
        sys.path.insert(0, str(_TOOLS_ROOT))



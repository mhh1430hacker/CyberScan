from security_toolkit import secrets_kit  # noqa: E402
from security_toolkit.core import run_tool, text_or_bytes  # noqa: E402

CREDENTIAL_CATEGORIES = {"credential", "private_key"}


def _analyze(ctx, data):
    text = text_or_bytes(data, max_bytes=20_000_000)
    ctx.input_kind = "text"
    path = data.get("path") or "input"
    items = [s for s in secrets_kit.scan(text) if s["category"] in CREDENTIAL_CATEGORIES]
    ignored = 0
    for item in items:
        if item["placeholder"]:
            ignored += 1
            continue
        private = item["category"] == "private_key"
        ctx.finding(f"credential.{item['type']}", f"{item['label']} exposed", "critical" if private else item["severity"],
                    f"Found at line {item['line']}. " + ("A private key lets anyone impersonate its owner; replace the key pair and revoke "
                                                         "the old public key/certificate." if private else
                                                         "Change this password everywhere it is used and remove it from the file."),
                    location=f"{path}:{item['line']}", recommendation="Rotate it; keep credentials in a secret manager, not in files.")
        ctx.evidence("masked_secret", f"{item['label']}: {item['masked']}", finding_id=f"credential.{item['type']}",
                     location=f"{path}:{item['line']}")
    ctx.artifacts.update({"credentials": len(items) - ignored, "placeholders_ignored": ignored})
    ctx.limit("Weak or low-entropy hard-coded passwords (e.g. 'password=admin') are only caught by the explicit formats listed.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)

LEVELS = ["public", "internal", "confidential", "restricted"]
MARKINGS = [
    (3, re.compile(r"(?i)\b(?:top secret|strictly confidential|highly confidential|restricted(?: data| use)?|secret//)\b|سري للغاية|سري جدا")),
    (2, re.compile(r"(?i)\b(?:confidential|privileged (?:and|&) confidential|attorney[- ]client privilege|not for (?:distribution|release))\b|(?<!\w)سري(?!\w)|خاص وسري")),
    (1, re.compile(r"(?i)\b(?:internal (?:use )?only|for internal use|company internal|do not forward|proprietary)\b|للاستخدام الداخلي|داخلي فقط")),
]
# category -> (level it implies, severity, patterns needing >= min_hits distinct matches)
CATEGORIES = {
    "health": (3, "high", 2, [r"(?i)\b(?:diagnos(?:is|ed)|patient|medical record|prescription|ICD-?10|HIV|oncology|psychiatric|blood type|allerg(?:y|ies))\b",
                              r"\b[A-TV-Z][0-9]{2}\.[0-9A-Z]{1,4}\b(?=.{0,40}(?i:diagnos|icd|code))", r"تشخيص|مريض|سجل طبي|وصفة طبية"]),
    "financial": (2, "medium", 2, [r"(?i)\b(?:account number|routing number|sort code|swift|bic|iban|credit limit|bank statement|wire transfer)\b",
                                   r"\b[A-Z]{4}[A-Z]{2}[A-Z0-9]{2}(?:[A-Z0-9]{3})?\b(?=.{0,30}(?i:swift|bic))", r"رقم الحساب|كشف حساب|حوالة"]),
    "hr": (2, "medium", 2, [r"(?i)\b(?:salary|compensation|bonus|performance review|disciplinary|termination|severance|background check|payroll)\b",
                            r"راتب|مكافأة|تقييم الأداء|إنهاء الخدمة"]),
    "legal": (2, "medium", 1, [r"(?i)\b(?:attorney[- ]client|legal hold|litigation|settlement agreement|under nda|non-disclosure agreement|without prejudice)\b"]),
}


def _analyze(ctx, data):
    text = text_or_bytes(data, max_bytes=20_000_000)
    ctx.input_kind = "text"
    level, reasons = 0, []
    for marking_level, pattern in MARKINGS:
        match = pattern.search(text)
        if match:
            line = line_of(text, match.start())
            ctx.finding(f"marking.{LEVELS[marking_level]}", f"Document is marked '{match.group(0).strip()}'",
                        "medium" if marking_level >= 2 else "low",
                        "An explicit classification marking restricts who may receive this document.",
                        assurance="verified_condition", location=f"line {line}")
            if marking_level > level:
                level = marking_level
            reasons.append(f"marking '{match.group(0).strip()}'")
            break
    for category, (implied, severity, min_hits, patterns) in CATEGORIES.items():
        ctx.check()
        hits = set()
        first = None
        for pattern in patterns:
            for match in re.finditer(pattern, text):
                hits.add(match.group(0).lower())
                first = first if first is not None else match.start()
        if len(hits) >= min_hits:
            ctx.finding(f"category.{category}", f"{category.upper() if category == 'hr' else category.capitalize()} information", severity,
                        f"{len(hits)} distinct {category} indicator(s), e.g. '{sorted(hits)[0]}'.", location=f"line {line_of(text, first)}")
            level = max(level, implied)
            reasons.append(category)
    personal = pii.summarize(pii.find(text))
    if personal:
        identifiers = {k: v for k, v in personal.items() if k in ("payment_card", "us_ssn", "saudi_id", "uk_nino", "passport", "iban")}
        ctx.finding("category.personal-data", f"Personal data ({sum(personal.values())} item(s))",
                    "high" if identifiers else "low", f"Kinds: {', '.join(f'{k} x{v}' for k, v in personal.items())}. Use tool 072 for details.",
                    location="document")
        level = max(level, 3 if identifiers else 1)
        reasons.append("personal data")
    secrets = [s for s in secrets_kit.scan(text) if not s["placeholder"]]
    if secrets:
        ctx.finding("category.credentials", f"Credentials or keys ({len(secrets)})", "high",
                    "The document contains secrets; use tools 074/075 for details and rotate them.", location="document")
        level = 3
        reasons.append("credentials")
    ctx.artifacts.update({"sensitivity": LEVELS[level], "reasons": reasons})
    ctx.summary = f"Sensitivity: {LEVELS[level]}" + (f" ({', '.join(reasons)})." if reasons else " (no markings or sensitive categories).")
    ctx.limit("Keyword categories are heuristic; a human should confirm the classification before acting on it.")



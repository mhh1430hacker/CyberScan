def _load_toolkit():
    digest = hashlib.sha256()
    for path in sorted((_TOOLS_ROOT / "security_toolkit").glob("*.py")):
        digest.update(path.name.encode("utf-8") + b"\0" + path.read_bytes() + b"\0")
    if digest.hexdigest() != TOOLKIT_SHA256:
        raise ImportError("security_toolkit differs from the version this tool was approved with.")
    if str(_TOOLS_ROOT) not in sys.path:
        sys.path.insert(0, str(_TOOLS_ROOT))


_load_toolkit()
from security_toolkit import secrets_kit  # noqa: E402
from security_toolkit.core import run_tool, text_or_bytes  # noqa: E402

KEY_CATEGORIES = {"api_key", "webhook"}


def _analyze(ctx, data):
    text = text_or_bytes(data, max_bytes=20_000_000)
    ctx.input_kind = "text"
    path = data.get("path") or "input"
    items = [s for s in secrets_kit.scan(text) if s["category"] in KEY_CATEGORIES]
    placeholders = 0
    for item in items:
        if item["placeholder"]:
            placeholders += 1
            continue
        ctx.finding(f"key.{item['type']}", f"{item['label']} exposed", item["severity"],
                    f"A value matching the {item['label']} format appears at line {item['line']}. Treat it as compromised if real: "
                    "revoke it at the provider and check its usage logs.", location=f"{path}:{item['line']}",
                    recommendation="Revoke and rotate; move secrets to a secret manager or environment variables.")
        ctx.evidence("masked_secret", f"{item['label']}: {item['masked']} (fingerprint {item['fingerprint']})",
                     finding_id=f"key.{item['type']}", location=f"{path}:{item['line']}")
    ctx.artifacts.update({"keys": len(items) - placeholders, "placeholders_ignored": placeholders,
                          "fingerprints": sorted({i["fingerprint"] for i in items if not i["placeholder"]})[:200]})
    ctx.limit("Matches are format-based; whether a key is live can only be confirmed by its provider, which this tool never contacts.")


def run(input_data, options=None):
    return run_tool(tool_id=TOOL_ID, version=VERSION, execution_mode="local", timeout_seconds=TIMEOUT_SECONDS,
                    input_data=input_data, options=options, analyze=_analyze)
